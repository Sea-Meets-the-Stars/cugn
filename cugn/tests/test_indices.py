def test_sea_level_anomaly_recovers_cycle_and_trend():
    """ A planted seasonal cycle + trend + spike is recovered.

    Generated by JXP and Claude
    """
    time = pd.date_range('1991-01-15', '2025-12-15', freq='MS') + pd.Timedelta(days=14)
    n = len(time)
    tyr = time.year + (time.dayofyear - 0.5) / 365.25
    rate = 0.003  # 3 mm/yr
    cycle = 0.08 * np.sin(2 * np.pi * (time.month - 1) / 12.)
    planted = np.zeros(n)
    idx = np.where((time.year == 2015) & (time.month.isin([10, 11, 12])))[0]
    planted[idx] = 0.15   # El Nino sea-level high
    msl = 0.02 + rate * (tyr - 2005.5) + cycle + planted
    df = pd.DataFrame({'time': time, 'msl': msl})

    out = indices.sea_level_anomaly(df, clim_years=(1991, 2020), detrend=True)
    assert {'clim', 'trend', 'anom'} <= set(out.columns)
    # Trend rate recovered (small bias from the planted spike is allowed)
    assert out.attrs['trend_mm_per_yr'] == pytest.approx(3.0, abs=0.15)
    # Anomaly ~0 outside the spike, ~0.15 inside
    mask = np.ones(n, bool)
    mask[idx] = False
    assert np.nanmax(np.abs(out['anom'].to_numpy()[mask])) < 0.02
    np.testing.assert_allclose(out['anom'].to_numpy()[idx], 0.15, atol=0.02)
    # Climatology reproduces the seasonal cycle shape (to within a constant)
    c = out['clim'].to_numpy()
    assert np.std(c - cycle) < 0.01
    # detrend=False gives zero trend and a trend-contaminated anomaly
    out2 = indices.sea_level_anomaly(df, detrend=False)
    assert np.all(out2['trend'] == 0.)
    assert out2['anom'].iloc[-1] - out2['anom'].iloc[0] > 0.05


def test_sea_level_anomaly_with_gaps():
    """ NaN months are tolerated and stay NaN in the anomaly.

    Generated by JXP and Claude
    """
    time = pd.date_range('2000-01-15', periods=240, freq='MS') + pd.Timedelta(days=14)
    msl = 0.1 * np.cos(2 * np.pi * time.month / 12.) + 0.001 * np.arange(240)
    msl = np.asarray(msl, float)
    msl[50:55] = np.nan
    out = indices.sea_level_anomaly(pd.DataFrame({'time': time, 'msl': msl}),
                                    clim_years=(2000, 2019))
    assert np.all(np.isnan(out['anom'].iloc[50:55]))
    assert np.isfinite(out['anom'].drop(out.index[50:55])).all()


