def test_line_temperature_index_planted_anomaly():
    """ Upper-100 m / inshore-200 km mean with 9-point smoothing.

    Generated by JXP and Claude
    """
    time = pd.date_range('2014-01-01', periods=120, freq='10D')
    depth = np.arange(10, 501, 10.)            # 10..500 m
    distance = np.arange(0, 501, 10.)          # 0..500 km
    data = np.zeros((len(time), len(depth), len(distance)))
    # Deep and offshore cells carry a large signal that must be excluded
    data[:, depth > 100, :] = 10.
    data[:, :, distance > 200] = -10.
    # Planted warm event in the upper 100 m / inshore 200 km, samples 40..79
    data[40:80, depth <= 100, :][:, :, distance <= 200] = 0.  # (no-op, clarity)
    inz = depth <= 100.
    inx = distance <= 200.
    for k in range(40, 80):
        data[k][np.ix_(inz, inx)] = 2.0
    # A NaN hole inside the box should be ignored
    data[50, 0, 0] = np.nan
    anom = xr.DataArray(data, dims=('time', 'depth', 'distance'),
                        coords=dict(time=time, depth=depth, distance=distance))

    idx = indices.line_temperature_index(anom, zmax=100., xmax=200., nsmooth=9)
    assert isinstance(idx, pd.Series)
    assert len(idx) == len(time)
    assert (idx.index == time).all()
    # Fully inside the event and away from its edges: exactly 2.0
    np.testing.assert_allclose(idx.iloc[45:75], 2.0)
    # Well outside: exactly 0
    np.testing.assert_allclose(idx.iloc[5:35], 0.0)
    # Smoothing ramps the edges over 9 samples
    assert 0. < idx.iloc[40] < 2.
    assert idx.iloc[44] == pytest.approx(2.0)
    # nsmooth=1 reproduces the unsmoothed box mean
    raw = indices.line_temperature_index(anom, nsmooth=1)
    np.testing.assert_allclose(raw.iloc[40:80], 2.0)
    np.testing.assert_allclose(raw.iloc[:40], 0.0)


