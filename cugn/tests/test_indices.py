def test_upwelling_anomaly_synthetic():
    """ Smoothed day-of-year climatology removes a planted seasonal cycle.

    Generated by JXP and Claude
    """
    time = pd.date_range('1988-01-01', '2024-12-31', freq='D')
    doy = time.dayofyear.to_numpy()
    cycle = 1.0 + 0.8 * np.sin(2 * np.pi * (doy - 100) / 365.25)
    rng = np.random.default_rng(0)
    noise = rng.normal(0., 0.3, len(time))
    value = cycle + noise
    # Planted anomaly: a strong 60-day upwelling burst in spring 2021
    burst = (time >= '2021-04-01') & (time < '2021-05-31')
    value[burst] += 2.0
    df = pd.DataFrame({'time': time, 'value': value})

    out = indices.upwelling_anomaly(df, clim_years=(1991, 2020), smooth_days=31)
    assert {'clim', 'anom'} <= set(out.columns)
    assert len(out) == len(df)
    # Climatology tracks the true cycle closely (noise averaged over 30 yrs x 31 d)
    assert np.nanmax(np.abs(out['clim'].to_numpy() - cycle)) < 0.1
    # Climatology is continuous across the year boundary
    dec31 = out.loc[out.time == '2000-12-31', 'clim'].iloc[0]
    jan01 = out.loc[out.time == '2001-01-01', 'clim'].iloc[0]
    assert abs(dec31 - jan01) < 0.05
    # Planted burst recovered, background anomaly ~ zero-mean
    assert out.loc[burst, 'anom'].mean() == pytest.approx(2.0, abs=0.15)
    assert abs(out.loc[~burst, 'anom'].mean()) < 0.02
    # Leap day handled (Feb 29 gets a finite climatology)
    assert np.isfinite(out.loc[out.time == '2000-02-29', 'clim'].iloc[0])


