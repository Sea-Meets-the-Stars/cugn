def test_running_mean_interior_and_edges():
    """ Interior values are exact 3-point means; edges use truncated windows.

    Generated by JXP and Claude
    """
    y = np.arange(10, dtype=float)
    rm = indices.running_mean(y, 3)
    assert len(rm) == 10
    # Interior: mean of (i-1, i, i+1) = i
    np.testing.assert_allclose(rm[1:-1], y[1:-1])
    # Edges: 2-point truncated windows (min_periods = max(1, 3//2) = 1)
    assert rm[0] == pytest.approx(0.5)
    assert rm[-1] == pytest.approx(8.5)


def test_running_mean_nan_handling():
    """ NaNs are skipped inside the window and do not poison neighbours.

    Generated by JXP and Claude
    """
    y = np.array([1., 2., np.nan, 4., 5.])
    rm = indices.running_mean(y, 3)
    assert rm[1] == pytest.approx(1.5)       # mean(1, 2), NaN skipped
    assert rm[2] == pytest.approx(3.0)       # mean(2, 4)
    assert rm[3] == pytest.approx(4.5)       # mean(4, 5)
    # A window with too few valid points returns NaN (n=9 -> min 4 points).
    y2 = np.full(20, np.nan)
    y2[10] = 1.
    rm2 = indices.running_mean(y2, 9)
    assert np.all(np.isnan(rm2))
    # Constant series is unchanged by smoothing.
    np.testing.assert_allclose(indices.running_mean(np.ones(30), 9), 1.)


