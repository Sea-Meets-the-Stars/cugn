""" Tests for cugn.oisst using synthetic data only (no network, no disk data).

Generated by JXP and Claude
"""

import numpy as np
import pandas as pd
import xarray as xr
import pytest

from cugn import oisst


def _synthetic_series(seed=0, sigma=0.3):
    """Daily SST 1991-2022: seasonal cycle + Gaussian noise, with planted spikes.

    Spikes (noise zeroed within +/-5 days of each so durations are exact):
      * +3 C for 10 days, 2021-07-01..2021-07-10   -> Extreme MHW, 10 days
      * +3 C for 3 days,  2021-10-01..2021-10-03   -> too short, no MHW
      * +3 C 6 days, 2 day gap, +3 C 6 days from 2022-03-01 -> joined, 14 days

    Returns
    -------
    pandas.Series

    Generated by JXP and Claude
    """
    rng = np.random.default_rng(seed)
    idx = pd.date_range('1991-01-01', '2022-12-31', freq='D')
    doy = idx.dayofyear.values
    seasonal = 14. + 3. * np.sin(2 * np.pi * (doy - 100) / 365.25)
    noise = rng.normal(0., sigma, idx.size)
    ser = pd.Series(seasonal, index=idx)

    def quiet(t0, t1, pad=5):
        # Remove noise in a buffer around the planted event
        sel = (idx >= pd.Timestamp(t0) - pd.Timedelta(days=pad)) & \
              (idx <= pd.Timestamp(t1) + pd.Timedelta(days=pad))
        noise[sel] = 0.

    quiet('2021-07-01', '2021-07-10')
    quiet('2021-10-01', '2021-10-03')
    quiet('2022-03-01', '2022-03-14')
    ser = ser + noise
    ser['2021-07-01':'2021-07-10'] += 3.
    ser['2021-10-01':'2021-10-03'] += 3.
    ser['2022-03-01':'2022-03-06'] += 3.
    ser['2022-03-09':'2022-03-14'] += 3.
    return ser


def test_hobday_mhw_detects_planted_spike():
    ser = _synthetic_series()
    out = oisst.hobday_mhw(ser, clim_years=(1991, 2020))
    daily, events = out['daily'], out['events']
    # Daily frame covers every day with the expected columns
    for col in ['sst', 'clim', 'thresh', 'anom', 'is_mhw', 'category']:
        assert col in daily.columns
    assert daily.index.size == ser.size
    # Threshold sits above the climatology everywhere
    assert (daily['thresh'] > daily['clim']).all()
    # The 10-day spike is one event with exact duration and Extreme category
    ev = events[(events.start >= '2021-06-01') & (events.start <= '2021-08-01')]
    assert len(ev) == 1
    ev = ev.iloc[0]
    assert ev.start == pd.Timestamp('2021-07-01')
    assert ev.end == pd.Timestamp('2021-07-10')
    assert ev.duration_days == 10
    assert ev.category == 4 and ev.category_label == 'Extreme'
    assert abs(ev.max_intensity - 3.) < 0.3
    assert daily.loc['2021-07-05', 'is_mhw']
    assert daily.loc['2021-07-05', 'category'] == 4


def test_hobday_mhw_ignores_short_spike():
    ser = _synthetic_series()
    out = oisst.hobday_mhw(ser, clim_years=(1991, 2020))
    events = out['events']
    ev = events[(events.start >= '2021-09-20') & (events.start <= '2021-10-15')]
    assert len(ev) == 0
    assert not out['daily'].loc['2021-10-02', 'is_mhw']


def test_hobday_mhw_joins_short_gap():
    ser = _synthetic_series()
    out = oisst.hobday_mhw(ser, clim_years=(1991, 2020), max_gap=2)
    events = out['events']
    ev = events[(events.start >= '2022-02-20') & (events.start <= '2022-03-20')]
    assert len(ev) == 1
    assert ev.iloc[0].duration_days == 14
    # Gap days are part of the event but not categorised above 0 necessarily
    assert out['daily'].loc['2022-03-07', 'is_mhw']
    # Without joining, we get two separate 6-day events
    out2 = oisst.hobday_mhw(ser, clim_years=(1991, 2020), max_gap=0)
    ev2 = out2['events']
    ev2 = ev2[(ev2.start >= '2022-02-20') & (ev2.start <= '2022-03-20')]
    assert len(ev2) == 2
    assert (ev2.duration_days == 6).all()


