def _synthetic_dataset():
    """Small (time, lat, lon) dataset: sst = 10 at lat 0, 20 at lat 60.

    Generated by JXP and Claude
    """
    time = pd.date_range('2020-01-01', periods=3, freq='D')
    lat = np.array([0., 60.], dtype=np.float32)
    lon = np.array([-122.5, -122.0], dtype=np.float32)
    sst = np.zeros((time.size, lat.size, lon.size), dtype=np.float32)
    sst[:, 0, :] = 10.
    sst[:, 1, :] = 20.
    return xr.Dataset({'sst': (('time', 'lat', 'lon'), sst)},
                      coords={'time': time, 'lat': lat, 'lon': lon})


def test_box_mean_cos_weighting():
    ds = _synthetic_dataset()
    ser = oisst.box_mean(ds, (-1., 61.), (-123., -121.), var='sst')
    # weights cos(0)=1, cos(60)=0.5 -> (10*1 + 20*0.5)/1.5 = 13.333
    assert isinstance(ser, pd.Series)
    assert ser.size == 3
    np.testing.assert_allclose(ser.values, 40. / 3., rtol=1e-5)
    # Unweighted mean would be 15; make sure we are not returning that
    assert abs(ser.iloc[0] - 15.) > 1.


def test_box_mean_ignores_nan():
    ds = _synthetic_dataset()
    ds['sst'][:, 1, 0] = np.nan          # one cell at lat 60 is land
    ser = oisst.box_mean(ds, (-1., 61.), (-123., -121.), var='sst')
    # Remaining: lat0 (2 cells, w=1 each) and lat60 (1 cell, w=0.5)
    np.testing.assert_allclose(ser.values, (10 * 2 + 20 * 0.5) / 2.5, rtol=1e-5)


def test_subset_global_lon_conversion():
    # Global 0.25 degree grid in 0..360 with sst encoding the longitude
    lon = np.arange(0.125, 360., 0.25, dtype=np.float32)
    lat = np.arange(-89.875, 90., 0.25, dtype=np.float32)
    time = pd.date_range('2026-08-20', periods=1)
    sst = np.broadcast_to(lon[None, None, None, :],
                          (1, 1, lat.size, lon.size)).astype(np.float32)
    ds = xr.Dataset({'sst': (('time', 'zlev', 'lat', 'lon'), sst.copy())},
                    coords={'time': time, 'zlev': [0.], 'lat': lat, 'lon': lon})
    sub = oisst.subset_global(ds, (25., 50.), (-135., -115.))
    assert sub.lon.min() >= -135. and sub.lon.max() <= -115.
    assert sub.lat.min() >= 25. and sub.lat.max() <= 50.
    assert sub.lon.size == 80 and sub.lat.size == 100
    assert np.all(np.diff(sub.lon.values) > 0)
    # Values still carry the original 0..360 longitude: lon_new + 360
    np.testing.assert_allclose(sub.sst.isel(time=0, zlev=0, lat=0).values,
                               sub.lon.values + 360., rtol=1e-6)
    # The canonical grid snap accepts this subset
    std = oisst._standardize(sub)
    snapped = oisst._snap_to_grid(std)
    clat, clon = oisst.canonical_grid()
    np.testing.assert_array_equal(snapped.lat.values, clat)
    np.testing.assert_array_equal(snapped.lon.values, clon)
    assert 'zlev' not in snapped.dims
    assert bool(snapped.preliminary.values.any()) is False


def test_latest_anomaly_map_synthetic():
    # Constant field -> zero anomaly; baseline 2 years, recent 7 days
    time = pd.date_range('2019-01-01', '2021-01-10', freq='D')
    lat = np.array([30.125, 30.375], dtype=np.float32)
    lon = np.array([-130.125, -129.875], dtype=np.float32)
    sst = np.full((time.size, 2, 2), 15., dtype=np.float32)
    sst[-7:] += 2.                       # last week is 2 C warm
    ds = xr.Dataset({'sst': (('time', 'lat', 'lon'), sst)},
                    coords={'time': time, 'lat': lat, 'lon': lon})
    anom = oisst.latest_anomaly_map(ds, ndays=7, clim_years=(2019, 2020))
    assert anom.dims == ('lat', 'lon')
    np.testing.assert_allclose(anom.values, 2., atol=1e-5)
    assert anom.attrs['end'] == '2021-01-10'
