""" Anomalies, gridding and isopycnal views for CUGN binned profiles.

Decomposition used throughout (Rudnick et al. 2017):

    observation = seasonal climatology (mean + harmonics) + anomaly

The seasonal climatology comes from `cugn.annualcycle.fit_annual_cycle`; this
module subtracts it profile by profile, bins the anomalies onto a regular
(time, depth, distance) grid without objective mapping, interpolates onto
potential-density surfaces with TEOS-10 (`gsw`), and identifies the latest
complete transect of a mission.

Generated by JXP and Claude
"""
import numpy as np
import pandas as pd
import xarray as xr
import gsw

from cugn import annualcycle

SIGMA_LEVELS = np.arange(25.0, 27.0 + 0.001, 0.1)


def profile_anomalies(ds, A, var):
    """ Subtract the fitted seasonal climatology from every profile.

    Parameters
    ----------
    ds : xarray.Dataset
        Dims (profile, depth) with coords `time`, `dist` and variable `var`.
    A : xarray.Dataset
        Fit from `cugn.annualcycle.fit_annual_cycle` for `var`.
    var : str

    Returns
    -------
    xarray.Dataset : copy of `ds` with `<var>_clim` and `<var>_anom` added.

    Generated by JXP and Claude
    """
    clim = annualcycle.evaluate_annual_cycle(A, ds.time.values, ds.dist.values)
    out = ds.copy()
    out[f'{var}_clim'] = (('profile', 'depth'), clim)
    out[f'{var}_anom'] = out[var] - out[f'{var}_clim']
    out[f'{var}_anom'].attrs.update(base_years=str(A.attrs['base_years']))
    return out


def grid_profiles(ds, var, dt_days=10, dx_km=5., xmax=400., t0='2007-01-01',
                  t1=None, max_offset=None):
    """ Bin-average a (profile, depth) variable onto a (time, depth, distance)
    grid by simple averaging (no objective mapping).

    Parameters
    ----------
    ds : xarray.Dataset
        Dims (profile, depth) with coords `time`, `dist`, `offset`.
    var : str
        Variable (e.g. 'temperature_anom').
    dt_days : int
        Time bin width (10 days, as the CUGN products).
    dx_km : float
        Cross-shore bin width; centres at 0, 5, ... `xmax`.
    xmax : float
        Last bin centre (km).
    t0, t1 : str or None
        Grid start and end (end defaults to the last profile time).
    max_offset : float or None
        Drop profiles farther than this (km) from the line.

    Returns
    -------
    xarray.Dataset with `<var>` (time, depth, distance) bin means and `count`
    (time, distance) profile counts; `time` is the bin centre.

    Generated by JXP and Claude
    """
    t = pd.to_datetime(ds.time.values)
    t1 = t.max() if t1 is None else pd.Timestamp(t1)
    tedges = pd.date_range(pd.Timestamp(t0), t1 + pd.Timedelta(days=dt_days),
                           freq=f'{dt_days}D')
    xedges = np.arange(-dx_km / 2, xmax + dx_km, dx_km)
    xcent = 0.5 * (xedges[:-1] + xedges[1:])
    vals = ds[var].transpose('profile', 'depth').values
    dist = ds.dist.values
    keep = np.isfinite(dist) & (t >= tedges[0]) & (t < tedges[-1])
    if max_offset is not None:
        keep &= np.abs(ds.offset.values) <= max_offset
    it = np.searchsorted(tedges, t[keep], side='right') - 1
    ix = np.searchsorted(xedges, dist[keep], side='right') - 1
    inx = (ix >= 0) & (ix < xcent.size)
    it, ix, v = it[inx], ix[inx], vals[keep][inx]
    nt, nz, nx = tedges.size - 1, ds.sizes['depth'], xcent.size
    ssum = np.zeros((nt, nz, nx))
    cnt = np.zeros((nt, nz, nx))
    good = np.isfinite(v)
    # Accumulate sums and counts per (time, distance) cell for every depth.
    for l in range(nz):
        g = good[:, l]
        np.add.at(ssum[:, l, :], (it[g], ix[g]), v[g, l])
        np.add.at(cnt[:, l, :], (it[g], ix[g]), 1)
    with np.errstate(invalid='ignore', divide='ignore'):
        mean = np.where(cnt > 0, ssum / cnt, np.nan)
    nprof = np.zeros((nt, nx))
    np.add.at(nprof, (it, ix), 1)
    tcent = tedges[:-1] + pd.Timedelta(days=dt_days / 2)
    out = xr.Dataset({var: (('time', 'depth', 'distance'), mean),
                      'count': (('time', 'distance'), nprof)},
                     coords=dict(time=tcent, depth=ds.depth.values, distance=xcent))
    out.attrs.update(dt_days=dt_days, dx_km=dx_km, method='bin average, no OI')
    return out


def add_sigma0(ds, lon_name='lon', lat_name='lat'):
    """ Add TEOS-10 potential density anomaly sigma0 (kg m-3) to binned profiles.

    Parameters
    ----------
    ds : xarray.Dataset
        Dims (profile, depth) with `temperature` (in situ, ITS-90), `salinity`
        (practical), and per-profile `lon`, `lat`.

    Returns
    -------
    xarray.Dataset : copy with `sigma0` (profile, depth).

    Generated by JXP and Claude
    """
    z = ds.depth.values[None, :] * np.ones((ds.sizes['profile'], 1))
    lat = ds[lat_name].values[:, None] * np.ones_like(z)
    lon = ds[lon_name].values[:, None] * np.ones_like(z)
    p = gsw.p_from_z(-z, lat)
    SA = gsw.SA_from_SP(ds['salinity'].transpose('profile', 'depth').values, p, lon, lat)
    CT = gsw.CT_from_t(SA, ds['temperature'].transpose('profile', 'depth').values, p)
    out = ds.copy()
    out['sigma0'] = (('profile', 'depth'), gsw.sigma0(SA, CT))
    out['sigma0'].attrs.update(units='kg m-3', note='TEOS-10 (gsw), referenced to 0 dbar')
    return out


def to_isopycnals(ds, var, sigma_levels=SIGMA_LEVELS):
    """ Interpolate a (profile, depth) variable onto potential-density surfaces.

    Parameters
    ----------
    ds : xarray.Dataset
        Must contain `sigma0` (see `add_sigma0`) and `var`.
    var : str
    sigma_levels : array-like
        Target sigma0 surfaces (default 25.0..27.0 by 0.1, as the CUGN products).

    Returns
    -------
    xarray.Dataset with `<var>` and `depth_of_sigma` on dims (profile, sigma);
    NaN where a surface is not bracketed by the profile.

    Generated by JXP and Claude
    """
    sig = ds['sigma0'].transpose('profile', 'depth').values
    val = ds[var].transpose('profile', 'depth').values
    z = ds.depth.values
    n = sig.shape[0]
    out = np.full((n, len(sigma_levels)), np.nan)
    zout = np.full_like(out, np.nan)
    for i in range(n):
        ok = np.isfinite(sig[i]) & np.isfinite(val[i])
        if ok.sum() < 3:
            continue
        s, v, zz = sig[i, ok], val[i, ok], z[ok]
        # Enforce monotonic density with depth (drop inversions) for np.interp.
        s_mono = np.maximum.accumulate(s)
        keep = np.r_[True, np.diff(s_mono) > 0]
        s_mono, v, zz = s_mono[keep], v[keep], zz[keep]
        inside = (sigma_levels >= s_mono[0]) & (sigma_levels <= s_mono[-1])
        out[i, inside] = np.interp(sigma_levels[inside], s_mono, v)
        zout[i, inside] = np.interp(sigma_levels[inside], s_mono, zz)
    res = xr.Dataset({var: (('profile', 'sigma'), out),
                      'depth_of_sigma': (('profile', 'sigma'), zout)},
                     coords=dict(profile=ds.profile.values, sigma=np.asarray(sigma_levels),
                                 time=('profile', ds.time.values),
                                 dist=('profile', ds.dist.values),
                                 offset=('profile', ds.offset.values)))
    return res


def find_transects(ds, min_span_frac=0.6, smooth=5, end_frac=0.15):
    """ Split a mission into inshore<->offshore legs from its distance record.

    Parameters
    ----------
    ds : xarray.Dataset
        Dims (profile, ...) sorted by time with coord `dist` (km).
    min_span_frac : float
        A leg counts as complete if its distance span is at least this fraction
        of the mission's overall (max - min) distance.
    smooth : int
        Running-median window (profiles) used before finding turning points.
    end_frac : float
        A leg is complete only if it also ends within this fraction of the
        mission's distance range from the inshore or offshore end, so a leg
        still under way (the glider mid-line) is not called complete.

    Returns
    -------
    pandas.DataFrame with one row per leg: i0, i1 (profile index range,
    inclusive), t0, t1, tmid, dist0, dist1, direction ('offshore'/'inshore'),
    complete (bool).

    Generated by JXP and Claude
    """
    cols = ['i0', 'i1', 't0', 't1', 'tmid', 'dist0', 'dist1', 'direction', 'complete']
    if ds.sizes['profile'] < 3:
        return pd.DataFrame(columns=cols)
    d = pd.Series(ds.dist.values).rolling(smooth, center=True, min_periods=1).median().to_numpy()
    sign = np.sign(np.diff(d))
    sign[sign == 0] = np.nan
    sign = pd.Series(sign).ffill().bfill().to_numpy()
    turns = np.where(np.diff(sign) != 0)[0] + 1
    bounds = np.r_[0, turns, d.size - 1]
    dmin, dmax = np.nanmin(d), np.nanmax(d)
    span = dmax - dmin
    t = pd.to_datetime(ds.time.values)
    rows = []
    for a, b in zip(bounds[:-1], bounds[1:]):
        if b <= a:
            continue
        rows.append(dict(i0=int(a), i1=int(b), t0=t[a], t1=t[b], tmid=t[a] + (t[b] - t[a]) / 2,
                         dist0=float(d[a]), dist1=float(d[b]),
                         direction='offshore' if d[b] > d[a] else 'inshore',
                         complete=(abs(d[b] - d[a]) >= min_span_frac * span) and
                                  (min(d[b] - dmin, dmax - d[b]) <= end_frac * span)))
    return pd.DataFrame(rows)


def section_from_profiles(ds, var, dx_km=5., xmax=400.):
    """ Bin a set of profiles into a (depth, distance) section.

    Parameters
    ----------
    ds : xarray.Dataset
        Dims (profile, depth) with coord `dist`; e.g. one transect.
    var : str
    dx_km, xmax : float
        Cross-shore bin width and last bin centre (km).

    Returns
    -------
    xarray.DataArray (depth, distance) of bin means.

    Generated by JXP and Claude
    """
    xedges = np.arange(-dx_km / 2, xmax + dx_km, dx_km)
    xcent = 0.5 * (xedges[:-1] + xedges[1:])
    ix = np.searchsorted(xedges, ds.dist.values, side='right') - 1
    vals = ds[var].transpose('profile', 'depth').values
    out = np.full((ds.sizes['depth'], xcent.size), np.nan)
    for j in range(xcent.size):
        sel = ix == j
        if sel.any():
            with np.errstate(invalid='ignore'):
                out[:, j] = np.nanmean(vals[sel], axis=0)
    return xr.DataArray(out, dims=('depth', 'distance'),
                        coords=dict(depth=ds.depth.values, distance=xcent), name=var)
