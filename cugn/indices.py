def _coops_request(params):
    """ One CO-OPS datagetter call returning the CSV text ('' if no data).

    Inputs
    ------
    params : dict
        Query parameters (product, station, begin_date, ...).

    Outputs
    -------
    str : CSV text, or '' when the API reports an error / no data.

    Generated by JXP and Claude
    """
    base = dict(application='cugn', datum='MSL', time_zone='GMT',
                units='metric', format='csv')
    base.update(params)
    resp = requests.get(COOPS_API, params=base, timeout=REQUEST_TIMEOUT,
                        headers=HEADERS)
    resp.raise_for_status()
    text = resp.text
    # The API returns HTTP 200 with an "Error:" line when nothing is found.
    if 'Error' in text.split('\n', 2)[0] or 'Error:' in text[:400]:
        return ''
    return text


def _coops_csv_to_frame(text):
    """ Parse CO-OPS CSV text into a DataFrame with stripped column names.

    Inputs
    ------
    text : str
        CSV text from the datagetter API.

    Outputs
    -------
    pandas.DataFrame (empty if `text` is empty).

    Generated by JXP and Claude
    """
    if not text.strip():
        return pd.DataFrame()
    df = pd.read_csv(io.StringIO(text))
    df.columns = [c.strip() for c in df.columns]
    return df


def download_station_metadata(station):
    """ Fetch name/lat/lon of a CO-OPS station and store it in stations.json.

    Inputs
    ------
    station : str
        7-digit CO-OPS station id.

    Outputs
    -------
    dict : {'id', 'name', 'lat', 'lon', 'state'}; also merged into
        $OS_CCS/SeaLevel/stations.json.

    Generated by JXP and Claude
    """
    os.makedirs(SEALEVEL_DIR, exist_ok=True)
    resp = requests.get(f'{COOPS_MDAPI}{station}.json', timeout=REQUEST_TIMEOUT,
                        headers=HEADERS)
    resp.raise_for_status()
    s = resp.json()['stations'][0]
    meta = {'id': str(station), 'name': s.get('name'),
            'lat': float(s['lat']), 'lon': float(s['lng']),
            'state': s.get('state')}
    jpath = os.path.join(SEALEVEL_DIR, 'stations.json')
    allmeta = {}
    if os.path.exists(jpath):
        with open(jpath) as f:
            allmeta = json.load(f)
    allmeta[str(station)] = meta
    with open(jpath, 'w') as f:
        json.dump(allmeta, f, indent=2)
    return meta


def _month_starts(start, end):
    """ Calendar-month (begin, end) date pairs covering start..end.

    Inputs
    ------
    start, end : Timestamp-like

    Outputs
    -------
    list of (Timestamp, Timestamp) : first and last day of each month,
        clipped to start/end.

    Generated by JXP and Claude
    """
    start = pd.Timestamp(start).normalize()
    end = pd.Timestamp(end).normalize()
    out = []
    t0 = start.replace(day=1)
    while t0 <= end:
        t1 = (t0 + pd.offsets.MonthEnd(0)).normalize()
        out.append((max(t0, start), min(t1, end)))
        t0 = t1 + pd.Timedelta(days=1)
    return out


def download_tide_gauge(station, product='monthly_mean', start='1991-01-01',
                        end=None):
    """ Download CO-OPS sea level for one station and save/extend the CSV.

    monthly_mean : requested in <=10-year chunks (the API also accepts the
        full range) and written to {station}_monthly_mean_MSL.csv with a
        `time` column (15th of each month) plus the raw MSL/MHHW/... columns.
    hourly_height : requested one calendar month at a time (31-day API
        limit).  Months for which verified hourly heights are not yet
        available (verified data lag ~1 month) fall back to the preliminary
        6-minute `water_level` product subsampled on the hour and are
        flagged `preliminary=1`.  Rows
        are merged into {station}_hourly_MSL_2026.csv (existing verified
        rows win over preliminary ones), so calling again later extends the
        file through e.g. Oct-Nov 2026.

    Inputs
    ------
    station : str
        CO-OPS station id ('9413450' Monterey, '9414290' San Francisco).
    product : str
        'monthly_mean' or 'hourly_height'.
    start, end : date-like
        Inclusive range; `end` defaults to today (UTC).

    Outputs
    -------
    str : path of the CSV written.

    Generated by JXP and Claude
    """
    os.makedirs(SEALEVEL_DIR, exist_ok=True)
    station = str(station)
    start = pd.Timestamp(start)
    end = pd.Timestamp(end) if end is not None else pd.Timestamp.now('UTC').tz_localize(None)
    fmt = '%Y%m%d'

    if product == 'monthly_mean':
        frames = []
        # <=10-year chunks; robust if the API ever refuses long ranges.
        t0 = start
        while t0 <= end:
            t1 = min(t0 + pd.DateOffset(years=10) - pd.Timedelta(days=1), end)
            text = _coops_request(dict(product='monthly_mean', station=station,
                                       begin_date=t0.strftime(fmt),
                                       end_date=t1.strftime(fmt)))
            frames.append(_coops_csv_to_frame(text))
            t0 = t1 + pd.Timedelta(days=1)
        df = pd.concat([f for f in frames if len(f)], ignore_index=True)
        df['time'] = pd.to_datetime(dict(year=df['Year'], month=df['Month'],
                                         day=15))
        df = (df.drop_duplicates('time').sort_values('time')
              .reset_index(drop=True))
        df = df[['time'] + [c for c in df.columns if c != 'time']]
        path = os.path.join(SEALEVEL_DIR, f'{station}_monthly_mean_MSL.csv')
        df.to_csv(path, index=False)
        return path

    elif product == 'hourly_height':
        frames = []
        for (t0, t1) in _month_starts(start, end):
            params = dict(product='hourly_height', station=station,
                          begin_date=t0.strftime(fmt), end_date=t1.strftime(fmt))
            text = _coops_request(params)
            prelim = 0
            if not text:
                # Verified hourly heights lag by ~1 month; use preliminary
                # 6-minute water levels sampled hourly instead.
                params.update(product='water_level', interval='h')
                text = _coops_request(params)
                prelim = 1
            sub = _coops_csv_to_frame(text)
            if not len(sub):
                continue
            sub = pd.DataFrame({
                'time': pd.to_datetime(sub['Date Time']),
                'msl': pd.to_numeric(sub['Water Level'], errors='coerce'),
                'sigma': pd.to_numeric(sub['Sigma'], errors='coerce'),
                'preliminary': prelim})
            # The API ignores interval=h for water_level and returns 6-min
            # samples; keep the on-the-hour values like hourly_height does.
            sub = sub[sub['time'].dt.minute == 0]
            frames.append(sub)
        path = os.path.join(SEALEVEL_DIR, f'{station}_hourly_MSL_2026.csv')
        new = (pd.concat(frames, ignore_index=True) if frames
               else pd.DataFrame(columns=['time', 'msl', 'sigma', 'preliminary']))
        # Merge with any existing file: verified rows replace preliminary.
        if os.path.exists(path):
            old = pd.read_csv(path, parse_dates=['time'])
            new = pd.concat([old, new], ignore_index=True)
        new = (new.sort_values(['time', 'preliminary'])
               .drop_duplicates('time', keep='first')
               .reset_index(drop=True))
        new.to_csv(path, index=False)
        return path

    raise ValueError("product must be 'monthly_mean' or 'hourly_height'")


