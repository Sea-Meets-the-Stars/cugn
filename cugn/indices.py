def download_scti(max_age_days=1.0):
    """ Download the SCTI 10-day and monthly tables from SprayData ERDDAP.

    The full tabledap CSV is requested (no constraints); ERDDAP CSV has a
    units row as line 2 which load_scti skips.

    Inputs
    ------
    max_age_days : float or None
        Re-download if the cached file is older than this many days.

    Outputs
    -------
    dict : cadence -> local CSV path in $OS_CCS/Indices/SCTI/.

    Generated by JXP and Claude
    """
    paths = {}
    for cadence, dset in SCTI_DATASETS.items():
        url = f'{SCTI_ERDDAP}{dset}.csv'   # all variables, all rows
        path = os.path.join(SCTI_DIR, f'{dset}.csv')
        paths[cadence] = _fetch_to_file(url, path, max_age_days=max_age_days)
    return paths


def load_scti(cadence='10day'):
    """ Load the cached SCTI table.

    Column mapping (SCTI_COLUMN_MAP): 10-day `scti_10day` -> `scti`;
    monthly `scti` -> `scti`, `oni` -> `oni` (CPC Nino-3.4 3-month mean as
    distributed with the SCTI).  Per the ERDDAP metadata the SCTI is the
    Line 90 temperature anomaly at 50 m depth averaged over the inshore
    200 km and smoothed over 90 days.

    Inputs
    ------
    cadence : str
        '10day' or 'monthly'.

    Outputs
    -------
    pandas.DataFrame : `time` (Timestamp, UTC-naive), `scti` (deg C) and,
        for 'monthly', `oni`.

    Generated by JXP and Claude
    """
    if cadence not in SCTI_DATASETS:
        raise ValueError(f"cadence must be one of {list(SCTI_DATASETS)}")
    path = os.path.join(SCTI_DIR, f'{SCTI_DATASETS[cadence]}.csv')
    # Row 1 (0-based) is the ERDDAP units row.
    df = pd.read_csv(path, skiprows=[1])
    df = df.rename(columns=SCTI_COLUMN_MAP[cadence])
    df['time'] = pd.to_datetime(df['time'], utc=True).dt.tz_localize(None)
    keep = ['time'] + [c for c in SCTI_COLUMN_MAP[cadence].values()
                       if c in df.columns]
    return df[keep].sort_values('time').reset_index(drop=True)


