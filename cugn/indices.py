def _file_age_days(path):
    """ Age of a file in days (np.inf if it does not exist).

    Inputs
    ------
    path : str
        File path.

    Outputs
    -------
    float : age in days since last modification.

    Generated by JXP and Claude
    """
    if not os.path.exists(path):
        return np.inf
    mtime = pd.Timestamp(os.path.getmtime(path), unit='s')
    return (pd.Timestamp.now() - mtime).total_seconds() / 86400.


def _fetch_to_file(url, path, max_age_days=None, binary=False):
    """ Download `url` to `path` unless a fresh cached copy exists.

    The download is written to a temporary file and moved into place so a
    failed transfer never clobbers a good cached copy.  If the transfer
    fails and a cached copy exists, a warning is issued and the cache kept.

    Inputs
    ------
    url : str
        Remote URL.
    path : str
        Destination path.
    max_age_days : float or None
        Skip the download if the cached file is younger than this; None
        always downloads.
    binary : bool
        Write bytes (NetCDF) rather than text.

    Outputs
    -------
    str : the destination path.

    Generated by JXP and Claude
    """
    os.makedirs(os.path.dirname(path), exist_ok=True)
    # Freshness check (mirrors Dan's downloadoni.m behaviour).
    if max_age_days is not None and _file_age_days(path) <= max_age_days:
        return path
    tmp = path + '.part'
    try:
        resp = requests.get(url, timeout=REQUEST_TIMEOUT, headers=HEADERS)
        resp.raise_for_status()
        if binary:
            with open(tmp, 'wb') as f:
                f.write(resp.content)
        else:
            with open(tmp, 'w') as f:
                f.write(resp.text)
        shutil.move(tmp, path)
    except Exception as err:
        if os.path.exists(tmp):
            os.remove(tmp)
        if os.path.exists(path):
            warnings.warn(f'Download of {url} failed ({err}); '
                          f'using cached {path}')
        else:
            raise
    return path


def running_mean(y, n):
    """ Centered running mean over `n` points, ignoring NaNs.

    Mirrors the `runmean` smoothing used in Dan Rudnick's time-series plots:
    n=3 on monthly data gives the 3-month ONI-style smoothing; n=9 on the
    10-day CUGN grid is ~90 days.  Each output point is the mean of the
    non-NaN values inside the centered window; at the edges the window is
    truncated and a value is still returned provided at least n//2 (min 1)
    valid points are present.  Otherwise NaN.

    Inputs
    ------
    y : 1-D array-like
        Input series (NaNs allowed).
    n : int
        Window length in samples.

    Outputs
    -------
    numpy.ndarray : same length as `y`, the centered running mean.

    Generated by JXP and Claude
    """
    s = pd.Series(np.asarray(y, dtype=float))
    min_periods = max(1, n // 2)
    return s.rolling(window=n, center=True,
                     min_periods=min_periods).mean().to_numpy()


