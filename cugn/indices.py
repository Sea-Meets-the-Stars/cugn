def download_oni(kind='official', max_age_days=1.0):
    """ Download (if stale) the CPC ONI or detrended Nino-3.4 text file.

    Inputs
    ------
    kind : str
        'official'  -> oni.ascii.txt (SEAS YR TOTAL ANOM, 3-month seasons)
        'detrended' -> detrend.nino34.ascii.txt (YR MON TOTAL ClimAdjust ANOM),
                       the file used by Dan's downloadoni.m.
    max_age_days : float or None
        Re-download if the cached file is older than this many days.

    Outputs
    -------
    str : path of the local file in $OS_CCS/Indices/ONI/.

    Generated by JXP and Claude
    """
    if kind not in ONI_URLS:
        raise ValueError(f"kind must be one of {list(ONI_URLS)}, got {kind!r}")
    path = os.path.join(ONI_DIR, ONI_FILES[kind])
    return _fetch_to_file(ONI_URLS[kind], path, max_age_days=max_age_days)


def parse_oni_official(text):
    """ Parse the CPC oni.ascii.txt format (SEAS YR TOTAL ANOM).

    Each row is a 3-month season (e.g. DJF) labelled with the year of the
    center month; the row is time-stamped at the 15th of that center month.

    Inputs
    ------
    text : str
        File contents.

    Outputs
    -------
    pandas.DataFrame : columns `time` (Timestamp, mid center-month),
        `season` (str), `total` (deg C), `oni` (deg C anomaly).

    Generated by JXP and Claude
    """
    df = pd.read_csv(io.StringIO(text), sep=r'\s+')
    # Center month from the season label (DJF -> January, etc.).
    month = df['SEAS'].map(lambda s: ONI_SEASONS.index(s) + 1)
    time = pd.to_datetime(dict(year=df['YR'], month=month, day=15))
    out = pd.DataFrame({'time': time,
                        'season': df['SEAS'].values,
                        'total': df['TOTAL'].astype(float).values,
                        'oni': df['ANOM'].astype(float).values})
    return out


def parse_oni_detrended(text, nsmooth=3):
    """ Parse detrend.nino34.ascii.txt (YR MON TOTAL ClimAdjust ANOM).

    Reproduces Dan's downloadoni.m / cugn_climatology.load_oni: monthly
    values stamped on the 15th; the `oni` column is the centered 3-month
    running mean of `anom`, which approximates the ONI.

    Inputs
    ------
    text : str
        File contents.
    nsmooth : int
        Running-mean window (months) for the `oni` column.

    Outputs
    -------
    pandas.DataFrame : columns `time` (Timestamp, mid-month), `total`,
        `clim_adjust`, `anom` (raw monthly Nino-3.4 anomaly), `oni`
        (nsmooth-month running mean of `anom`).

    Generated by JXP and Claude
    """
    df = pd.read_csv(io.StringIO(text), sep=r'\s+')
    time = pd.to_datetime(dict(year=df['YR'], month=df['MON'], day=15))
    anom = df['ANOM'].astype(float).values
    out = pd.DataFrame({'time': time,
                        'total': df['TOTAL'].astype(float).values,
                        'clim_adjust': df['ClimAdjust'].astype(float).values,
                        'anom': anom,
                        'oni': running_mean(anom, nsmooth)})
    return out


def load_oni(kind='official'):
    """ Load the cached ONI (official) or detrended Nino-3.4 series.

    Does not download; call `download_oni(kind)` first (main() does).

    Inputs
    ------
    kind : str
        'official' or 'detrended' (see download_oni).

    Outputs
    -------
    pandas.DataFrame with `time` (Timestamp, mid-month) and `oni` (float,
        deg C).  'official' adds `season`, `total`; 'detrended' adds
        `total`, `clim_adjust`, `anom` (raw monthly) with `oni` the
        3-month running mean of `anom`.

    Generated by JXP and Claude
    """
    path = os.path.join(ONI_DIR, ONI_FILES[kind])
    with open(path) as f:
        text = f.read()
    if kind == 'official':
        return parse_oni_official(text)
    elif kind == 'detrended':
        return parse_oni_detrended(text)
    raise ValueError(f"kind must be one of {list(ONI_URLS)}, got {kind!r}")


