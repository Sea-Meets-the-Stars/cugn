def daily_mean(df, min_hours=20):
    """ Daily mean of an hourly sea-level series.

    Inputs
    ------
    df : pandas.DataFrame
        `time`, `msl` (from load_hourly_sea_level).
    min_hours : int
        Days with fewer valid hourly values are set to NaN.

    Outputs
    -------
    pandas.DataFrame : `time` (Timestamp at 12:00 of each day), `msl`
        (daily mean, m), `nhours` (valid hours).

    Generated by JXP and Claude
    """
    day = pd.DatetimeIndex(df['time']).normalize()
    g = pd.Series(df['msl'].to_numpy(dtype=float)).groupby(day)
    out = pd.DataFrame({'time': g.mean().index + pd.Timedelta(hours=12),
                        'msl': g.mean().to_numpy(),
                        'nhours': g.count().to_numpy()})
    out.loc[out['nhours'] < min_hours, 'msl'] = np.nan
    return out.reset_index(drop=True)


