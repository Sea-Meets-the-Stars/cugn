def download_upwelling(max_age_days=1.0):
    """ Download the CUTI and BEUTI daily NetCDF files from mjacox.com.

    The first time this runs, the pre-existing Dec-2024 copies of
    CUTI_daily.nc / BEUTI_daily.nc are preserved as *_2024.nc before the
    new files are written.

    Inputs
    ------
    max_age_days : float or None
        Re-download if the cached file is older than this many days.

    Outputs
    -------
    dict : index -> local path in $OS_CCS/Upwelling/.

    Generated by JXP and Claude
    """
    paths = {}
    for index, url in UPWELLING_URLS.items():
        path = os.path.join(UPWELLING_DIR, f'{index}_daily.nc')
        backup = os.path.join(UPWELLING_DIR, f'{index}_daily_2024.nc')
        # One-time preservation of the original (Dec 2024) files.
        if os.path.exists(path) and not os.path.exists(backup):
            os.rename(path, backup)
        paths[index] = _fetch_to_file(url, path, max_age_days=max_age_days,
                                      binary=True)
    return paths


def load_upwelling(index='CUTI', lat=36):
    """ Load a daily upwelling index at one latitude.

    Inputs
    ------
    index : str
        'CUTI' (m^2/s, vertical transport) or 'BEUTI' (mmol/m/s nitrate flux).
    lat : float
        Latitude in deg N; the nearest grid latitude (31..47 in 1 deg steps)
        is used.  36 N is the Line 66.7 / Monterey Bay latitude.

    Outputs
    -------
    pandas.DataFrame : `time` (daily Timestamp) and `value`; attribute
        `.attrs['latitude']` records the grid latitude actually used.

    Generated by JXP and Claude
    """
    path = os.path.join(UPWELLING_DIR, f'{index}_daily.nc')
    with xr.open_dataset(path) as ds:
        da = ds[index].sel(latitude=lat, method='nearest').load()
        df = pd.DataFrame({'time': pd.to_datetime(da['time'].values),
                           'value': da.values.astype(float)})
        df.attrs['latitude'] = float(da['latitude'].values)
        df.attrs['index'] = index
    return df


def _noleap_doy(time):
    """ Day of year on a 365-day calendar (Feb 29 shares day 59 with Feb 28).

    Inputs
    ------
    time : pandas.DatetimeIndex or Series of Timestamps.

    Outputs
    -------
    numpy.ndarray of int : 1..365.

    Generated by JXP and Claude
    """
    t = pd.DatetimeIndex(time)
    doy = t.dayofyear.to_numpy().copy()
    # In leap years, every day after Feb 29 (doy 60) shifts back by one so
    # that Mar 1 is always day 60; Feb 29 itself maps to 59.
    leap = np.asarray(t.is_leap_year)
    doy[leap & (doy >= 60)] -= 1
    return doy


def _circular_running_mean(y, n):
    """ Centered running mean of a periodic series (wraps around the ends).

    Inputs
    ------
    y : 1-D array (NaNs allowed), one full period.
    n : int
        Window length in samples.

    Outputs
    -------
    numpy.ndarray : same length as `y`.

    Generated by JXP and Claude
    """
    y = np.asarray(y, dtype=float)
    m = len(y)
    # Pad with a copy on each side, smooth, and cut out the middle period.
    padded = np.concatenate([y, y, y])
    sm = running_mean(padded, n)
    return sm[m:2 * m]


def upwelling_anomaly(df, clim_years=(1991, 2020), smooth_days=31):
    """ Daily climatology and anomaly of an upwelling index.

    The climatology is the mean by (365-day) day-of-year over `clim_years`,
    smoothed with a circular centered running mean of `smooth_days`.

    Inputs
    ------
    df : pandas.DataFrame
        Output of load_upwelling (`time`, `value`).
    clim_years : (int, int)
        Inclusive first/last year of the climatology.
    smooth_days : int
        Running-mean window (days) applied to the day-of-year climatology.

    Outputs
    -------
    pandas.DataFrame : copy of `df` with added `clim` and `anom` = value - clim.

    Generated by JXP and Claude
    """
    out = df.copy()
    doy = _noleap_doy(out['time'])
    years = pd.DatetimeIndex(out['time']).year.to_numpy()
    in_clim = (years >= clim_years[0]) & (years <= clim_years[1])
    # Raw day-of-year means over the climatology years.
    clim_doy = (pd.Series(out['value'].to_numpy()[in_clim])
                .groupby(doy[in_clim]).mean()
                .reindex(np.arange(1, 366)).to_numpy())
    # Circular smoothing so Dec 31 and Jan 1 are continuous.
    clim_doy = _circular_running_mean(clim_doy, smooth_days)
    out['clim'] = clim_doy[doy - 1]
    out['anom'] = out['value'] - out['clim']
    out.attrs.update(df.attrs)
    return out


