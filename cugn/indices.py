def line_temperature_index(anom, zmax=100.0, xmax=200.0, nsmooth=9):
    """ Upper-ocean, inshore-averaged, smoothed anomaly index for a CUGN line.

    Mirrors Dan's ptimeONIAllLines.m and the spirit of the SCTI: the
    interannual anomaly is nan-averaged over depth <= zmax and distance <=
    xmax, then smoothed with a centered nsmooth-point running mean (9 points
    on the 10-day grid ~ 90 days, matching the ONI's 3-month window).  Note
    the operational SCTI uses the 50-m level rather than the upper 100 m.

    Inputs
    ------
    anom : xarray.DataArray
        dims ('time', 'depth', 'distance'); depth in m positive down,
        distance in km with 0 inshore; regular (10-day) time axis.
    zmax : float
        Maximum depth (m) included in the average.
    xmax : float
        Maximum offshore distance (km) included.
    nsmooth : int
        Running-mean window in time samples.

    Outputs
    -------
    pandas.Series : index = time, values = smoothed index (units of `anom`).

    Generated by JXP and Claude
    """
    sub = anom.sel(depth=slice(0, zmax), distance=slice(0, xmax))
    series = sub.mean(('depth', 'distance'), skipna=True).values
    smoothed = running_mean(series, nsmooth)
    return pd.Series(smoothed, index=pd.DatetimeIndex(anom['time'].values),
                     name='index')


