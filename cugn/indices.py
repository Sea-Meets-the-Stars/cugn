def sea_level_anomaly(df, clim_years=(1991, 2020), detrend=True):
    """ Monthly sea-level anomaly relative to a climatology and linear trend.

    A linear trend is fit over the full record jointly with 12 monthly
    means (so partial years do not bias the slope); it is referenced to
    zero at the center of `clim_years`.  The climatology is the monthly
    mean of (msl - trend) over `clim_years`; anom = msl - clim - trend.

    Inputs
    ------
    df : pandas.DataFrame
        `time`, `msl` (from load_sea_level).
    clim_years : (int, int)
        Inclusive years for the monthly climatology.
    detrend : bool
        If False the trend is zero.

    Outputs
    -------
    pandas.DataFrame : copy of `df` with `clim`, `trend`, `anom` (m);
        `.attrs['trend_mm_per_yr']` holds the fitted rate.

    Generated by JXP and Claude
    """
    out = df.copy()
    t = pd.DatetimeIndex(out['time'])
    # Decimal year for the trend.
    tyr = np.asarray(t.year + (t.dayofyear - 0.5) / 365.25, dtype=float)
    month = np.asarray(t.month)
    msl = out['msl'].to_numpy(dtype=float)
    good = np.isfinite(msl)

    in_clim = np.asarray((t.year >= clim_years[0]) & (t.year <= clim_years[1]))
    tref = tyr[in_clim].mean() if in_clim.any() else tyr.mean()

    if detrend:
        # Design matrix: 12 month indicators + (t - tref); no intercept
        # because the indicators span it.
        X = np.zeros((len(msl), 13))
        X[np.arange(len(msl)), month - 1] = 1.
        X[:, 12] = tyr - tref
        coef, *_ = np.linalg.lstsq(X[good], msl[good], rcond=None)
        slope = coef[12]
    else:
        slope = 0.
    trend = slope * (tyr - tref)

    detr = msl - trend
    clim_month = (pd.Series(detr[in_clim]).groupby(month[in_clim]).mean()
                  .reindex(np.arange(1, 13)).to_numpy())
    out['clim'] = clim_month[month - 1]
    out['trend'] = trend
    out['anom'] = msl - out['clim'] - out['trend']
    out.attrs['trend_mm_per_yr'] = float(slope * 1000.)
    return out


