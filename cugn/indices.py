def _latest(df, col):
    """ (time, value) of the last finite entry of `col`.

    Inputs
    ------
    df : pandas.DataFrame with a `time` column.
    col : str

    Outputs
    -------
    (Timestamp, float)

    Generated by JXP and Claude
    """
    good = df[np.isfinite(df[col].to_numpy(dtype=float))]
    row = good.iloc[-1]
    return row['time'], float(row[col])


def main(max_age_days=0.0):
    """ Download every dataset and print the latest value of each.

    Inputs
    ------
    max_age_days : float
        Freshness threshold passed to the downloaders (0 = always refresh).

    Outputs
    -------
    none (prints a summary; failures of one endpoint do not stop the rest).

    Generated by JXP and Claude
    """
    today = pd.Timestamp.now('UTC').tz_localize(None).normalize()
    print(f'cugn.indices refresh, {today.date()}  (OS_CCS={OS_CCS})')

    # ONI
    for kind in ('official', 'detrended'):
        try:
            path = download_oni(kind, max_age_days=max_age_days)
            df = load_oni(kind)
            t, v = _latest(df, 'oni')
            extra = ''
            if kind == 'official':
                extra = f" season {df['season'].iloc[-1]}"
            else:
                ta, va = _latest(df, 'anom')
                extra = f'; raw monthly anom {va:+.2f} at {ta:%Y-%m}'
            print(f'ONI {kind:9s}: {path}\n    {df.time.iloc[0]:%Y-%m} -> '
                  f'{df.time.iloc[-1]:%Y-%m}; latest oni {v:+.2f} at {t:%Y-%m}{extra}')
        except Exception as err:
            print(f'ONI {kind}: FAILED ({err})')

    # SCTI
    try:
        paths = download_scti(max_age_days=max_age_days)
        for cadence, path in paths.items():
            df = load_scti(cadence)
            t, v = _latest(df, 'scti')
            print(f'SCTI {cadence:7s}: {path}\n    {df.time.iloc[0]:%Y-%m-%d} -> '
                  f'{df.time.iloc[-1]:%Y-%m-%d}; latest scti {v:+.2f} at {t:%Y-%m-%d}')
    except Exception as err:
        print(f'SCTI: FAILED ({err})')

    # Upwelling
    try:
        paths = download_upwelling(max_age_days=max_age_days)
        for index, path in paths.items():
            for lat in (36, 37):
                df = load_upwelling(index, lat=lat)
                t, v = _latest(df, 'value')
                print(f'{index} {lat}N: {path}\n    {df.time.iloc[0]:%Y-%m-%d} -> '
                      f'{df.time.iloc[-1]:%Y-%m-%d}; latest {v:.2f} at {t:%Y-%m-%d}')
    except Exception as err:
        print(f'Upwelling: FAILED ({err})')

    # Tide gauges
    for station, name in TIDE_STATIONS.items():
        try:
            meta = download_station_metadata(station)
            path = download_tide_gauge(station, 'monthly_mean', '1991-01-01', today)
            df = sea_level_anomaly(load_sea_level(station))
            t, v = _latest(df, 'anom')
            print(f"{name} {station} ({meta['lat']:.3f}N, {meta['lon']:.3f}E): {path}\n"
                  f'    {df.time.iloc[0]:%Y-%m} -> {df.time.iloc[-1]:%Y-%m}; '
                  f'latest MSL {df.msl.iloc[-1]:.3f} m, anom {v:+.3f} m at {t:%Y-%m}; '
                  f"trend {df.attrs['trend_mm_per_yr']:.1f} mm/yr")
        except Exception as err:
            print(f'{name} monthly: FAILED ({err})')
        try:
            path = download_tide_gauge(station, 'hourly_height', '2026-06-01', today)
            hdf = load_hourly_sea_level(station)
            dm = daily_mean(hdf)
            t, v = _latest(dm, 'msl')
            nprelim = int(hdf['preliminary'].sum())
            print(f'{name} hourly: {path}\n    {hdf.time.iloc[0]} -> {hdf.time.iloc[-1]}; '
                  f'{len(hdf)} rows ({nprelim} preliminary); latest daily mean '
                  f'{v:.3f} m on {t:%Y-%m-%d}')
        except Exception as err:
            print(f'{name} hourly: FAILED ({err})')


if __name__ == '__main__':
    main()
