def doy366(times):
    """Day of year on a 366-day (leap-year) calendar.

    Feb 29 is day 60 and Mar 1 is day 61 in every year, so calendar dates
    line up across leap and non-leap years.

    Parameters
    ----------
    times : pandas.DatetimeIndex or array of datetime64

    Returns
    -------
    np.ndarray of int (1..366)

    Generated by JXP and Claude
    """
    times = pd.DatetimeIndex(times)
    doy = times.dayofyear.values.copy()
    is_leap = times.is_leap_year
    # In non-leap years, shift everything from Mar 1 onward by one day
    doy[(~is_leap) & (doy >= 60)] += 1
    return doy


def circular_running_mean(arr, window, axis=0):
    """Running mean with circular (periodic) boundary along one axis.

    Parameters
    ----------
    arr : np.ndarray
        Array periodic along ``axis`` (e.g. 366 days of year).  NaNs are
        ignored (nanmean over the window).
    window : int
        Odd window length.
    axis : int

    Returns
    -------
    np.ndarray of the same shape.

    Generated by JXP and Claude
    """
    half = window // 2
    arr = np.moveaxis(np.asarray(arr, dtype=float), axis, 0)
    # Pad by wrapping so the window is complete at both ends
    padded = np.concatenate([arr[-half:], arr, arr[:half]], axis=0)
    out = np.empty_like(arr)
    for i in range(arr.shape[0]):
        with warnings.catch_warnings():
            warnings.simplefilter('ignore', category=RuntimeWarning)
            out[i] = np.nanmean(padded[i:i + window], axis=0)
    return np.moveaxis(out, 0, axis)


def _fill_feb29(arr):
    """Replace day-60 (Feb 29) values by the mean of days 59 and 61 along axis 0.

    Parameters
    ----------
    arr : np.ndarray with 366 along axis 0

    Returns
    -------
    np.ndarray (copy)

    Generated by JXP and Claude
    """
    arr = arr.copy()
    arr[59] = 0.5 * (arr[58] + arr[60])
    return arr


def daily_climatology(series, clim_years=(1991, 2020), pctile=90,
                      window_days=11, smooth_days=31):
    """Hobday et al. (2016) day-of-year climatology and threshold for a series.

    For each day of the 366-day year, values within a centred
    ``window_days`` window across all baseline years are pooled; their
    mean is the climatology and their ``pctile`` percentile the threshold.
    Both are then smoothed with a circular ``smooth_days`` running mean.
    Feb 29 (day 60) is set to the mean of Feb 28 and Mar 1 before
    smoothing, following the reference implementation.

    Parameters
    ----------
    series : pandas.Series with a daily DatetimeIndex
    clim_years : (int, int)
        Inclusive baseline years.
    pctile : float
    window_days : int
    smooth_days : int

    Returns
    -------
    clim, thresh : np.ndarray (366,)
        Indexed by ``doy366 - 1``.

    Generated by JXP and Claude
    """
    ser = series.copy()
    ser.index = pd.DatetimeIndex(ser.index)
    base = ser[(ser.index.year >= clim_years[0]) & (ser.index.year <= clim_years[1])]
    if base.size == 0:
        raise ValueError('no data in the baseline years')
    years = np.arange(clim_years[0], clim_years[1] + 1)
    # Arrange the baseline as (year, doy366) with NaN where there is no data
    table = np.full((years.size, 366), np.nan)
    iy = base.index.year.values - clim_years[0]
    idoy = doy366(base.index) - 1
    table[iy, idoy] = base.values
    half = window_days // 2
    offsets = np.arange(-half, half + 1)
    clim = np.full(366, np.nan)
    thresh = np.full(366, np.nan)
    for d in range(366):
        vals = table[:, (d + offsets) % 366].ravel()
        vals = vals[np.isfinite(vals)]
        if vals.size == 0:
            continue
        clim[d] = vals.mean()
        thresh[d] = np.percentile(vals, pctile)
    clim = circular_running_mean(_fill_feb29(clim), smooth_days)
    thresh = circular_running_mean(_fill_feb29(thresh), smooth_days)
    return clim, thresh


def hobday_mhw(series, clim_years=(1991, 2020), pctile=90, window_days=11,
               min_duration=5, max_gap=2):
    """Detect marine heatwaves in a daily SST series (Hobday et al. 2016, 2018).

    Climatology and threshold follow :func:`daily_climatology` (centred
    ``window_days`` window across the baseline years, 31-day circular
    smoothing, Feb 29 handled on a 366-day calendar).  A marine heatwave
    is a run of at least ``min_duration`` days with SST above the
    threshold; events separated by gaps of at most ``max_gap`` days are
    joined into one (gap days included).  Categories follow Hobday et al.
    (2018): the anomaly (SST - clim) in units of (thresh - clim), floored
    and capped at 4: 1 Moderate, 2 Strong, 3 Severe, 4 Extreme.

    Parameters
    ----------
    series : pandas.Series
        Daily SST with a DatetimeIndex (missing days are filled with NaN).
    clim_years : (int, int)
    pctile : float
    window_days : int
    min_duration : int
    max_gap : int

    Returns
    -------
    dict with keys
        'daily' : pandas.DataFrame indexed by day with columns
            sst, clim, thresh, anom, is_mhw (bool), category (int 0-4),
            category_label (str), event (event index or -1)
        'events' : pandas.DataFrame with one row per event:
            start, end, duration_days, max_intensity, date_max,
            mean_intensity, category (int), category_label (str)
        'clim_years', 'pctile', 'window_days', 'min_duration', 'max_gap'

    Generated by JXP and Claude
    """
    ser = pd.Series(series).copy()
    ser.index = pd.DatetimeIndex(ser.index).normalize()
    ser = ser[~ser.index.duplicated(keep='last')].sort_index()
    # Complete daily axis so runs/gaps are counted in calendar days
    full = pd.date_range(ser.index[0], ser.index[-1], freq='D')
    ser = ser.reindex(full)

    clim366, thresh366 = daily_climatology(ser, clim_years=clim_years,
                                           pctile=pctile, window_days=window_days)
    idoy = doy366(ser.index) - 1
    clim = clim366[idoy]
    thresh = thresh366[idoy]
    sst = ser.values.astype(float)
    anom = sst - clim
    exceed = np.isfinite(sst) & (sst > thresh)

    # --- find runs of exceedance and keep those long enough
    runs = _find_runs(exceed)
    runs = [(s, e) for s, e in runs if (e - s + 1) >= min_duration]
    # --- join events separated by short gaps (gap days become part of the event)
    joined = []
    for s, e in runs:
        if joined and (s - joined[-1][1] - 1) <= max_gap:
            joined[-1] = (joined[-1][0], e)
        else:
            joined.append((s, e))

    n = sst.size
    is_mhw = np.zeros(n, dtype=bool)
    event_id = np.full(n, -1, dtype=int)
    for k, (s, e) in enumerate(joined):
        is_mhw[s:e + 1] = True
        event_id[s:e + 1] = k

    # --- categories: anomaly in units of (thresh - clim), only on MHW days
    scale = thresh - clim
    with np.errstate(invalid='ignore', divide='ignore'):
        ratio = anom / scale
    category = np.zeros(n, dtype=int)
    ok = is_mhw & np.isfinite(ratio) & (ratio >= 1)
    category[ok] = np.clip(np.floor(ratio[ok]), 1, 4).astype(int)

    daily = pd.DataFrame({'sst': sst, 'clim': clim, 'thresh': thresh,
                          'anom': anom, 'is_mhw': is_mhw, 'category': category,
                          'category_label': [CATEGORY_LABELS[c] for c in category],
                          'event': event_id}, index=ser.index)
    daily.index.name = 'time'

    rows = []
    for k, (s, e) in enumerate(joined):
        a = anom[s:e + 1]
        imax = int(np.nanargmax(a))
        cat = int(category[s:e + 1].max())
        rows.append({'start': ser.index[s], 'end': ser.index[e],
                     'duration_days': int(e - s + 1),
                     'max_intensity': float(a[imax]),
                     'date_max': ser.index[s + imax],
                     'mean_intensity': float(np.nanmean(a)),
                     'category': cat, 'category_label': CATEGORY_LABELS[cat]})
    events = pd.DataFrame(rows, columns=['start', 'end', 'duration_days',
                                         'max_intensity', 'date_max',
                                         'mean_intensity', 'category',
                                         'category_label'])
    return {'daily': daily, 'events': events, 'clim_years': clim_years,
            'pctile': pctile, 'window_days': window_days,
            'min_duration': min_duration, 'max_gap': max_gap}


def _find_runs(mask):
    """Start/end indices (inclusive) of runs of True in a boolean array.

    Parameters
    ----------
    mask : np.ndarray of bool

    Returns
    -------
    list of (start, end) tuples

    Generated by JXP and Claude
    """
    m = np.concatenate([[False], mask.astype(bool), [False]])
    d = np.diff(m.astype(int))
    starts = np.where(d == 1)[0]
    ends = np.where(d == -1)[0] - 1
    return list(zip(starts, ends))


def gridded_climatology(ds, clim_years=(1991, 2020), var='sst',
                        window_days=11, smooth_days=31):
    """Hobday-style day-of-year climatology for every grid cell.

    Same recipe as :func:`daily_climatology` (centred window pooled across
    baseline years, Feb 29 filled from neighbours, 31-day circular
    smoothing), implemented with per-day sums and counts so the pooled
    window mean is exact.

    Parameters
    ----------
    ds : xarray.Dataset with dims (time, lat, lon)
    clim_years : (int, int)
    var : str
    window_days : int
    smooth_days : int

    Returns
    -------
    xarray.DataArray dims (doy, lat, lon) with doy = 1..366 (366-day calendar)

    Generated by JXP and Claude
    """
    t0 = f'{clim_years[0]}-01-01'
    t1 = f'{clim_years[1]}-12-31'
    base = ds[var].sel(time=slice(t0, t1)).load()
    if base.time.size == 0:
        raise ValueError('no data in the baseline years')
    idoy = doy366(base.time.values)
    vals = base.values.astype(np.float32)
    finite = np.isfinite(vals)
    # Per-doy sums and counts (366, lat, lon)
    shape = (366,) + vals.shape[1:]
    sums = np.zeros(shape, dtype=np.float64)
    cnts = np.zeros(shape, dtype=np.float64)
    np.add.at(sums, idoy - 1, np.where(finite, vals, 0.))
    np.add.at(cnts, idoy - 1, finite.astype(float))
    # Pool over the centred window (circular) by summing sums and counts
    half = window_days // 2
    wsum = np.zeros_like(sums)
    wcnt = np.zeros_like(cnts)
    for off in range(-half, half + 1):
        wsum += np.roll(sums, off, axis=0)
        wcnt += np.roll(cnts, off, axis=0)
    with np.errstate(invalid='ignore', divide='ignore'):
        clim = np.where(wcnt > 0, wsum / wcnt, np.nan)
    clim = circular_running_mean(_fill_feb29(clim), smooth_days, axis=0)
    return xr.DataArray(clim.astype(np.float32),
                        dims=('doy', 'lat', 'lon'),
                        coords={'doy': np.arange(1, 367), 'lat': base.lat,
                                'lon': base.lon},
                        name=f'{var}_clim',
                        attrs={'clim_years': f'{clim_years[0]}-{clim_years[1]}',
                               'window_days': window_days,
                               'smooth_days': smooth_days})


def latest_anomaly_map(ds, ndays=7, clim_years=(1991, 2020), var='sst',
                       clim=None):
    """Map of the most recent ``ndays`` mean SST minus its day-of-year climatology.

    Parameters
    ----------
    ds : xarray.Dataset with dims (time, lat, lon)
    ndays : int
        Number of most recent days to average.
    clim_years : (int, int)
        Baseline for the climatology (ignored if ``clim`` is given).
    var : str
    clim : xarray.DataArray, optional
        Output of :func:`gridded_climatology` to avoid recomputation.

    Returns
    -------
    xarray.DataArray (lat, lon) of the anomaly in degrees C with attrs
    ``start``, ``end`` (dates averaged) and ``clim_years``.

    Generated by JXP and Claude
    """
    if clim is None:
        clim = gridded_climatology(ds, clim_years=clim_years, var=var)
    recent = ds[var].isel(time=slice(-ndays, None)).load()
    idoy = doy366(recent.time.values)
    # Climatology for the same calendar days, averaged the same way
    clim_recent = clim.isel(doy=idoy - 1).mean(dim='doy', skipna=True)
    anom = (recent.mean(dim='time', skipna=True) - clim_recent.values)
    anom.name = f'{var}_anom'
    anom.attrs = {'long_name': f'{ndays}-day mean {var} anomaly',
                  'units': 'degC',
                  'start': f'{pd.Timestamp(recent.time.values[0]):%Y-%m-%d}',
                  'end': f'{pd.Timestamp(recent.time.values[-1]):%Y-%m-%d}',
                  'clim_years': clim.attrs.get('clim_years',
                                               f'{clim_years[0]}-{clim_years[1]}')}
    return anom


