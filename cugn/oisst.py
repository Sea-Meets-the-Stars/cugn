def year_file(year):
    """Path of the regional OISST file for one year.

    Parameters
    ----------
    year : int

    Returns
    -------
    str : ``OISST_DIR/oisst_ccs_{year}.nc``

    Generated by JXP and Claude
    """
    return os.path.join(OISST_DIR, f'oisst_ccs_{year}.nc')


def canonical_grid(lat_range=LAT_RANGE, lon_range=LON_RANGE):
    """Return the 1/4 degree OISST cell-centre coordinates inside the region.

    Parameters
    ----------
    lat_range, lon_range : (float, float)
        Inclusive bounds (degrees N, degrees E in -180..180).

    Returns
    -------
    lat, lon : np.ndarray (float32)
        Cell centres at x.125, x.375, ... inside the bounds.

    Generated by JXP and Claude
    """
    # OISST cells are centred on multiples of 0.25 offset by 0.125
    def centres(lo, hi):
        first = np.floor(lo / 0.25) * 0.25 + 0.125
        vals = np.arange(first, hi + 1e-6, 0.25)
        return vals[(vals >= lo) & (vals <= hi)].astype(np.float32)
    return centres(*lat_range), centres(*lon_range)


def _snap_to_grid(ds, lat_range=LAT_RANGE, lon_range=LON_RANGE):
    """Replace lat/lon coordinates by the canonical float32 grid values.

    Files from ERDDAP and NCEI describe the same grid but may differ in
    the last bits of the coordinate floats, which would break exact
    alignment when concatenating.  This asserts the grids agree to 1e-3
    degrees and then overwrites the coordinates.

    Parameters
    ----------
    ds : xarray.Dataset with ``lat`` and ``lon`` coordinates

    Returns
    -------
    xarray.Dataset

    Generated by JXP and Claude
    """
    lat, lon = canonical_grid(lat_range, lon_range)
    # ERDDAP picks the *nearest* grid index to each requested bound, so the
    # returned box may include one extra row/column just outside the range;
    # trim to the exact bounds first
    ds = ds.sortby('lat').sortby('lon')
    ds = ds.sel(lat=slice(lat_range[0], lat_range[1]),
                lon=slice(lon_range[0], lon_range[1]))
    if ds.lat.size != lat.size or ds.lon.size != lon.size:
        raise ValueError('Regional grid has unexpected shape: '
                         f'{ds.lat.size}x{ds.lon.size} vs {lat.size}x{lon.size}')
    if not (np.allclose(ds.lat.values, lat, atol=1e-3)
            and np.allclose(ds.lon.values, lon, atol=1e-3)):
        raise ValueError('Regional grid does not match the canonical grid')
    return ds.assign_coords(lat=('lat', lat), lon=('lon', lon))


def _get(url, stream=False, retries=N_RETRY, pause=RETRY_PAUSE):
    """HTTP GET with retries; returns None on a 404.

    Parameters
    ----------
    url : str
    stream : bool
        Passed to requests (True for large downloads).
    retries : int
        Number of attempts before raising.
    pause : float
        Seconds to wait between attempts.

    Returns
    -------
    requests.Response or None
        None if the server answered 404 (file does not exist).

    Raises
    ------
    RuntimeError if every attempt fails with a non-404 error.

    Generated by JXP and Claude
    """
    last_err = None
    for attempt in range(retries):
        try:
            resp = requests.get(url, stream=stream, timeout=HTTP_TIMEOUT,
                                headers=HEADERS)
            if resp.status_code == 404:
                resp.close()
                return None
            resp.raise_for_status()
            return resp
        except (requests.RequestException, OSError) as err:
            last_err = err
            # Wait before retrying (server may be busy)
            time.sleep(pause)
    raise RuntimeError(f'Failed to GET {url} after {retries} attempts: {last_err}')


def _download_to_file(url, outfile):
    """Stream a URL to ``outfile``; returns False on 404.

    Parameters
    ----------
    url : str
    outfile : str
        Destination path (written in chunks).

    Returns
    -------
    bool : True if the file was written, False if the URL returned 404.

    Generated by JXP and Claude
    """
    resp = _get(url, stream=True)
    if resp is None:
        return False
    with open(outfile, 'wb') as fh:
        for chunk in resp.iter_content(chunk_size=1 << 20):
            fh.write(chunk)
    resp.close()
    return True


def _standardize(ds):
    """Bring an OISST dataset to the archive layout.

    Drops the singleton ``zlev`` dimension, renames latitude/longitude to
    lat/lon, keeps only ``sst`` and ``anom``, floors the time stamps to
    midnight (OISST stamps daily fields at 12:00Z), sorts lat/lon, and
    adds a boolean ``preliminary`` variable (False) if missing.

    Parameters
    ----------
    ds : xarray.Dataset

    Returns
    -------
    xarray.Dataset with dims (time, lat, lon)

    Generated by JXP and Claude
    """
    if 'zlev' in ds.dims:
        ds = ds.isel(zlev=0, drop=True)
    elif 'zlev' in ds.coords:
        ds = ds.drop_vars('zlev')
    rename = {}
    if 'latitude' in ds.dims:
        rename['latitude'] = 'lat'
    if 'longitude' in ds.dims:
        rename['longitude'] = 'lon'
    if rename:
        ds = ds.rename(rename)
    keep = [v for v in VARS if v in ds.data_vars]
    extra = ['preliminary'] if 'preliminary' in ds.data_vars else []
    ds = ds[keep + extra]
    # Floor time to the day so ERDDAP (12:00Z) and NCEI stamps agree
    ds = ds.assign_coords(time=ds.time.dt.floor('D').values.astype('datetime64[ns]'))
    ds = ds.sortby('lat').sortby('lon')
    if 'preliminary' not in ds.data_vars:
        ds['preliminary'] = ('time', np.zeros(ds.time.size, dtype=bool))
    ds['preliminary'].attrs['long_name'] = 'True if from an NCEI preliminary file'
    for v in keep:
        ds[v] = ds[v].astype(np.float32)
    return ds


def subset_global(ds, lat_range=LAT_RANGE, lon_range=LON_RANGE):
    """Subset a global 0..360 longitude OISST file to the region.

    Converts longitude to -180..180, sorts, and selects the lat/lon box.
    Used for NCEI daily files.

    Parameters
    ----------
    ds : xarray.Dataset with dims including ``lat`` and ``lon``
        (or ``latitude``/``longitude``); lon may be 0..360.
    lat_range, lon_range : (float, float)
        Inclusive bounds; lon_range is in -180..180.

    Returns
    -------
    xarray.Dataset restricted to the box with lon in -180..180.

    Generated by JXP and Claude
    """
    rename = {}
    if 'latitude' in ds.dims:
        rename['latitude'] = 'lat'
    if 'longitude' in ds.dims:
        rename['longitude'] = 'lon'
    if rename:
        ds = ds.rename(rename)
    # Wrap longitudes into -180..180 and sort so slicing works
    lon = ((ds.lon.values + 180.) % 360.) - 180.
    ds = ds.assign_coords(lon=('lon', lon.astype(ds.lon.dtype))).sortby('lon')
    ds = ds.sortby('lat')
    return ds.sel(lat=slice(*lat_range), lon=slice(*lon_range))


def _write_netcdf(ds, path):
    """Write the archive dataset atomically (``.part`` then rename) and verify.

    Parameters
    ----------
    ds : xarray.Dataset
    path : str

    Returns
    -------
    str : path

    Generated by JXP and Claude
    """
    part = path + '.part'
    encoding = {v: {'zlib': True, 'complevel': 4, 'dtype': 'float32',
                    '_FillValue': np.float32(np.nan)}
                for v in VARS if v in ds.data_vars}
    encoding['time'] = {'units': 'days since 1970-01-01', 'dtype': 'int32'}
    ds.attrs['title'] = 'NOAA OISST v2.1 daily, California Current subset'
    ds.attrs['source'] = f'{ERDDAP_BASE} and {NCEI_BASE}'
    ds.attrs['history'] = f'Written {datetime.datetime.now(datetime.timezone.utc):%Y-%m-%dT%H:%MZ} by cugn.oisst'
    ds.load().to_netcdf(part, engine='netcdf4', encoding=encoding)
    # Verify the file opens and has the expected content before accepting it
    with xr.open_dataset(part) as chk:
        assert all(v in chk.data_vars for v in VARS), 'missing variables'
        assert chk.time.size > 0, 'empty time axis'
    os.replace(part, path)
    return path


def _today_utc():
    """Today's date (UTC) as a midnight pandas.Timestamp.

    Returns
    -------
    pandas.Timestamp

    Generated by JXP and Claude
    """
    return pd.Timestamp(datetime.datetime.now(datetime.timezone.utc).date())


