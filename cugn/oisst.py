def load(start_year=FIRST_YEAR, end_year=None):
    """Open the regional archive for a range of years.

    Parameters
    ----------
    start_year : int
    end_year : int, optional
        Defaults to the latest year present on disk.

    Returns
    -------
    xarray.Dataset
        Lazily loaded (dask) if available, dims (time, lat, lon), sorted in
        time with duplicate days dropped; variables sst, anom, preliminary.

    Generated by JXP and Claude
    """
    if end_year is None:
        end_year = _today_utc().year
    paths = [year_file(y) for y in range(start_year, end_year + 1)]
    paths = [p for p in paths if os.path.exists(p)]
    if len(paths) == 0:
        raise FileNotFoundError(f'No OISST files in {OISST_DIR}; run update()')
    try:
        # Lazy, chunked per file (requires dask)
        ds = xr.open_mfdataset(paths, combine='nested', concat_dim='time',
                               join='exact', data_vars='minimal',
                               coords='minimal', compat='override')
    except (ImportError, ValueError):
        ds = xr.concat([xr.open_dataset(p) for p in paths], dim='time',
                       join='exact')
    ds = ds.sortby('time')
    ds = ds.drop_duplicates('time', keep='last')
    return ds


def box_mean(ds, lat_range, lon_range, var='sst'):
    """Area-weighted (cos latitude) mean time series over a lat/lon box.

    Parameters
    ----------
    ds : xarray.Dataset with dims (time, lat, lon)
    lat_range : (float, float)
        Latitude bounds (either order).
    lon_range : (float, float)
        Longitude bounds in -180..180 (either order).
    var : str
        Variable to average ('sst' or 'anom').

    Returns
    -------
    pandas.Series indexed by time (NaN grid cells, e.g. land, are ignored).

    Generated by JXP and Claude
    """
    la = sorted(lat_range)
    lo = sorted(lon_range)
    sub = ds[var].sel(lat=slice(la[0], la[1]), lon=slice(lo[0], lo[1]))
    if sub.lat.size == 0 or sub.lon.size == 0:
        raise ValueError('box contains no grid cells')
    # Grid cells shrink with cos(latitude); weight accordingly
    weights = np.cos(np.deg2rad(sub.lat))
    weights = weights.broadcast_like(sub.isel(time=0, drop=True))
    mean = sub.weighted(weights.fillna(0)).mean(dim=('lat', 'lon'), skipna=True)
    ser = mean.to_series()
    ser.name = var
    return ser


def line_track_mean(ds, line='66.7', var='sst', npts=41):
    """Mean time series along the straight track of a CUGN line.

    Samples ``npts`` equally spaced points between the line endpoints from
    ``cugn.utils.line_endpoints`` at the nearest OISST grid cell and
    averages them (NaN cells, e.g. land, ignored).

    Parameters
    ----------
    ds : xarray.Dataset with dims (time, lat, lon)
    line : str
        CUGN line identifier ('56.0', '66.7', '80.0', '90.0', 'al').
    var : str
    npts : int
        Number of sample points along the track.

    Returns
    -------
    pandas.Series indexed by time.

    Generated by JXP and Claude
    """
    lonendpts, latendpts = utils.line_endpoints(line)
    lons = np.linspace(lonendpts[0], lonendpts[1], npts)
    lats = np.linspace(latendpts[0], latendpts[1], npts)
    # Vectorized nearest-neighbour sampling along a new 'pt' dimension
    pts = ds[var].sel(lat=xr.DataArray(lats, dims='pt'),
                      lon=xr.DataArray(lons, dims='pt'), method='nearest')
    ser = pts.mean(dim='pt', skipna=True).to_series()
    ser.name = f'{var}_line{line}'
    return ser


