def aggregate_last_time():
    """Query the ERDDAP aggregate for its last time step.

    Returns
    -------
    pandas.Timestamp
        Date (midnight) of the last day in ``ncdcOisst21Agg_LonPM180``.

    Generated by JXP and Claude
    """
    url = ERDDAP_BASE + '.csv?time%5Blast%5D'
    resp = _get(url)
    if resp is None:
        raise RuntimeError('ERDDAP aggregate time[last] query returned 404')
    # CSV has a header line, a units line, then the value
    lines = [ln.strip() for ln in resp.text.strip().splitlines() if ln.strip()]
    tval = pd.Timestamp(lines[-1])
    return tval.tz_convert(None).normalize() if tval.tzinfo else tval.normalize()


def erddap_url(t0, t1, lat_range=LAT_RANGE, lon_range=LON_RANGE):
    """Build the ERDDAP griddap URL for sst and anom over a time span.

    Parameters
    ----------
    t0, t1 : pandas.Timestamp
        First and last day (inclusive); stamped at 12:00Z in the query.
    lat_range, lon_range : (float, float)

    Returns
    -------
    str

    Generated by JXP and Claude
    """
    tsel = (f'%5B({t0:%Y-%m-%d}T12:00:00Z):({t1:%Y-%m-%d}T12:00:00Z)%5D'
            '%5B(0.0)%5D'
            f'%5B({lat_range[0]}):({lat_range[1]})%5D'
            f'%5B({lon_range[0]}):({lon_range[1]})%5D')
    return ERDDAP_BASE + '.nc?' + ','.join(f'{v}{tsel}' for v in VARS)


def download_erddap(t0, t1, tmpfile):
    """Download an ERDDAP regional subset for [t0, t1] and return it standardized.

    Parameters
    ----------
    t0, t1 : pandas.Timestamp
        Inclusive day range; t1 must not exceed ``aggregate_last_time()``.
    tmpfile : str
        Scratch path for the raw download (deleted afterwards).

    Returns
    -------
    xarray.Dataset (time, lat, lon) with sst, anom, preliminary=False

    Generated by JXP and Claude
    """
    url = erddap_url(t0, t1)
    ok = _download_to_file(url, tmpfile)
    if not ok:
        raise RuntimeError(f'ERDDAP returned 404 for {t0:%Y-%m-%d}..{t1:%Y-%m-%d}')
    try:
        with xr.open_dataset(tmpfile) as raw:
            ds = _standardize(raw).load()
    finally:
        if os.path.exists(tmpfile):
            os.remove(tmpfile)
    return _snap_to_grid(ds)


def ncei_url(day, preliminary=False):
    """URL of an NCEI daily global OISST file.

    Parameters
    ----------
    day : pandas.Timestamp
    preliminary : bool
        If True, use the ``_preliminary`` file name.

    Returns
    -------
    str

    Generated by JXP and Claude
    """
    suffix = '_preliminary' if preliminary else ''
    return (f'{NCEI_BASE}/{day:%Y%m}/'
            f'oisst-avhrr-v02r01.{day:%Y%m%d}{suffix}.nc')


def download_ncei_day(day, tmpfile, try_preliminary=True):
    """Fetch one NCEI daily file, subset to the region, and delete the global file.

    Tries the final file first, then (optionally) the preliminary one.

    Parameters
    ----------
    day : pandas.Timestamp
    tmpfile : str
        Scratch path for the ~1.6 MB global file (deleted afterwards).
    try_preliminary : bool
        Whether to fall back to the ``_preliminary`` file.

    Returns
    -------
    xarray.Dataset or None
        Standardized regional dataset for that day (with ``preliminary``
        set accordingly), or None if neither file exists (404).

    Generated by JXP and Claude
    """
    options = [False, True] if try_preliminary else [False]
    for prelim in options:
        ok = _download_to_file(ncei_url(day, prelim), tmpfile)
        time.sleep(REQUEST_PAUSE)
        if not ok:
            continue
        try:
            with xr.open_dataset(tmpfile) as raw:
                ds = _standardize(subset_global(raw)).load()
        finally:
            if os.path.exists(tmpfile):
                os.remove(tmpfile)
        ds['preliminary'] = ('time', np.full(ds.time.size, prelim, dtype=bool))
        ds['preliminary'].attrs['long_name'] = 'True if from an NCEI preliminary file'
        return _snap_to_grid(ds)
    return None


def _combine(parts):
    """Concatenate datasets along time, sort, and drop duplicate days (keep last).

    Parameters
    ----------
    parts : list of xarray.Dataset

    Returns
    -------
    xarray.Dataset

    Generated by JXP and Claude
    """
    parts = [p for p in parts if p is not None and p.time.size > 0]
    if len(parts) == 0:
        raise ValueError('nothing to combine')
    ds = xr.concat(parts, dim='time', join='exact', combine_attrs='override')
    ds = ds.sortby('time')
    # keep='last' so later parts (fresher data) override earlier ones
    ds = ds.drop_duplicates('time', keep='last')
    return ds


def expected_days(year, today=None):
    """Calendar days of ``year`` that could exist in the archive (up to today).

    Parameters
    ----------
    year : int
    today : pandas.Timestamp, optional

    Returns
    -------
    pandas.DatetimeIndex

    Generated by JXP and Claude
    """
    today = _today_utc() if today is None else today
    y0 = pd.Timestamp(year=year, month=1, day=1)
    y1 = min(pd.Timestamp(year=year, month=12, day=31), today)
    return pd.date_range(y0, y1, freq='D') if y1 >= y0 else pd.DatetimeIndex([])


def download_year(year, overwrite=False, agg_last=None, verbose=True):
    """Build the regional OISST file for one calendar year.

    The part of the year up to the ERDDAP aggregate's last day is fetched
    in a single ERDDAP request.  Every calendar day of the year still
    missing afterwards -- days after the aggregate end, and the days the
    aggregate itself lacks (it has ~1200 gaps, mostly 1992-1998) -- is
    fetched from NCEI daily files (final first, then preliminary; days
    that 404 are skipped).  When a file already exists and ``overwrite``
    is True, its non-preliminary days are reused (so gap-fills are not
    re-downloaded), the ERDDAP part is re-fetched and takes precedence,
    and preliminary days are re-tried as finals (kept as preliminary if
    no final exists yet).

    Parameters
    ----------
    year : int
    overwrite : bool
        If False and the file exists, return it without any network access.
    agg_last : pandas.Timestamp, optional
        Last day of the ERDDAP aggregate (queried if None).
    verbose : bool

    Returns
    -------
    str : path of ``oisst_ccs_{year}.nc``

    Generated by JXP and Claude
    """
    os.makedirs(OISST_DIR, exist_ok=True)
    path = year_file(year)
    if os.path.exists(path) and not overwrite:
        return path
    if agg_last is None:
        agg_last = aggregate_last_time()
    today = _today_utc()
    y0 = pd.Timestamp(year=year, month=1, day=1)
    y1 = pd.Timestamp(year=year, month=12, day=31)
    if y0 > today:
        raise ValueError(f'{year} is in the future')

    parts = []
    # --- Reuse what is already on disk: finals kept, prelims re-checked below
    existing_prelim = {}
    if os.path.exists(path):
        with xr.open_dataset(path) as old:
            old = old.load()
        old = _snap_to_grid(_standardize(old))
        finals = old.sel(time=~old.preliminary.values)
        if finals.time.size > 0:
            parts.append(finals)
        prelims = old.sel(time=old.preliminary.values)
        for tt in prelims.time.values:
            existing_prelim[pd.Timestamp(tt)] = prelims.sel(time=[tt])

    # --- ERDDAP part: y0 .. min(y1, agg_last); overrides existing days
    t1 = min(y1, agg_last)
    if t1 >= y0:
        if verbose:
            print(f'[oisst] {year}: ERDDAP {y0:%Y-%m-%d}..{t1:%Y-%m-%d}', flush=True)
        tmp = os.path.join(OISST_DIR, f'oisst_ccs_{year}.erddap.tmp')
        erddap_ds = download_erddap(y0, t1, tmp)
        # ERDDAP snaps the time bounds to the nearest *existing* index, so
        # when Jan 1 or Dec 31 is a gap the response spills into the
        # neighbouring year; keep only this calendar year
        parts.append(erddap_ds.sel(time=slice(y0, y1)))
        time.sleep(REQUEST_PAUSE)

    # --- NCEI part: every expected day not yet held as a final field
    have = pd.DatetimeIndex([])
    for p in parts:
        have = have.union(pd.DatetimeIndex(p.time.values))
    missing = expected_days(year, today).difference(have)
    n_new = n_prelim = n_skip = 0
    if len(missing) > 0:
        if verbose:
            print(f'[oisst] {year}: NCEI for {len(missing)} missing day(s) '
                  f'({missing[0]:%Y-%m-%d}..{missing[-1]:%Y-%m-%d})', flush=True)
        tmp = os.path.join(OISST_DIR, f'oisst_ccs_{year}.ncei.tmp')
        prelim_days = pd.DatetimeIndex(list(existing_prelim.keys()))
        for day in missing:
            if day in prelim_days:
                # Only look for the final; otherwise keep the stored preliminary
                ds_day = download_ncei_day(day, tmp, try_preliminary=False)
                if ds_day is None:
                    ds_day = existing_prelim[prelim_days[prelim_days == day][0]]
                    n_prelim += 1
                else:
                    n_new += 1
            else:
                ds_day = download_ncei_day(day, tmp, try_preliminary=True)
                if ds_day is None:
                    n_skip += 1
                    continue                   # not published (yet)
                n_new += 1
                n_prelim += int(bool(ds_day.preliminary.values[0]))
            parts.append(ds_day)
        if verbose:
            print(f'[oisst] {year}: NCEI {n_new} new day(s), {n_prelim} preliminary, '
                  f'{n_skip} unavailable', flush=True)

    ds = _combine(parts)
    ds = ds.sel(time=slice(y0, y1))        # belt and braces: this year only
    _write_netcdf(ds, path)
    if verbose:
        print(f'[oisst] wrote {path} ({ds.time.size} days, '
              f'{os.path.getsize(path)/1e6:.1f} MB)', flush=True)
    return path


def update(start_year=FIRST_YEAR, end_year=None, verbose=True):
    """Download missing years and refresh incomplete or current-year files.

    Years whose file is missing are downloaded.  A file is rebuilt when
    its year is at or after the ERDDAP aggregate's last year, when it
    contains preliminary days, or when its days are not exactly the
    calendar days of the year (aggregate gaps not yet filled from NCEI,
    or spill-over days from a neighbouring year).  Rebuilding reuses
    the final days already on disk, re-fetches the ERDDAP part, tops up
    from NCEI, and replaces preliminary days by finals when available.

    Parameters
    ----------
    start_year : int
    end_year : int, optional
        Defaults to the current year (UTC).
    verbose : bool

    Returns
    -------
    list of str : paths of all year files in the range

    Generated by JXP and Claude
    """
    os.makedirs(OISST_DIR, exist_ok=True)
    today = _today_utc()
    if end_year is None:
        end_year = today.year
    agg_last = aggregate_last_time()
    if verbose:
        print(f'[oisst] ERDDAP aggregate ends {agg_last:%Y-%m-%d}; today {today:%Y-%m-%d}',
              flush=True)
    paths = []
    for year in range(start_year, end_year + 1):
        path = year_file(year)
        refresh = year >= agg_last.year
        if os.path.exists(path) and not refresh:
            with xr.open_dataset(path) as old:
                has_prelim = bool(old.preliminary.values.any()) if 'preliminary' in old else True
                have = pd.DatetimeIndex(old.time.values)
            # Refresh if preliminary days remain, or the stored days are not
            # exactly the calendar days of the year (missing or spill-over)
            refresh = has_prelim or not have.equals(expected_days(year, today))
        if os.path.exists(path) and not refresh:
            paths.append(path)
            continue
        paths.append(download_year(year, overwrite=True, agg_last=agg_last,
                                   verbose=verbose))
    return paths


