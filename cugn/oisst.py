# Local archive directory: <data root>/SST/OISST, derived from OS_SPRAY
OISST_DIR = os.path.join(
    os.path.dirname(os.environ['OS_SPRAY'].rstrip('/')), 'SST', 'OISST')

# ERDDAP griddap aggregate (lon in -180..180)
ERDDAP_BASE = ('https://coastwatch.pfeg.noaa.gov/erddap/griddap/'
               'ncdcOisst21Agg_LonPM180')
# NCEI daily global files
NCEI_BASE = ('https://www.ncei.noaa.gov/data/'
             'sea-surface-temperature-optimum-interpolation/v2.1/access/avhrr')

# Regional box (inclusive edges; the 1/4 degree grid cells are at x.125, x.375, ...)
LAT_RANGE = (25.0, 50.0)
LON_RANGE = (-135.0, -115.0)

FIRST_YEAR = 1991          # first year of the local archive
VARS = ('sst', 'anom')     # variables kept from OISST

# Politeness settings for HTTP requests
N_RETRY = 3
RETRY_PAUSE = 15.0         # seconds between retries
REQUEST_PAUSE = 1.0        # seconds between successive requests
HTTP_TIMEOUT = 900         # seconds (ERDDAP yearly requests can be slow)
HEADERS = {'User-Agent': 'cugn-oisst/0.1 (UCSC; jxp@ucsc.edu)'}

# Hobday et al. (2018) category labels indexed by integer category
CATEGORY_LABELS = {0: '', 1: 'Moderate', 2: 'Strong', 3: 'Severe', 4: 'Extreme'}


