""" NOAA OISST v2.1 daily SST for the California Current region.

Downloads and serves a regional subset (25-50 N, 135-115 W) of the
NOAA 1/4 degree daily Optimum Interpolation SST (OISST v2.1), one NetCDF
file per year in OISST_DIR, and provides analysis helpers (box means,
along-track means for the CUGN lines, Hobday et al. marine heatwave
detection, and a recent-anomaly map) used in the 2026-27 El Nino report
for CUGN Line 66.7.

Two data sources are combined:
  1. The CoastWatch ERDDAP aggregate ``ncdcOisst21Agg_LonPM180`` which
     supports server-side subsetting but lags NCEI by ~2 weeks.
  2. NCEI's daily global files (final, then ``_preliminary``) for the
     days after the end of the aggregate.

Run ``python -m cugn.oisst`` to build/refresh the local archive.

Generated by JXP and Claude
"""

import os
import time
import datetime
import warnings

import numpy as np
