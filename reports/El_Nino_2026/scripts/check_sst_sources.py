""" Which satellite SST products could feed a close-up Monterey Bay map, and how current is each?

Written for the November 2026 newsletter SST figure (prompt "SST figure 1" of
`prompts/elnino_nov2026_prompts.md`): the September map used NOAA OISST v2.1 at
1/4 degree, which puts only ~3 x 3 cells across Monterey Bay, so zooming in
needs a finer product.  For each candidate this script asks the ERDDAP server
for the first and last time step, the grid spacing near Monterey Bay and the
variables, and pulls the latest day over the bay to count valid (ocean, cloud-
free) cells.  It also reports where the OISST archive on this laptop ends, and
the last day NCEI has published, because the anomaly baseline (1991-2020) comes
from OISST.

Candidates (all gap-filled "L4" analyses except the ACSPO L3S composite):

  * NOAA OISST v2.1, 0.25 deg, final and preliminary aggregates (current source)
  * NOAA Coral Reef Watch CoralTemp v3.1, 0.05 deg, 1985-present
  * NOAA Geo-polar Blended, night-only (2002-) and day+night (2019-), 0.05 deg
  * JPL MUR v4.1, 0.01 deg, 2002-present, plus its ready-made anomaly product
    (relative to a 2003-2014 MUR climatology)
  * NOAA ACSPO L3S-LEO 7-day composite, 0.02 deg (not gap-filled: clouds leave holes)

Usage (ocean14):
    python reports/El_Nino_2026/scripts/check_sst_sources.py

Writes `reports/El_Nino_2026/figs/sst_sources_check_<YYYY-MM-DD>.json`.

Generated by JXP and Claude
"""
import os
import io
import json

import numpy as np
import pandas as pd
import requests

from cugn import oisst

# Monterey Bay close-up used to sample the latest day (a little larger than the bay)
BAY = dict(lat=(36.4, 37.1), lon=(-122.3, -121.75))
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'figs')
PFEG = 'https://coastwatch.pfeg.noaa.gov/erddap'
CWNOAA = 'https://coastwatch.noaa.gov/erddap'
# (label, server, dataset id, SST variable, note)
CANDIDATES = [
    ('OISST v2.1 final', PFEG, 'ncdcOisst21Agg_LonPM180', 'sst', '0.25 deg, current source'),
    ('OISST v2.1 preliminary', PFEG, 'ncdcOisst21NrtAgg_LonPM180', 'sst', '0.25 deg, NRT'),
    ('CoralTemp v3.1', CWNOAA, 'noaacrwsstDaily', 'analysed_sst', '0.05 deg, 1985-'),
    ('Geo-polar Blended night', PFEG, 'nesdisBLENDEDsstDaily', 'analysed_sst', '0.05 deg, 2002-'),
    ('Geo-polar Blended day+night', PFEG, 'nesdisBLENDEDsstDNDaily', 'analysed_sst', '0.05 deg, 2019-'),
    ('MUR v4.1', PFEG, 'jplMURSST41', 'analysed_sst', '0.01 deg, 2002-'),
    ('MUR v4.1 anomaly', PFEG, 'jplMURSST41anom1day', 'sstAnom', '0.01 deg, vs 2003-2014'),
    ('ACSPO L3S-LEO 7-day NRT', PFEG, 'noaacwLEOACSPOSSTL3SCWeeklyNRT', 'sea_surface_temperature',
     '0.02 deg, not gap-filled'),
]


def _get(url, timeout=90):
    """ GET a URL and return the text.

    Parameters
    ----------
    url : str
    timeout : float, seconds

    Returns
    -------
    str : response body

    Generated by JXP and Claude
    """
    r = requests.get(url, timeout=timeout)
    r.raise_for_status()
    return r.text


def dataset_info(server, dsid):
    """ Variables, time coverage and grid spacing of an ERDDAP griddap dataset.

    Parameters
    ----------
    server : str, ERDDAP base URL (ending in /erddap)
    dsid : str, dataset id

    Returns
    -------
    dict : `variables` (list), `time_start`, `time_end` (str), `dlat` (deg),
        `lon_range` (min, max: tells -180/180 from 0/360 grids)

    Generated by JXP and Claude
    """
    info = pd.read_csv(io.StringIO(_get(f'{server}/info/{dsid}/index.csv')))
    variables = info.loc[info['Row Type'] == 'variable', 'Variable Name'].tolist()
    attr = info[info['Row Type'] == 'attribute']

    def gattr(name):
        hit = attr[(attr['Variable Name'] == 'NC_GLOBAL') & (attr['Attribute Name'] == name)]
        return hit['Value'].iloc[0] if len(hit) else None

    def vattr(var, name):
        hit = attr[(attr['Variable Name'] == var) & (attr['Attribute Name'] == name)]
        return hit['Value'].iloc[0] if len(hit) else None

    lon_rng = vattr('longitude', 'actual_range')
    return dict(variables=variables,
                time_start=gattr('time_coverage_start'), time_end=gattr('time_coverage_end'),
                dlat=float(gattr('geospatial_lat_resolution')) if gattr('geospatial_lat_resolution') else None,
                lon_range=[float(x) for x in lon_rng.split(',')] if lon_rng else None)


def latest_bay(server, dsid, var, lon_range):
    """ The latest day of one variable over the Monterey Bay close-up.

    Parameters
    ----------
    server, dsid, var : str
    lon_range : (float, float) or None, the dataset's longitude range

    Returns
    -------
    dict : `time` of the last step, `n_cells`, `n_valid` (finite values),
        `mean` of the valid values (in the dataset's units), `nlat`, `nlon`

    Generated by JXP and Claude
    """
    lon0, lon1 = BAY['lon']
    if lon_range is not None and lon_range[0] >= 0:     # 0-360 grid
        lon0, lon1 = lon0 + 360., lon1 + 360.
    dims = _get(f'{server}/info/{dsid}/index.csv')
    # some datasets carry a singleton depth/altitude axis between time and latitude
    extra = '[0]' if (',altitude,' in dims or ',depth,' in dims or ',zlev,' in dims) else ''
    q = (f'{server}/griddap/{dsid}.csv?{var}[last]{extra}'
         f'[({BAY["lat"][0]}):({BAY["lat"][1]})][({lon0}):({lon1})]')
    df = pd.read_csv(io.StringIO(_get(q, timeout=180)), skiprows=[1])
    vals = pd.to_numeric(df[var], errors='coerce').to_numpy()
    return dict(time=str(df['time'].iloc[0]), n_cells=int(vals.size), n_valid=int(np.isfinite(vals).sum()),
                mean=float(np.nanmean(vals)) if np.isfinite(vals).any() else None,
                nlat=int(df['latitude'].nunique()), nlon=int(df['longitude'].nunique()))


def local_oisst():
    """ Where the regional OISST archive on disk ends, and how many days are preliminary.

    Returns
    -------
    dict : `last_day`, `n_days_this_year`, `n_preliminary`, `dir`

    Generated by JXP and Claude
    """
    year = pd.Timestamp.now().year
    ds = oisst.load(start_year=year)
    t = pd.DatetimeIndex(ds.time.values)
    prelim = int(ds['preliminary'].values.astype(bool).sum()) if 'preliminary' in ds else None
    return dict(last_day=str(t[-1].date()), n_days_this_year=int(t.size), n_preliminary=prelim,
                dir=oisst.OISST_DIR)


def ncei_latest(max_back=10):
    """ The most recent day for which NCEI serves an OISST daily file (final or preliminary).

    Parameters
    ----------
    max_back : int, days before today to try

    Returns
    -------
    dict : `last_day` (str or None), `preliminary` (bool), `status` of the last request

    Generated by JXP and Claude
    """
    today = pd.Timestamp.now().normalize()
    status = None
    for k in range(max_back + 1):
        day = today - pd.Timedelta(days=k)
        for prelim in (True, False):
            url = oisst.ncei_url(day, preliminary=prelim)
            try:
                r = requests.head(url, timeout=20, allow_redirects=True)
                status = r.status_code
                if r.status_code == 200:
                    return dict(last_day=str(day.date()), preliminary=prelim, status=status)
            except requests.RequestException as exc:
                status = f'{exc.__class__.__name__}'
    return dict(last_day=None, preliminary=None, status=status)


def main():
    """ Run every check, print a table and write the JSON. Generated by JXP and Claude """
    out = dict(checked=str(pd.Timestamp.now().round('s')), bay_box=BAY, products={})
    try:
        out['local_oisst'] = local_oisst()
    except Exception as exc:
        out['local_oisst'] = {'error': f'{exc.__class__.__name__}: {exc}'}
    out['ncei_oisst'] = ncei_latest()
    for label, server, dsid, var, note in CANDIDATES:
        rec = dict(server=server, dataset=dsid, variable=var, note=note)
        try:
            rec.update(dataset_info(server, dsid))
            rec['latest_bay'] = latest_bay(server, dsid, var, rec.get('lon_range'))
        except Exception as exc:   # a dead server is a result, not a crash
            rec['error'] = f'{exc.__class__.__name__}: {str(exc)[:200]}'
        out['products'][label] = rec
        print(f"{label:28s} {rec.get('time_start', '')!s:22.10s} -> {rec.get('time_end', '')!s:22.10s} "
              f"dlat={rec.get('dlat')} "
              + (f"bay {rec['latest_bay']['nlat']}x{rec['latest_bay']['nlon']} "
                 f"valid {rec['latest_bay']['n_valid']}/{rec['latest_bay']['n_cells']} "
                 f"mean {rec['latest_bay']['mean']}" if 'latest_bay' in rec else rec.get('error', '')),
              flush=True)
    print('local OISST:', out['local_oisst'])
    print('NCEI OISST :', out['ncei_oisst'])
    path = os.path.join(OUT_DIR, f'sst_sources_check_{pd.Timestamp.now():%Y-%m-%d}.json')
    with open(path, 'w') as fh:
        json.dump(out, fh, indent=2)
    print('wrote', os.path.normpath(path))


if __name__ == '__main__':
    main()
