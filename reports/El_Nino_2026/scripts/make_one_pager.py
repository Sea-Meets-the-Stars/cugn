def c2f(dc):
    """ Convert a temperature *difference* from °C to °F. Generated by JXP and Claude """
    return 1.8 * dc


def fig_past_events(idx, path):
    """ Redesigned event composite: four curves by calendar month from July.

    Parameters
    ----------
    idx : pandas.DataFrame with `time`, `index` (the Line 66.7 index)
    path : str output PNG

    Returns
    -------
    dict of the peak index per curve (for the text).

    Generated by JXP and Claude
    """
    s = idx.set_index('time')['index']
    curves = [("2014–15 marine heatwave (\"the Blob\")", 2014, 'tab:orange', 2.2, '-'),
              ("2015–16 El Niño", 2015, 'tab:red', 2.2, '-'),
              ("The past year (from July 2025)", 2025, 'tab:green', 2.8, '-'),
              ("Now (from July 2026)", 2026, 'k', 4.0, '-')]
    plt.rcParams.update({'font.size': 14})
    fig, ax = plt.subplots(figsize=(11, 6.2))
    peaks = {}
    for label, y0, col, lw, ls in curves:
        t0 = pd.Timestamp(f'{y0}-07-01'); t1 = pd.Timestamp(f'{y0 + 1}-06-30')
        v = s.loc[t0:t1].dropna()
        m = (v.index - t0).days / 30.44
        ax.plot(m, v.values, color=col, lw=lw, ls=ls, label=label, solid_capstyle='round')
        peaks[label] = float(v.max())
        if y0 == 2026:  # "we are here"
            ax.annotate('we are here', xy=(m[-1], v.values[-1]), xytext=(m[-1] + 0.6, v.values[-1] + 0.35),
                        fontsize=14, fontweight='bold',
                        arrowprops=dict(arrowstyle='->', lw=2))
    ax.axhline(0, color='0.4', lw=0.8)
    ax.set_xticks(range(12)); ax.set_xticklabels(MONTHS); ax.set_xlim(0, 12)
    ax.set_ylim(-0.1, 2.3)
    ax.set_ylabel('Ocean temperature above normal (°C)', fontsize=15)
    axr = ax.twinx(); axr.set_ylim(c2f(-0.1), c2f(2.3)); axr.set_ylabel('(°F)', fontsize=15)
    ax.set_title('Monterey Bay waters are entering this El Niño warmer than in any past event',
                 fontsize=16, fontweight='bold', pad=22)
    fig.text(0.5, 0.905, 'Upper ocean (top 100 m) within 200 km of the coast on Scripps glider Line 66.7, '
             'relative to 2008–2013 normals; 3-month averages', ha='center', fontsize=11.5, color='0.3')
    ax.legend(loc='upper left', fontsize=12.5, frameon=False)
    ax.grid(axis='y', lw=0.3, alpha=0.6)
    fig.tight_layout()
    fig.savefig(path, dpi=160); plt.close(fig)
    return peaks


def fig_index_oni(idx, oni, path):
    """ Simplified dual-axis figure: Line 66.7 index (left) and NOAA ONI (right), large labels.

    Parameters
    ----------
    idx : pandas.DataFrame with `time`, `index`
    oni : pandas.DataFrame with `time`, `oni`
    path : str output PNG

    Generated by JXP and Claude
    """
    plt.rcParams.update({'font.size': 14})
    fig, ax = plt.subplots(figsize=(11, 5.6))
    ax.fill_between(idx.time, 0, idx['index'].fillna(0), where=idx['index'].fillna(0) > 0,
                    color='tab:red', alpha=0.18, lw=0)
    ax.fill_between(idx.time, 0, idx['index'].fillna(0), where=idx['index'].fillna(0) < 0,
                    color='tab:blue', alpha=0.18, lw=0)
    ax.plot(idx.time, idx['index'], color='tab:green', lw=2.6, label='Monterey Bay ocean temperature (Line 66.7 gliders)')
    ax.axhline(0, color='0.4', lw=0.8)
    ax.set_ylabel('Ocean temperature above normal (°C)', fontsize=15)
    ax.set_ylim(-2.6, 2.6)
    axr = ax.twinx()
    axr.plot(oni.time, oni.oni, color='k', lw=2.4, label='El Niño index (NOAA ONI)')
    axr.set_ylim(-4, 4); axr.set_ylabel('El Niño index (°C)   El Niño ↑  La Niña ↓', fontsize=14)
    ax.set_xlim(pd.Timestamp('2007-01-01'), pd.Timestamp('2027-03-01'))
    ax.xaxis.set_major_locator(mdates.YearLocator(2)); ax.xaxis.set_major_formatter(mdates.DateFormatter('%Y'))
    for txt, x, y in [("2014–15 \"Blob\"", '2014-08-01', 2.3), ('2015–16 El Niño', '2015-12-01', 1.98),
                      ('past year', '2025-10-15', 2.2), ('2009–10 El Niño', '2010-01-01', 1.25)]:
        ax.text(pd.Timestamp(x), y, txt, fontsize=12.5, ha='center', color='0.25')
    h1, l1 = ax.get_legend_handles_labels(); h2, l2 = axr.get_legend_handles_labels()
    ax.legend(h1 + h2, l1 + l2, loc='lower right', fontsize=12.5, frameon=False)
    ax.set_title('Twenty years of glider observations: the local ocean tracks El Niño', fontsize=16,
                 fontweight='bold')
    ax.grid(axis='y', lw=0.3, alpha=0.6)
    fig.tight_layout(); fig.savefig(path, dpi=160); plt.close(fig)


def oxygen_percent(stats):
    """ Express the isopycnal oxygen anomaly as a percentage of the 2017-2024 normal on sigma 25.5.

    Parameters
    ----------
    stats : dict from the report's stats.json

    Returns
    -------
    (anom_umol, normal_umol, percent)

    Generated by JXP and Claude
    """
    anom = float(stats['oxygen']['recent_on_sigma']['25.5'])
    ds = xr.open_dataset(os.path.join(PRODUCTS, 'line66_profiles_anom.nc'))
    yr = pd.to_datetime(ds.time.values).year
    sel = (yr >= 2017) & (yr <= 2024) & (ds.dist.values <= 200)
    sub = ds.isel(profile=np.where(sel)[0])
    near = np.abs(sub['sigma0'].values - 25.5) < 0.05
    normal = float(np.nanmean(sub['doxy'].values[near]))
    return anom, normal, 100 * anom / normal


def b64png(path):
    """ Read a PNG and return a data URI for inline HTML. Generated by JXP and Claude """
    with open(path, 'rb') as fh:
        return 'data:image/png;base64,' + base64.b64encode(fh.read()).decode()


