def main():
    """ Build figures, HTML and .docx for the leadership briefing. Generated by JXP and Claude """
    ap = argparse.ArgumentParser()
    ap.add_argument('--date', default='2026-09-03')
    args = ap.parse_args()
    date = pd.Timestamp(args.date)
    os.makedirs(OUT_DIR, exist_ok=True)
    figdir = os.path.join(REPORT_DIR, 'figs', date.strftime('%Y_%m'))
    with open(os.path.join(figdir, 'stats.json')) as fh:
        stats = json.load(fh)
    idx = pd.read_csv(os.path.join(PRODUCTS, 'line66_index.csv'), parse_dates=['time'])
    oni = indices.load_oni('official')

    fig1 = os.path.join(OUT_DIR, 'onepager_fig1_past_events.png')
    fig2 = os.path.join(OUT_DIR, 'onepager_fig2_index_oni.png')
    peaks = fig_past_events(idx, fig1)
    fig_index_oni(idx, oni, fig2)
    o2 = oxygen_percent(stats)
    print('peaks', peaks, 'oxygen', o2)

    stem = f"El_Nino_{date:%b%Y}"
    html_path = os.path.join(OUT_DIR, stem + '.html')
    with open(html_path, 'w') as fh:
        fh.write(build_html(stats, peaks, o2, fig1, fig2, date))
    # LibreOffice: HTML (images inlined as data URIs so they are embedded) -> .docx
    subprocess.run(['soffice', '--headless', '--convert-to', 'docx:MS Word 2007 XML', '--outdir', OUT_DIR, html_path],
                   check=True, capture_output=True, timeout=300)
    print('wrote', html_path, 'and', os.path.join(OUT_DIR, stem + '.docx'))


if __name__ == '__main__':
    main()
