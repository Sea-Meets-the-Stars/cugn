    date = pd.Timestamp(args.date)
    end = pd.Timestamp(args.sst_end) if args.sst_end else date - pd.Timedelta('1D')
    os.makedirs(FIG_DIR, exist_ok=True)

    figdir = os.path.join(REPORT_DIR, 'figs', date.strftime('%Y_%m'))
    with open(os.path.join(figdir, 'stats.json')) as fh:
        stats = json.load(fh)

    # month-stamped names so the dated copy of the page keeps pointing at its own figures
    fig1 = os.path.join(FIG_DIR, f'newsletter_fig1_past_events_{date:%b%Y}.png')
    fig2 = os.path.join(FIG_DIR, f'newsletter_fig2_sealevel_{date:%b%Y}.png')
    sst_json = os.path.join(FIG_DIR, f'sst_numbers_{date:%b%Y}.json')
    use_cov = bool(stats['index'].get('use_coverage', False))
    cov_threshold = stats['index'].get('cov_threshold', 0.30) if use_cov else None
    if args.no_figs:
        print('figures left as they are (--no-figs)')
    else:
        try:
            figs_from_products(fig1, fig2, sst_json, end=end, date=date, cov_threshold=cov_threshold)
            print('figures drawn from the glider products and the tide gauges; satellite numbers computed')
        except Exception as exc:   # products or OISST cache absent: keep what is on disk
            if not (os.path.exists(fig1) and os.path.exists(fig2) and os.path.exists(sst_json)):
                raise                  # nothing to fall back on
            print(f'could not redraw the figures ({exc.__class__.__name__}: {exc});'
                  ' keeping the ones already on disk')

    # The numbers ride along in JSON sidecars, so the text can be rebuilt
    # (--no-figs, or a failed redraw) without recomputing anything
    if not os.path.exists(sst_json):
        raise SystemExit(f'missing {sst_json}: run without --no-figs first')
    with open(sst_json) as fh:
        sst = json.load(fh)
    sl_json = os.path.splitext(fig2)[0] + '.json'
    if not os.path.exists(sl_json):
        raise SystemExit(f'missing {sl_json}: run make_newsletter_sealevel.py --date {date:%Y-%m-%d} first')
    with open(sl_json) as fh:
        sl = json.load(fh)

    # last month's stats, for the "up from" comparisons
    prev_date = date - pd.offsets.MonthBegin(1) - pd.Timedelta('1D')
    with open(os.path.join(REPORT_DIR, 'figs', prev_date.strftime('%Y_%m'), 'stats.json')) as fh:
        prev = json.load(fh)
    # the two record checks (check_sealevel_record.py for the last complete month,
    # check_sst_record.py for the month of the satellite window)
    slrec_json = os.path.join(REPORT_DIR, 'figs', f'sealevel_record_check_{prev_date:%Y-%m}.json')
    sstrec_json = os.path.join(REPORT_DIR, 'figs', f"sst_record_check_{pd.Timestamp(sst['end']):%Y-%m}.json")
    for path, script in [(slrec_json, 'check_sealevel_record.py'), (sstrec_json, 'check_sst_record.py')]:
        if not os.path.exists(path):
            raise SystemExit(f'missing {path}: run {script} first')
    with open(slrec_json) as fh:
        slrec = json.load(fh)
    with open(sstrec_json) as fh:
        sstrec = json.load(fh)
    # where the ONI stands in its record; cached beside the figures like the other numbers
