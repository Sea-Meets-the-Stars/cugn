""" Build the Line 66.7 El Niño report products from the downloaded glider data.

Steps (each product is written to `$OS_SPRAY/CUGN/Line_66/products/`):
 1. Load the SprayData delayed-mode binned record (`binnedCUGN66.nc`).
 2. Bin the real-time Glider-DAC mission(s) to 10 m and append profiles later
    than the delayed-mode record (`combine_binned_and_dac`).
 3. Fit seasonal climatologies: temperature over 2008-2013 (Rudnick et al.
    2017 base years for Line 66.7) and dissolved oxygen over 2017-2024.
 4. Profile anomalies; 10-day x 5-km bin-averaged anomaly grids on depth.
 5. TEOS-10 sigma0; oxygen on isopycnals (25.0-27.0) with its own seasonal fit
    and anomaly grid.
 6. Latest complete transect of the active mission as (depth, distance) sections.
 7. The Line 66.7 Temperature Index (upper 100 m, inshore 200 km, 3-month
    running mean) and a JSON summary.

Usage (ocean14):
    python reports/El_Nino_2026/scripts/build_products.py [--strict-flags] [--no-download]

Generated by JXP and Claude
"""
import os
import sys
import json
import argparse
import datetime

import numpy as np
import pandas as pd
import xarray as xr

from cugn import erddap, annualcycle, climatology

LINE = '66'
PRODUCTS = os.path.join(erddap.line_dir(LINE), 'products')
T_BASE = (2008, 2013)
DO_BASE = (2017, 2024)


def running_mean(y, n):
    """ Centered NaN-aware running mean (n=9 on a 10-day grid ~ 90 days).

    Parameters
    ----------
    y : array-like
    n : int

    Returns
    -------
    numpy.ndarray

    Generated by JXP and Claude
    """
    return pd.Series(np.asarray(y, float)).rolling(n, center=True, min_periods=max(1, n // 2)).mean().to_numpy()


def temperature_index(grid, var='temperature_anom', zmax=100., xmax=200., nsmooth=9):
    """ Upper-`zmax` m, inshore-`xmax` km mean anomaly and its running mean.

    Parameters
    ----------
    grid : xarray.Dataset with `var` (time, depth, distance)
    var : str
    zmax, xmax : float
    nsmooth : int

    Returns
    -------
    pandas.DataFrame with `time`, `raw`, `index`, `nprof` (profiles in the box).

    Generated by JXP and Claude
    """
    sub = grid[var].sel(depth=slice(0, zmax), distance=slice(0, xmax))
    raw = sub.mean(('depth', 'distance'), skipna=True).values
    nprof = grid['count'].sel(distance=slice(0, xmax)).sum('distance').values
    return pd.DataFrame(dict(time=pd.to_datetime(grid.time.values), raw=raw,
                             index=running_mean(raw, nsmooth), nprof=nprof))


def main():
    """ Run the product build; see module docstring. Generated by JXP and Claude """
    ap = argparse.ArgumentParser()
    ap.add_argument('--strict-flags', action='store_true',
                    help='keep only QARTOD flag 1 (drop not-evaluated = 2) in real-time data')
    ap.add_argument('--no-download', action='store_true', help='use files already on disk')
    args = ap.parse_args()
    keep_flags = (1,) if args.strict_flags else (1, 2)
    os.makedirs(PRODUCTS, exist_ok=True)
    today = datetime.date.today().isoformat()
    summary = dict(build_date=today, keep_flags=list(keep_flags))

    # 1. Delayed-mode record ---------------------------------------------------
    if not args.no_download:
        erddap.download_binned_line(LINE, snapshot=True, overwrite=False)
    print('loading binned record ...', flush=True)
    binned = erddap.load_binned_line(LINE)
    summary['delayed_mode'] = dict(nprof=int(binned.sizes['profile']),
                                   first=str(binned.time.min().values)[:10],
                                   last=str(binned.time.max().values)[:10])
    print('  ', summary['delayed_mode'], flush=True)

    # 2. Real-time missions -------------------------------------------------------
    dac_ids = []
    if not args.no_download:
        missions = erddap.list_dac_missions(LINE, since='2025-06-01T00:00:00Z')
        newer = missions[pd.to_datetime(missions.maxTime) > pd.Timestamp(binned.time.max().values, tz='UTC')]
        dac_ids = list(newer.datasetID)
        for did in dac_ids:
            print('downloading DAC', did, flush=True)
            erddap.download_dac_mission(did, LINE, overwrite=True)
    else:
        dac_ids = [f[:-3] for f in os.listdir(os.path.join(erddap.line_dir(LINE), 'DAC'))
                   if f.startswith('sp') and f.endswith('.nc')]
    dac_binned = [erddap.bin_dac_mission(d, LINE, keep_flags=keep_flags) for d in dac_ids]
    ds = erddap.combine_binned_and_dac(binned, dac_binned)
    summary['realtime'] = dict(missions=dac_ids,
                               nprof=int(ds.realtime.sum()),
                               last=str(ds.time.max().values)[:10])
    print('  realtime', summary['realtime'], flush=True)
    ds.attrs['build_date'] = today
    ds.to_netcdf(os.path.join(PRODUCTS, 'line66_profiles.nc'))

    # 3. Seasonal climatologies -----------------------------------------------------
    print('fitting annual cycles ...', flush=True)
    A_T = annualcycle.fit_annual_cycle(ds, 'temperature', base_years=T_BASE)
    A_DO = annualcycle.fit_annual_cycle(ds, 'doxy', base_years=DO_BASE)
    A_T.to_netcdf(os.path.join(PRODUCTS, f'annual_cycle_T_{T_BASE[0]}-{T_BASE[1]}.nc'))
    A_DO.to_netcdf(os.path.join(PRODUCTS, f'annual_cycle_DO_{DO_BASE[0]}-{DO_BASE[1]}.nc'))
    # Offshore extent with a valid fit (all depths) for the record
    okx = np.isfinite(A_T.coef[..., 0].values).any(axis=0)
    summary['fit_xmax_km'] = float(A_T.xcenter.values[okx].max())

    # 4. Anomalies and depth grids ---------------------------------------------------
    ds = climatology.profile_anomalies(ds, A_T, 'temperature')
    ds = climatology.profile_anomalies(ds, A_DO, 'doxy')
    gT = climatology.grid_profiles(ds, 'temperature_anom')
    gDO = climatology.grid_profiles(ds, 'doxy_anom')
    grid = xr.merge([gT, gDO[['doxy_anom']]])
    grid.attrs.update(T_base_years=str(T_BASE), DO_base_years=str(DO_BASE), build_date=today)
    grid.to_netcdf(os.path.join(PRODUCTS, 'line66_grid_anom.nc'))

    # 5. Isopycnal oxygen --------------------------------------------------------------
    print('isopycnal interpolation ...', flush=True)
    ds = climatology.add_sigma0(ds)
    iso = climatology.to_isopycnals(ds, 'doxy')
    # Isopycnal depths from the temperature record (full 2007+ coverage; the DO
    # interpolation only exists from 2017), so the depth anomaly can use T_BASE.
    iso['depth_of_sigma'] = climatology.to_isopycnals(ds, 'temperature')['depth_of_sigma']
    iso_fit_in = iso.rename({'sigma': 'depth'})          # reuse the depth-based fitter
    A_DOs = annualcycle.fit_annual_cycle(iso_fit_in, 'doxy', base_years=DO_BASE)
    A_Zs = annualcycle.fit_annual_cycle(iso_fit_in, 'depth_of_sigma', base_years=T_BASE)
    iso_fit_in = climatology.profile_anomalies(iso_fit_in, A_DOs, 'doxy')
    iso_fit_in = climatology.profile_anomalies(iso_fit_in, A_Zs, 'depth_of_sigma')
    gS = xr.merge([climatology.grid_profiles(iso_fit_in, 'doxy_anom'),
                   climatology.grid_profiles(iso_fit_in, 'depth_of_sigma_anom')[['depth_of_sigma_anom']]])
    gS = gS.rename({'depth': 'sigma'})
    gS.attrs.update(DO_base_years=str(DO_BASE), isopycnal_depth_base_years=str(T_BASE), build_date=today)
    gS.to_netcdf(os.path.join(PRODUCTS, 'line66_grid_anom_sigma.nc'))
    ds.to_netcdf(os.path.join(PRODUCTS, 'line66_profiles_anom.nc'))

    # 6. Latest transect --------------------------------------------------------------------
    rt = ds.isel(profile=np.where(ds.realtime.values)[0])
    legs = climatology.find_transects(rt)
    complete = legs[legs.complete.astype(bool)] if len(legs) else legs
    if rt.sizes['profile'] == 0:  # no real-time data: use the last delayed-mode 10 days
        rt = ds.isel(profile=np.where(ds.time.values >= ds.time.max().values - np.timedelta64(10, 'D'))[0])
    if len(complete):
        leg = complete.iloc[-1]
        sub = rt.isel(profile=slice(int(leg.i0), int(leg.i1) + 1))
        kind = 'complete transect'
    else:  # fall back to the last 10 days
        sub = rt.isel(profile=np.where(rt.time.values >= rt.time.max().values - np.timedelta64(10, 'D'))[0])
        leg = pd.Series(dict(t0=pd.Timestamp(sub.time.min().values), t1=pd.Timestamp(sub.time.max().values),
                             direction='n/a'))
        kind = 'last 10 days (no complete leg)'
    secs = xr.merge([climatology.section_from_profiles(sub, v).rename(v)
                     for v in ['temperature', 'temperature_anom', 'temperature_clim', 'sigma0',
                               'doxy', 'doxy_anom', 'salinity']])
    secs.attrs.update(kind=kind, t0=str(leg.t0)[:16], t1=str(leg.t1)[:16], direction=str(leg.direction),
                      nprof=int(sub.sizes['profile']))
    secs.to_netcdf(os.path.join(PRODUCTS, 'line66_latest_section.nc'))
    legs.to_csv(os.path.join(PRODUCTS, 'line66_realtime_legs.csv'), index=False)
    summary['latest_section'] = dict(secs.attrs)

    # 7. Index and summary --------------------------------------------------------------------
    idx = temperature_index(grid, 'temperature_anom')
    idx_do = temperature_index(grid, 'doxy_anom')
    idx['do_raw'], idx['do_index'] = idx_do['raw'], idx_do['index']
    idx.to_csv(os.path.join(PRODUCTS, 'line66_index.csv'), index=False)
    valid = idx.dropna(subset=['index'])
    last = valid.iloc[-1]
    rank = int((valid['index'] >= last['index']).sum())
    summary['index'] = dict(last_time=str(last.time)[:10], last_value=round(float(last['index']), 3),
                            record_max=round(float(valid['index'].max()), 3),
                            record_max_time=str(valid.loc[valid['index'].idxmax(), 'time'])[:10],
                            rank_of_last=rank, n_valid=int(len(valid)),
                            do_last=round(float(valid['do_index'].dropna().iloc[-1]), 2))
    with open(os.path.join(PRODUCTS, 'summary.json'), 'w') as fh:
        json.dump(summary, fh, indent=2, default=str)
    print(json.dumps(summary, indent=2, default=str))


if __name__ == '__main__':
    main()
