def _save(fig, figdir, name):
    """ Save a figure as PNG at 130 dpi and close it.

    Parameters
    ----------
    fig : matplotlib Figure
    figdir, name : str

    Returns
    -------
    str : output path

    Generated by JXP and Claude
    """
    path = os.path.join(figdir, name)
    fig.savefig(path, dpi=130, bbox_inches='tight')
    plt.close(fig)
    print('wrote', path, flush=True)
    return path


def load_products():
    """ Open the product files written by build_products.py.

    Returns
    -------
    dict with `grid` (depth anomaly grid), `sigma` (isopycnal grid), `section`
    (latest transect), `index` (DataFrame), `summary` (dict).

    Generated by JXP and Claude
    """
    P = lambda f: os.path.join(PRODUCTS, f)
    with open(P('summary.json')) as fh:
        summary = json.load(fh)
    return dict(grid=xr.open_dataset(P('line66_grid_anom.nc')),
                sigma=xr.open_dataset(P('line66_grid_anom_sigma.nc')),
                section=xr.open_dataset(P('line66_latest_section.nc')),
                index=pd.read_csv(P('line66_index.csv'), parse_dates=['time']),
                summary=summary)


def shade_events(ax, alpha=0.08):
    """ Shade the comparison-event windows on a time axis.

    Parameters
    ----------
    ax : matplotlib Axes with a datetime x axis
    alpha : float

    Generated by JXP and Claude
    """
    for name, (t0, t1) in indices.event_windows().items():
        t1 = pd.Timestamp.now() if t1 is None else t1
        ax.axvspan(t0, t1, color=EVENT_COLORS.get(name, '0.5'), alpha=alpha, lw=0)


def fig01_index(prod, figdir):
    """ Fig 1: Line 66.7 Temperature Index with the ONI and the SCTI. Generated by JXP and Claude """
    idx = prod['index']
    oni = indices.load_oni('official')
    try:
        scti = indices.load_scti('10day')
        scti = scti.assign(scti=indices.running_mean(scti['scti'].to_numpy(), 9))
    except Exception:
        scti = None
    s = pd.Series(idx['index'].to_numpy(), index=idx['time'])
    fig, ax = plt.subplots(figsize=(12, 5))
    shade_events(ax)
    plotting.plot_index_with_oni({'Line 66.7 index (10-100 m, 0-200 km, 3-mo mean)': s}, oni,
                                 ax=ax, scti=scti, xlim=(pd.Timestamp('2007-01-01'), pd.Timestamp('2027-07-01')),
                                 title='Line 66.7 Temperature Index vs. Oceanic Niño Index')
    # mark the real-time portion
    last_dm = pd.Timestamp(prod['summary']['delayed_mode']['last'])
    ax.axvline(last_dm, color='0.4', ls=':', lw=1)
    ax.text(last_dm, ax.get_ylim()[0] * 0.95, ' real-time →', fontsize=8, color='0.3', va='bottom')
    _save(fig, figdir, 'fig01_line66_index_oni.png')
    valid = idx.dropna(subset=['index'])
    STATS['index'] = dict(last_time=str(valid.time.iloc[-1])[:10], last=float(valid['index'].iloc[-1]),
                          max=float(valid['index'].max()), max_time=str(valid.loc[valid['index'].idxmax(), 'time'])[:10],
                          raw_last=float(valid['raw'].iloc[-1]),
                          oni_last=float(oni['oni'].dropna().iloc[-1]), oni_last_time=str(oni['time'].iloc[-1])[:10])
    if scti is not None:
        sv = scti.dropna(subset=['scti'])
        STATS['index']['scti_last'] = float(sv['scti'].iloc[-1]); STATS['index']['scti_last_time'] = str(sv['time'].iloc[-1])[:10]


def _upper(grid, var, zmax=100.):
    """ Upper-`zmax` m mean of a (time, depth, distance) variable. Generated by JXP and Claude """
    return grid[var].sel(depth=slice(0, zmax)).mean('depth', skipna=True)


def _inshore(grid, var, xmax=200.):
    """ Inshore-`xmax` km mean of a (time, depth, distance) variable. Generated by JXP and Claude """
    return grid[var].sel(distance=slice(0, xmax)).mean('distance', skipna=True)


