def fig04_zoom(prod, figdir):
    """ Fig 4: 2025-2026 zoom of the index and both Hovmöllers. Generated by JXP and Claude """
    grid = prod['grid']; idx = prod['index']
    t0, t1 = pd.Timestamp('2025-01-01'), pd.Timestamp('2026-12-31')
    g = grid.sel(time=slice(t0, t1), distance=slice(0, prod['summary'].get('fit_xmax_km', 400)))
    oni = indices.load_oni('official')
    fig, axes = plt.subplots(3, 1, figsize=(12, 10), sharex=True,
                             gridspec_kw=dict(height_ratios=[1, 1.4, 1.4]))
    ax = axes[0]
    sel = (idx.time >= t0) & (idx.time <= t1)
    ax.plot(idx.time[sel], idx['raw'][sel], color='0.6', lw=1, label='10-day mean')
    ax.plot(idx.time[sel], idx['index'][sel], color='tab:green', lw=2.5, label='3-month running mean')
    ax.axhline(0, color='0.5', lw=0.6); ax.set_ylabel('T anomaly (°C)')
    axr = ax.twinx(); o = oni[(oni.time >= t0)]
    axr.plot(o.time, o.oni, 'k', lw=2, label='ONI'); axr.set_ylim(-3, 3); axr.set_ylabel('ONI (°C)')
    h1, l1 = ax.get_legend_handles_labels(); h2, l2 = axr.get_legend_handles_labels()
    ax.legend(h1 + h2, l1 + l2, loc='upper left', fontsize=8)
    ax.set_title('Line 66.7, 2025-2026: index (top), 10-100 m anomaly vs distance, inshore anomaly vs depth')
    plotting.plot_xtime_hovmoller(_upper(g, 'temperature_anom').rename('temperature_anom'), ax=axes[1])
    plotting.plot_ztime_hovmoller(_inshore(g, 'temperature_anom').rename('temperature_anom'), ax=axes[2])
    axes[2].xaxis.set_major_locator(mdates.MonthLocator(interval=2))
    axes[2].xaxis.set_major_formatter(mdates.DateFormatter('%b\n%Y'))
    axes[2].set_xlim(t0, t1)
    _save(fig, figdir, 'fig04_zoom_2025_2026.png')
    # numbers: peak 10-day surface (10 m) anomaly and where/when
    surf = g['temperature_anom'].sel(depth=10.)
    imax = np.unravel_index(np.nanargmax(surf.values), surf.shape)
    STATS['zoom'] = dict(peak_10m_anom=float(surf.values[imax]), peak_time=str(surf.time.values[imax[0]])[:10],
                         peak_dist_km=float(surf.distance.values[imax[1]]))


