def fig07_events(prod, figdir):
    """ Fig 7: event composite of the Line 66.7 index by calendar month, plus a table. Generated by JXP and Claude """
    idx = prod['index'].set_index('time')
    grid = prod['grid']
    inshore = _inshore(grid, 'temperature_anom')
    years = {'2009-10 El Niño': 2009, '2014-15 Blob': 2014, '2015-16 El Niño': 2015,
             '2025-26 MHW': 2025, '2026-27 El Niño': 2026}
    colors = {'2009-10 El Niño': 'tab:blue', '2014-15 Blob': 'tab:orange', '2015-16 El Niño': 'tab:red',
              '2025-26 MHW': 'tab:green', '2026-27 El Niño': 'k'}
    fig, ax = plt.subplots(figsize=(10, 5))
    rows = []
    for name, y0 in years.items():
        t0, t1 = pd.Timestamp(f'{y0}-07-01'), pd.Timestamp(f'{y0 + 1}-06-30')
        s = idx.loc[t0:t1, 'index'].dropna()
        if s.empty:
            continue
        months = (s.index - t0).days / 30.44
        ax.plot(months, s.values, color=colors[name], lw=2.5 if y0 >= 2025 else 1.8, label=f'{name} (from Jul {y0})')
        ipk = s.idxmax()
        # depth penetration at the peak: shallowest depth where the inshore anomaly < +0.5 °C
        # depth structure at the peak: mean over +-45 days so a single 10-day gap does not blank it
        prof = inshore.sel(time=slice(ipk - pd.Timedelta(days=45), ipk + pd.Timedelta(days=45))).mean('time', skipna=True)
        below = prof.depth.values[prof.values < 0.5]
        rows.append(dict(event=name, start=str(t0)[:10], peak_index=round(float(s.max()), 2),
                         peak_month=str(ipk)[:7], months_from_jul=round(float((ipk - t0).days / 30.44), 1),
                         depth_below_half_deg_m=float(below.min()) if below.size else np.nan,
                         anom_10m=round(float(prof.sel(depth=10)), 2), anom_100m=round(float(prof.sel(depth=100)), 2),
                         anom_200m=round(float(prof.sel(depth=200)), 2)))
    ax.axhline(0, color='0.5', lw=0.6)
    ax.set_xticks(range(0, 12)); ax.set_xticklabels(['Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec', 'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun'])
    ax.set_xlim(0, 12); ax.set_ylabel('Line 66.7 Temperature Index (°C)')
    ax.set_title('Line 66.7 index through past warm events (July of year 0 → June of year +1)')
    ax.legend(fontsize=8)
    _save(fig, figdir, 'fig07_event_composite.png')
    table = pd.DataFrame(rows)
    table.to_csv(os.path.join(figdir, 'event_table.csv'), index=False)
    STATS['events'] = table.to_dict(orient='records')


def fig08_oisst_map(figdir):
    """ Fig 8: latest 7-day OISST anomaly map with the CUGN lines (plain lon/lat axes;
    land is where OISST is undefined). Generated by JXP and Claude """
    ds = oisst.load(start_year=1991)
    amap = oisst.latest_anomaly_map(ds, ndays=7)
    fig, ax = plt.subplots(figsize=(9, 8))
    ax.set_facecolor('0.75')                       # land / missing = grey
    m = ax.pcolormesh(amap.lon, amap.lat, np.ma.masked_invalid(amap.values), cmap=cmocean.cm.balance,
                      vmin=-4, vmax=4, shading='nearest')
    for line, lab in [('56.0', '56.7'), ('66.7', '66.7'), ('80.0', '80.0'), ('90.0', '90.0')]:
        lons, lats = cugn_utils.line_endpoints(line)
        ax.plot(lons, lats, 'k-', lw=2); ax.text(lons[1] - 0.2, lats[1], lab, fontsize=9, ha='right', va='center')
    bx, by = MONTEREY_BOX['lon'], MONTEREY_BOX['lat']
    ax.plot([bx[0], bx[1], bx[1], bx[0], bx[0]], [by[0], by[0], by[1], by[1], by[0]], color='tab:green', lw=1.5)
    ax.set_xlim(-135, -115); ax.set_ylim(25, 50); ax.set_aspect(1 / np.cos(np.deg2rad(37)))
    ax.set_xlabel('Longitude'); ax.set_ylabel('Latitude'); ax.grid(lw=0.3, alpha=0.5)
    plt.colorbar(m, ax=ax, shrink=0.75, label='SST anomaly (°C) vs 1991-2020')
    t_end = pd.Timestamp(ds.time.values[-1])
    ax.set_title(f'OISST v2.1 SST anomaly, 7 days ending {t_end:%Y-%m-%d}, with the CUGN lines')
    _save(fig, figdir, 'fig08_oisst_anomaly_map.png')
    # Track-mean anomaly along Line 66.7 (nearest grid points to 41 track points)
    lons, lats = cugn_utils.line_endpoints('66.7')
    tl = np.linspace(lons[0], lons[1], 41); tb = np.linspace(lats[0], lats[1], 41)
    track = [float(amap.sel(lon=x, lat=y, method='nearest')) for x, y in zip(tl, tb)]
    STATS['oisst_map'] = dict(end=str(t_end)[:10],
                              monterey_box_anom=float(amap.sel(lat=slice(*by), lon=slice(*bx)).mean()),
                              line66_track_anom=float(np.nanmean(track)),
                              region_mean_anom=float(amap.mean()))
    return ds


def fig09_oisst_mhw(ds, figdir):
    """ Fig 9: Monterey Bay OISST with Hobday climatology, threshold and MHW shading. Generated by JXP and Claude """
    series = oisst.box_mean(ds, MONTEREY_BOX['lat'], MONTEREY_BOX['lon'])
    res = oisst.hobday_mhw(series)
    daily, events = res['daily'], res['events']
    d = daily.loc['2024-01-01':]
    fig, ax = plt.subplots(figsize=(12, 5))
    ax.plot(d.index, d['clim'], color='0.4', lw=1, label='1991-2020 climatology')
    ax.plot(d.index, d['thresh'], color='tab:red', lw=1, ls='--', label='90th percentile')
    ax.plot(d.index, d['sst'], color='k', lw=1.2, label='OISST, Monterey Bay box')
    ax.fill_between(d.index, d['thresh'], d['sst'], where=d['sst'] > d['thresh'], color='tab:red', alpha=0.5, label='marine heatwave')
    ax.set_ylabel('SST (°C)'); ax.legend(fontsize=8, loc='upper left')
    ax.set_title('Monterey Bay box (36.3-37.0 °N, 122.6-121.8 °W): OISST SST and Hobday et al. (2016) marine-heatwave days')
    _save(fig, figdir, 'fig09_oisst_monterey_mhw.png')
    ev = events[events['end'] >= pd.Timestamp('2025-01-01')]
    STATS['mhw'] = dict(events=ev.astype(str).to_dict(orient='records'),
                        current_category=str(daily['category'].iloc[-1]), last_day=str(daily.index[-1])[:10],
                        last_anom=float(daily['anom'].iloc[-1]),
                        mhw_days_since_2025_05=int(daily.loc['2025-05-01':, 'is_mhw'].sum()),
                        days_since_2025_05=int(len(daily.loc['2025-05-01':])))


def fig10_upwelling(figdir):
    """ Fig 10: CUTI and BEUTI anomalies at 36-37 °N, 2023-present. Generated by JXP and Claude """
    fig, axes = plt.subplots(2, 1, figsize=(12, 7), sharex=True)
    for ax, name in zip(axes, ['CUTI', 'BEUTI']):
        for lat, col in [(36, 'tab:blue'), (37, 'tab:orange')]:
            df = indices.upwelling_anomaly(indices.load_upwelling(name, lat=lat))
            d = df[df.time >= pd.Timestamp('2023-01-01')]
            sm = indices.running_mean(d['anom'].to_numpy(), 31)
            ax.plot(d.time, sm, color=col, lw=1.8, label=f'{lat} °N (31-day mean)')
            STATS.setdefault('upwelling', {})[f'{name}_{lat}N_last90d_anom'] = float(np.nanmean(df['anom'].to_numpy()[-90:]))
            STATS['upwelling'][f'{name}_last'] = str(df.time.iloc[-1])[:10]
        ax.axhline(0, color='0.5', lw=0.6); ax.set_ylabel(f'{name} anomaly')
        ax.legend(fontsize=8)
    axes[0].set_title('Upwelling indices near Line 66.7: anomaly from the 1991-2020 daily climatology (Jacox et al. 2018)')
    _save(fig, figdir, 'fig10_upwelling_cuti_beuti.png')


