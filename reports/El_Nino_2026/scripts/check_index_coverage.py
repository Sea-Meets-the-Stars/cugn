""" How well do the latest 10-day bins of the Line 66.7 Temperature Index sample
the 0-200 km, 10-100 m box it averages over?

The index is the mean temperature anomaly over the inshore 200 km of the line
in the upper 100 m, smoothed with a 9-bin (~90-day) running mean.  A glider
that spends weeks near shore (e.g. the end of a mission) fills those bins with
inshore profiles only, so the raw value is not comparable with a bin that saw
a full transect.  This script prints, for the last `--nbins` bins, the number
of profiles, the along-line distance range they cover and the raw and
smoothed index, so the monthly report can caveat the latest value.

Inputs : products in $OS_SPRAY/CUGN/Line_66/products/ (line66_profiles_anom.nc,
         line66_index.csv) written by build_products.py.
Outputs: a table on stdout (nothing written).

Usage (ocean14):
    python reports/El_Nino_2026/scripts/check_index_coverage.py [--nbins 12]

Generated by JXP and Claude
"""
import os
import argparse

import numpy as np
import pandas as pd
import xarray as xr

from cugn import erddap

PRODUCTS = os.path.join(erddap.line_dir('66'), 'products')
XMAX = 200.    # km, inshore extent of the index box
ZMAX = 100.    # m, depth extent of the index box


def bin_coverage(ds, idx, nbins=12, xmax=XMAX, zmax=ZMAX):
    """ Per-bin sampling statistics for the last `nbins` index bins.

    Parameters
    ----------
    ds : xarray.Dataset
        Profiles with `time`, `dist` (km along the line), `depth` and `temperature_anom`
        (from line66_profiles_anom.nc).
    idx : pandas.DataFrame
        The index table (time, raw, index, nprof) from line66_index.csv; the
        bins are 10 days wide and centred on `time`.
    nbins : int
    xmax, zmax : float
        Box used by the index.

    Returns
    -------
    pandas.DataFrame with one row per bin: time, nprof (in the box), dist_min,
    dist_max (km), frac_box (fraction of the 0-xmax range covered in 5-km
    steps), mean_anom_box (upper-zmax mean of the box profiles), raw, index.

    Generated by JXP and Claude
    """
    t = pd.to_datetime(ds.time.values)
    x = ds.dist.values
    # Upper-box mean anomaly of every profile (NaN where no data)
    za = ds['temperature_anom'].sel(depth=slice(0, zmax)).mean('depth', skipna=True).values
    rows = []
    for _, r in idx.tail(nbins).iterrows():
        t0, t1 = r.time - pd.Timedelta(days=5), r.time + pd.Timedelta(days=5)
        sel = (t >= t0) & (t < t1) & (x >= 0) & (x <= xmax)
        xs = x[sel]
        # Which 5-km cells of the box were sampled at least once
        cells = np.unique(np.floor(xs / 5.)) if sel.any() else np.array([])
        rows.append(dict(time=r.time.date(), nprof=int(sel.sum()),
                         dist_min=float(xs.min()) if sel.any() else np.nan,
                         dist_max=float(xs.max()) if sel.any() else np.nan,
                         frac_box=len(cells) / (xmax / 5.),
                         mean_anom_box=float(np.nanmean(za[sel])) if sel.any() else np.nan,
                         raw=r.raw, index=r['index']))
    return pd.DataFrame(rows)


def main():
    """ Print the coverage table for the latest bins. Generated by JXP and Claude """
    ap = argparse.ArgumentParser()
    ap.add_argument('--nbins', type=int, default=12, help='number of trailing 10-day bins')
    args = ap.parse_args()
    ds = xr.open_dataset(os.path.join(PRODUCTS, 'line66_profiles_anom.nc'))
    idx = pd.read_csv(os.path.join(PRODUCTS, 'line66_index.csv'), parse_dates=['time'])
    pd.set_option('display.width', 200)
    table = bin_coverage(ds, idx, nbins=args.nbins)
    print(f'Line 66.7 index box: 0-{XMAX:.0f} km, 0-{ZMAX:.0f} m; last {args.nbins} 10-day bins')
    print(table.to_string(index=False, float_format=lambda v: f'{v:7.2f}'))
    full = table[table.frac_box >= 0.8]
    if len(full):
        print(f'\nlast bin with >=80% of the box sampled: {full.time.iloc[-1]} '
              f'(raw {full.raw.iloc[-1]:+.2f}, index {full["index"].iloc[-1]:+.2f})')


if __name__ == '__main__':
    main()
