""" Stand-alone close-up of Monterey Bay's sea-surface temperature, November 2026.

Prompt "SST figure 2" of `prompts/elnino_nov2026_prompts.md`, following JXP's
answers in Q&A/SST (26 Nov 2026):

  * data: NOAA Coral Reef Watch CoralTemp v3.1, daily, 0.05 deg (~5 km), five
    times finer than the OISST map of September and with a record back to 1985,
    so the anomaly uses the same 1991-2020 normal as the rest of the newsletter;
  * two panels: the actual temperature, and its difference from normal;
  * the bay and its approaches, 36.2-37.2 N, 122.7-121.7 W (Ano Nuevo to Point Sur);
    no glider line;
  * the 7-day mean ending on the last day CoralTemp has published;
  * labels: Santa Cruz, Moss Landing, Monterey, Ano Nuevo, Point Sur;
  * a warm-only colour scale for the anomaly, 0 to +7 degC.

The normal is computed exactly as for OISST (`cugn.oisst.gridded_climatology`:
day-of-year means pooled over an 11-day window across 1991-2020, then smoothed
over 31 days), cell by cell on the CoralTemp grid.

Data come from the PacIOOS ERDDAP (`dhw_5km`, variable `CRW_SST`, which is
CoralTemp v3.1), one request per year for a box slightly larger than the map.  Each year is cached as a small
NetCDF file under `<SST dir>/CoralTemp/` and never fetched again (the current
month is re-fetched when its file is older than 12 h), so an interrupted run
resumes where it stopped; the server was intermittent in November 2026, so
every request is retried.

Usage (ocean14):
    python reports/El_Nino_2026/scripts/make_sst_nov2026.py [--end 2026-11-24]

Outputs:
  * `reports/El_Nino_2026/figures/SST_Nov2026.png` (dpi 300)
  * `reports/El_Nino_2026/figures/SST_Nov2026.json` (the numbers on the figure)

Generated by JXP and Claude
"""
import os
import json
import time
import argparse

import numpy as np
import pandas as pd
import xarray as xr
import requests
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.ticker
import matplotlib.patheffects as pe
import cartopy.crs as ccrs
import cartopy.feature as cfeature
import cmocean

from cugn import oisst

REPORT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(REPORT_DIR, 'figures')
CACHE_DIR = os.path.join(os.path.dirname(oisst.OISST_DIR.rstrip('/')), 'CoralTemp')
# CoralTemp v3.1 SST (`CRW_SST`) from Coral Reef Watch's 5-km product on the PacIOOS
# ERDDAP: coastwatch.pfeg.noaa.gov's `NOAA_DHW` redirects here, and
# coastwatch.noaa.gov's own `noaacrwsstDaily` answered 502 to every data request
# on 26-27 Nov 2026 (metadata only)
ERDDAP = 'https://pae-paha.pacioos.hawaii.edu/erddap/griddap/dhw_5km'
SST_VAR = 'CRW_SST'
# Map extent (JXP, Q&A/SST 3) and the slightly larger box that is downloaded
# (the east edge is 0.15 deg past JXP's -121.7: land only, so the town labels fit)
MAP_LAT, MAP_LON = (36.2, 37.2), (-122.7, -121.55)
FETCH_LAT, FETCH_LON = (36.1, 37.3), (-122.8, -121.6)
# The same Monterey Bay box the newsletter text quotes from OISST
MONTEREY_BOX = dict(lat=(36.3, 37.0), lon=(-122.6, -121.8))
CLIM_YEARS = (1991, 2020)
NDAYS = 7
ANOM_MAX = 7.0                     # top of the warm-only anomaly scale (Q&A/SST 6)
# (label, lon, lat, text side, vertical alignment) -- JXP's list, Q&A/SST 5
PLACES = [('Santa Cruz', -122.030, 36.974, 'left', 'bottom'),
          ('Moss Landing', -121.787, 36.804, 'left', 'center'),
          ('Monterey', -121.894, 36.600, 'left', 'center'),
          ('Año Nuevo', -122.337, 37.108, 'left', 'center'),
          ('Point Sur', -121.901, 36.306, 'left', 'center')]


def _request(url, path, retries=6, pause=60, timeout=900):
    """ Download `url` to `path`, retrying on server errors and time-outs.

    Parameters
    ----------
    url : str
    path : str, destination (written via a temporary file, so a partial
        download never looks complete)
    retries : int, attempts
    pause : float, seconds between attempts
    timeout : float, seconds of silence before a request is abandoned

    Returns
    -------
    str : `path`

    Generated by JXP and Claude
    """
    err = None
    for k in range(retries):
        try:
            with requests.get(url, stream=True, timeout=timeout) as r:
                r.raise_for_status()
                with open(path + '.part', 'wb') as fh:
                    for chunk in r.iter_content(1 << 20):
                        fh.write(chunk)
            os.replace(path + '.part', path)
            return path
        except requests.RequestException as exc:
            err = exc
            print(f'[coraltemp]   attempt {k + 1}/{retries} failed: {str(exc)[:120]}', flush=True)
            time.sleep(pause)
    raise RuntimeError(f'could not fetch {url}: {err}')


def fetch(t0, t1, path, max_age_hours=None):
    """ Fetch CoralTemp SST for the download box between two days, cached in `path`.

    Parameters
    ----------
    t0, t1 : pandas.Timestamp, first and last day (inclusive)
    path : str, cache file
    max_age_hours : float or None, re-fetch when the cache is older (None: never)

    Returns
    -------
    str : `path`

    Generated by JXP and Claude
    """
    if os.path.exists(path):
        age = (time.time() - os.path.getmtime(path)) / 3600.
        if max_age_hours is None or age < max_age_hours:
            return path
    # latitude is stored north to south on this server, so the range is given high -> low
    url = (f'{ERDDAP}.nc?{SST_VAR}'
           f'[({t0:%Y-%m-%d}T12:00:00Z):1:({t1:%Y-%m-%d}T12:00:00Z)]'
           f'[({FETCH_LAT[1]}):1:({FETCH_LAT[0]})][({FETCH_LON[0]}):1:({FETCH_LON[1]})]')
    print(f'[coraltemp] {t0:%Y-%m-%d}..{t1:%Y-%m-%d} -> {os.path.basename(path)}', flush=True)
    return _request(url, path)


def last_day():
    """ The last day CoralTemp has published, from the ERDDAP time axis.

    Returns
    -------
    pandas.Timestamp (normalised to midnight)

    Generated by JXP and Claude
    """
    r = requests.get(f'{ERDDAP}.csv?time[last]', timeout=300)
    r.raise_for_status()
    return pd.Timestamp(r.text.splitlines()[-1].strip()).tz_localize(None).normalize()


def load(end):
    """ CoralTemp over the download box: the baseline years plus the 30 days to `end`.

    Parameters
    ----------
    end : pandas.Timestamp, last day wanted

    Returns
    -------
    xarray.Dataset with `sst` (degC) on (time, lat, lon), latitude ascending

    Generated by JXP and Claude
    """
    os.makedirs(CACHE_DIR, exist_ok=True)
    files = []
    for year in range(CLIM_YEARS[0], CLIM_YEARS[1] + 1):   # one small file per baseline year
        files.append(fetch(pd.Timestamp(f'{year}-01-01'), pd.Timestamp(f'{year}-12-31'),
                           os.path.join(CACHE_DIR, f'coraltemp_mbay_{year}.nc')))
    t0 = end - pd.Timedelta(days=29)                        # the recent month, refreshed twice a day
    files.append(fetch(t0, end, os.path.join(CACHE_DIR, f'coraltemp_mbay_recent_{end:%Y%m%d}.nc'),
                       max_age_hours=12.))
    parts = []
    for f in files:
        with xr.open_dataset(f) as ds:
            parts.append(ds.load())
    ds = xr.concat(parts, dim='time').rename({'latitude': 'lat', 'longitude': 'lon', SST_VAR: 'sst'})
    ds = ds.sortby('lat').sortby('time')
    ds['time'] = pd.DatetimeIndex(ds.time.values).normalize()   # stamps are 12:00 UTC
    return ds.drop_duplicates('time')


def week_maps(ds, end, ndays=NDAYS):
    """ The `ndays`-day mean temperature ending on `end`, and its anomaly from the 1991-2020 normal.

    Parameters
    ----------
    ds : xarray.Dataset from load()
    end : pandas.Timestamp
    ndays : int

    Returns
    -------
    (sst, anom) : xarray.DataArray (lat, lon) each, degC; `anom` carries the
        `start`/`end`/`clim_years` attributes of cugn.oisst.latest_anomaly_map

    Generated by JXP and Claude
    """
    sub = ds.sel(time=slice(None, end))
    week = sub['sst'].isel(time=slice(-ndays, None))
    days = pd.DatetimeIndex(week.time.values)
    # the window must be `ndays` consecutive days ending on `end`
    assert days[-1] == end and (days[-1] - days[0]).days == ndays - 1, f'gap in the last {ndays} days: {days}'
    clim = oisst.gridded_climatology(sub, clim_years=CLIM_YEARS, var='sst')
    anom = oisst.latest_anomaly_map(sub, ndays=ndays, clim=clim, var='sst')
    sst = week.mean('time', skipna=True)
    sst.attrs = dict(anom.attrs)
    return sst, anom


def box_mean(da, box=MONTEREY_BOX):
    """ Mean of a (lat, lon) field over a lat/lon box, ignoring land.

    Parameters
    ----------
    da : xarray.DataArray (lat, lon)
    box : dict with `lat` and `lon` ranges

    Returns
    -------
    float

    Generated by JXP and Claude
    """
    return float(da.sel(lat=slice(*box['lat']), lon=slice(*box['lon'])).mean(skipna=True))


def _coast(ax):
    """ Land and coastline at a resolution fit for a 100-km map.

    Uses the full-resolution GSHHS shoreline when cartopy can get it, and Natural
    Earth 10 m otherwise.

    Parameters
    ----------
    ax : cartopy GeoAxes

    Returns
    -------
    str : which shoreline was drawn

    Generated by JXP and Claude
    """
    try:
        feat = cfeature.GSHHSFeature(scale='f', levels=[1])
        list(feat.intersecting_geometries([MAP_LON[0], MAP_LON[1], MAP_LAT[0], MAP_LAT[1]]))  # forces the download
        ax.add_feature(feat, facecolor='#E8E4DC', edgecolor='0.3', linewidth=0.7, zorder=2)
        return 'GSHHS full'
    except Exception as exc:
        print(f'GSHHS unavailable ({exc.__class__.__name__}); using Natural Earth 10 m', flush=True)
        ax.add_feature(cfeature.NaturalEarthFeature('physical', 'land', '10m'),
                       facecolor='#E8E4DC', edgecolor='0.3', linewidth=0.7, zorder=2)
        return 'Natural Earth 10m'


def fig_sst_pair(sst, anom, path):
    """ Two-panel public figure: the week's sea-surface temperature, and how far above normal it is.

    Parameters
    ----------
    sst : xarray.DataArray (lat, lon), 7-day mean SST (degC)
    anom : xarray.DataArray (lat, lon), its anomaly from the 1991-2020 normal (degC),
        with `start`, `end`, `clim_years` attributes
    path : str, output PNG (saved at dpi 300)

    Returns
    -------
    dict : the numbers on the figure (box means, map extremes, colour ranges,
        dates, shoreline used)

    Generated by JXP and Claude
    """
    plt.rcParams.update({'font.size': 13})
    proj = ccrs.PlateCarree()
    halo = [pe.withStroke(linewidth=2.8, foreground='white')]
    fig, axes = plt.subplots(1, 2, figsize=(16, 9.2), subplot_kw=dict(projection=proj))
    fig.subplots_adjust(left=0.06, right=0.97, top=0.88, bottom=0.04, wspace=0.12)
    # temperature range rounded outwards to whole degrees, so the colour bar ticks are tidy
    vals = sst.sel(lat=slice(*MAP_LAT), lon=slice(*MAP_LON)).values
    tmin, tmax = np.floor(np.nanmin(vals)), np.ceil(np.nanmax(vals))
    panels = [(axes[0], sst, cmocean.cm.thermal, tmin, tmax, 'Sea-surface temperature this week'),
              (axes[1], anom, 'YlOrRd', 0., ANOM_MAX, 'How much warmer than normal')]
    shore = None
    for ax, field, cmap, vmin, vmax, title in panels:
        ax.set_extent([MAP_LON[0], MAP_LON[1], MAP_LAT[0], MAP_LAT[1]], crs=proj)
        # CoralTemp's land-masked coastal cells are drawn in the land colour, not left white
        cmap = matplotlib.colormaps.get_cmap(cmap).copy()
        cmap.set_bad('#E8E4DC')
        ax.set_facecolor('#E8E4DC')       # and where the coastline and CoralTemp's land mask disagree
        mesh = ax.pcolormesh(field.lon, field.lat, np.ma.masked_invalid(field.values), cmap=cmap,
                             vmin=vmin, vmax=vmax, shading='nearest', transform=proj, zorder=1)
        shore = _coast(ax)
        for label, lon, lat, ha, va in PLACES:
            ax.plot(lon, lat, 'o', ms=4.5, color='0.15', transform=proj, zorder=5)
            ax.text(lon + 0.025, lat, label, fontsize=12.5, ha=ha, va=va, color='0.1',
                    transform=proj, zorder=5, path_effects=halo)
        gl = ax.gridlines(draw_labels=True, lw=0.3, color='0.5', alpha=0.5, zorder=3)
        gl.top_labels = gl.right_labels = False
        gl.left_labels = ax is axes[0]          # latitudes once, on the left
        gl.xlocator = matplotlib.ticker.FixedLocator([-122.6, -122.4, -122.2, -122.0, -121.8, -121.6])
        gl.ylocator = matplotlib.ticker.FixedLocator([36.2, 36.4, 36.6, 36.8, 37.0, 37.2])
        gl.xlabel_style = gl.ylabel_style = {'size': 10.5, 'color': '0.3'}
        ax.set_title(title, fontsize=15, fontweight='bold', pad=8)
        cb = fig.colorbar(mesh, ax=ax, orientation='horizontal', pad=0.09, shrink=0.88,
                          extend='both' if field is sst else 'max')
        if field is sst:
            cb.set_label('°C', fontsize=13)
            # Fahrenheit along the top of the same bar, for readers who think in °F
            fax = cb.ax.secondary_xaxis('top', functions=(lambda c: 1.8 * c + 32., lambda f: (f - 32.) / 1.8))
            fax.set_xlabel('°F', fontsize=12, labelpad=4)
            fax.tick_params(labelsize=11)
        else:
            cb.set_label('°C above the 1991–2020 normal for the time of year', fontsize=13)
    t0, t1 = pd.Timestamp(anom.attrs['start']), pd.Timestamp(anom.attrs['end'])
    fig.suptitle(f'Monterey Bay is {box_mean(anom):.0f} °C ({1.8 * box_mean(anom):.0f} °F) warmer than normal',
                 fontsize=18, fontweight='bold', y=0.975)
    fig.text(0.5, 0.935, f'NOAA satellite sea-surface temperature (Coral Reef Watch CoralTemp, 5 km), '
             f'average for {t0:%-d}–{t1:%-d %B %Y}', ha='center', va='top', fontsize=12, color='0.3')
    # no bbox_inches='tight': with the cartopy gridliners it cropped into the maps
    fig.savefig(path, dpi=300)
    plt.close(fig)
    amap = anom.sel(lat=slice(*MAP_LAT), lon=slice(*MAP_LON))
    return dict(start=str(t0.date()), end=str(t1.date()), clim_years=anom.attrs['clim_years'],
                box=MONTEREY_BOX, box_mean_sst=round(box_mean(sst), 2), box_mean_anom=round(box_mean(anom), 2),
                map_max_anom=round(float(amap.max()), 2), map_min_anom=round(float(amap.min()), 2),
                map_min_sst=round(float(np.nanmin(vals)), 2), map_max_sst=round(float(np.nanmax(vals)), 2),
                sst_colour_range=[float(tmin), float(tmax)], anom_colour_range=[0., ANOM_MAX],
                extent=dict(lat=MAP_LAT, lon=MAP_LON), shoreline=shore, product='CoralTemp v3.1 (CRW_SST, PacIOOS dhw_5km)')


def main():
    """ Fetch, compute, draw and write the sidecar. Generated by JXP and Claude """
    ap = argparse.ArgumentParser()
    ap.add_argument('--end', default=None, help='last day (YYYY-MM-DD); default: last day CoralTemp has')
    args = ap.parse_args()
    end = pd.Timestamp(args.end) if args.end else last_day()
    print(f'[coraltemp] window ends {end:%Y-%m-%d}', flush=True)
    ds = load(end)
    sst, anom = week_maps(ds, end)
    os.makedirs(OUT_DIR, exist_ok=True)
    png = os.path.join(OUT_DIR, f'SST_{end:%b%Y}.png')
    stats = fig_sst_pair(sst, anom, png)
    # the same week from OISST (the product the newsletter text quotes), for comparison
    try:
        ods = oisst.load(start_year=CLIM_YEARS[0]).sel(time=slice(None, end))
        oanom = oisst.latest_anomaly_map(ods, ndays=NDAYS, clim_years=CLIM_YEARS)
        stats['oisst_same_week'] = dict(end=oanom.attrs['end'], box_mean_anom=round(box_mean(oanom), 2))
    except Exception as exc:   # comparison only
        stats['oisst_same_week'] = {'error': f'{exc.__class__.__name__}: {exc}'}
    with open(os.path.splitext(png)[0] + '.json', 'w') as fh:
        json.dump(stats, fh, indent=2)
    print('wrote', png)
    print(json.dumps(stats, indent=2))


if __name__ == '__main__':
    main()
