    same_month = anom[(pd.DatetimeIndex(anom['time']).month == last['time'].month)].dropna(subset=['anom'])
    stats['sea_level'] = dict(
        trend_mm_per_yr=anom.attrs['trend_mm_per_yr'],
        last_month=str(last['time'])[:7], last_anom_cm=100 * float(last['anom']),
        last12_mean_cm=100 * float(recent['anom'].mean()),
        rank_of_last_among_same_month=int((same_month['anom'] >= last['anom']).sum()),
        n_same_month=int(len(same_month)),
        record_month=str(anom.loc[anom['anom'].idxmax(), 'time'])[:7],
        record_anom_cm=100 * float(anom['anom'].max()))
    stats['enso'] = enso_relation(anom, oni)
    fig_sea_level_oni(anom, oni, os.path.join(FIG_DIR, 'fig_sealevel_oni.png'))

    # --- 2. the astronomical tide alone ------------------------------------------------
    pred_sc = fetch_hilo(SANTA_CRUZ, PRED_YEARS, kind='pred', download=dl)
    amax = annual_max_prediction(pred_sc)
    nodal = cycle_fit(amax)          # 18.6-yr nodal + 8.85-yr perigee precession
    this_year = amax[amax['year'] == 2026]
    decade = amax[(amax['year'] >= 2020) & (amax['year'] <= 2029)]
    stats['astronomical'] = dict(
        year_max_2026_m=float(this_year['max_pred'].iloc[0]),
        when_2026=str(this_year['when'].iloc[0]),
        decade_rank_2026=int((decade['max_pred'] >= float(this_year['max_pred'].iloc[0])).sum()),
        max_year_in_record=int(amax.loc[amax['max_pred'].idxmax(), 'year']),
        max_in_record_m=float(amax['max_pred'].max()),
        min_year_in_record=int(amax.loc[amax['max_pred'].idxmin(), 'year']),
        min_in_record_m=float(amax['max_pred'].min()),
        cycle_fit={k: v for k, v in nodal.items() if k != 'curve'},
        annual_max=amax.assign(when=amax['when'].astype(str)).to_dict(orient='records'))
    proxi = proxigean_by_year(f'{PRED_YEARS[0]}-01-01', f'{PRED_YEARS[1]}-12-31')
    stats['astronomical']['proxigean_by_year'] = [
        dict(year=int(r.year), distance_km=float(r.distance_km), time=str(r.time)[:16],
             hours_from_syzygy=float(r.hours_from_syzygy)) for r in proxi.itertuples()]
    stats['astronomical']['closest_alignment_2020s'] = int(
        proxi[(proxi.year >= 2020) & (proxi.year <= 2029)].sort_values('distance_km').iloc[0]['year'])
    fig_nodal_cycle(amax, os.path.join(FIG_DIR, 'fig_nodal_cycle.png'), fit=nodal, proxi=proxi)

    # Perigean spring tides: perigee close to new or full moon makes the big ones
    perigees = perigee_events('2026-09-01', '2027-04-30')
    big = amax[amax['year'] == 2026]
    when_big = pd.Timestamp(big['when'].iloc[0])
    lc_big = lunar_context([when_big]).iloc[0]
    near = perigees.iloc[(perigees['time'] - when_big).abs().argsort().iloc[0]]
    stats['perigean'] = dict(
        biggest_tide_of_2026=str(when_big),
        moon_distance_km=float(lc_big['distance_km']),
        degrees_from_syzygy=float(lc_big['from_syzygy_deg']),
        nearest_perigee=str(near['time']),
        nearest_perigee_distance_km=float(near['distance_km']),
        hours_between_tide_and_perigee=float((when_big - near['time']).total_seconds() / 3600.),
        perigee_hours_from_syzygy=float(near['hours_from_syzygy']),
        closest_perigee_of_season=str(perigees.loc[perigees['distance_km'].idxmin(), 'time']),
        closest_perigee_of_season_km=float(perigees['distance_km'].min()),
        perigees=[dict(time=str(r.time)[:16], distance_km=float(r.distance_km),
                       hours_from_syzygy=float(r.hours_from_syzygy)) for r in perigees.itertuples()])
    fig_perigee_winter(pred_sc, perigees, os.path.join(FIG_DIR, 'fig_perigee_winter.png'))

    # --- 3. observed minus predicted high water ------------------------------------------
    obs_mry = fetch_hilo(MONTEREY, OBS_YEARS, kind='obs', download=dl)
    pred_mry = fetch_hilo(MONTEREY, OBS_YEARS, kind='pred', download=dl)
    # The outlook needs predictions past the end of the observations
    pred_mry_future = fetch_hilo(MONTEREY, (2026, 2027), kind='pred', download=dl)
    res = residual_series(obs_mry, pred_mry)
    res_recent = res[res['date'] >= res['date'].max() - pd.Timedelta(days=365)]
    clim_res = res[(pd.DatetimeIndex(res['date']).year >= CLIM_YEARS[0])
                   & (pd.DatetimeIndex(res['date']).year <= CLIM_YEARS[1])]
    stats['residual'] = dict(
        last_date=str(res['date'].max())[:10],
        last12_mean_cm=100 * float(res_recent['residual'].mean()),
        clim_mean_cm=100 * float(clim_res['residual'].mean()),
        clim_sd_cm=100 * float(clim_res['residual'].std()),
        last12_days_above_10cm=int((res_recent['residual'] > 0.10).sum()),
        highest_hhw_recent_m=float(res_recent['hhw_obs'].max()),
        highest_hhw_recent_date=str(res_recent.loc[res_recent['hhw_obs'].idxmax(), 'date'])[:10],
        record_hhw_m=float(res['hhw_obs'].max()),
        record_hhw_date=str(res.loc[res['hhw_obs'].idxmax(), 'date'])[:10],
        n_days=int(len(res)))
    fig_residual(res, os.path.join(FIG_DIR, 'fig_residual.png'))
    if wharf is not None:   # test NOAA's subordinate-station offsets against the City's gauge
        stats['wharf_gauge']['comparison'] = compare_wharf_to_monterey(wharf, obs_mry, pred_mry)

    # --- 4. how often the water has actually reached flood level ---------------------------
    fd = flood_days(MONTEREY, OBS_YEARS)
    thr = threshold_days(res, minor_m)
    stats['flood_days'] = dict(
        source='NOAA derived-product API (htf_annual), calendar years',
        minor_total=int(fd['minor'].sum()),
        by_year=fd.to_dict(orient='records'),
        year_2026=int(fd.loc[fd['year'] == 2026, 'minor'].iloc[0]) if (fd['year'] == 2026).any() else None,
        worst_year=int(fd.loc[fd['minor'].idxmax(), 'year']),
        worst_year_days=int(fd['minor'].max()),
        thresholds_m_mllw=dict(minor=minor_m, moderate=moderate_m, major=major_m),
        # The same question asked of this analysis's own daily high waters
        winter_days_above_minor=thr.to_dict(orient='records'))
    fig_flood_days(fd, os.path.join(FIG_DIR, 'fig_flood_days.png'))

    # --- 5. what El Nino winters do to the residual ------------------------------------------
    wr = winter_residual_stats(res)
    nino = wr[wr['winter'].isin(BIG_NINO_WINTERS)]
    epoch = datum_epoch_offset(anom)
    stats['winter_residual'] = dict(
        by_winter=[dict(winter=int(r.winter), mean_cm=100 * float(r.mean),
                        median_cm=100 * float(r.median), p90_cm=100 * float(r.p90),
                        n=int(r.n)) for r in wr.itertuples()],
        all_winters_mean_cm=100 * float(wr['mean'].mean()),
        nino_winters=sorted(int(w) for w in nino['winter']),
        nino_mean_cm=100 * float(nino['mean'].mean()),
        nino_p90_cm=100 * float(nino['p90'].mean()),
        best_winter=int(wr.loc[wr['mean'].idxmax(), 'winter']),
        best_winter_mean_cm=100 * float(wr['mean'].max()),
        last_winter=int(wr['winter'].max()),
        last_winter_mean_cm=100 * float(wr.loc[wr['winter'].idxmax(), 'mean']),
        last_winter_p90_cm=100 * float(wr.loc[wr['winter'].idxmax(), 'p90']),
        datum_epoch=epoch)
    fig_winter_residual(wr, os.path.join(FIG_DIR, 'fig_winter_residual.png'))
    stats['extra_water'] = extra_water_stats(res)

    # --- 6. the winter ahead -------------------------------------------------------------------
    hh_sc = daily_higher_high(pred_sc)
    hh_mry = daily_higher_high(pred_mry_future)
    season = (pd.Timestamp('2026-10-01'), pd.Timestamp('2027-03-31'))
    win_sc = hh_sc[(hh_sc['date'] >= season[0]) & (hh_sc['date'] <= season[1])]
    win_mry = hh_mry[(hh_mry['date'] >= season[0]) & (hh_mry['date'] <= season[1])]
    top = win_sc.nlargest(10, 'hhw')
    # Three ways to say "what sea level will sit under the tide this winter":
    #   - the regression on the ONI forecast
    #   - the average strong-El-Nino winter in this record
    #   - 1998, the strongest analogue, at its 90th-percentile day
    oni_forecast = 2.0
    off_reg = stats['enso']['slope_cm_per_degC'] * oni_forecast + stats['enso']['intercept_cm']
    off_nino = stats['winter_residual']['nino_mean_cm']
    # Worst case: the strongest El Nino winter in the record, at its 90th-percentile day
    worst = nino.loc[nino['p90'].idxmax()]
    off_worst = 100 * float(worst['p90'])
    worst_label = f"{int(worst['winter']) - 1}–{str(int(worst['winter']))[2:]}"
    scenarios = {f'+ typical strong El Niño winter ({off_nino:.0f} cm)': off_nino,
                 f'+ {worst_label} analogue, worst days ({off_worst:.0f} cm)': off_worst}
    mhhw = dat['MHHW'] - dat['MLLW']          # average daily higher-high, m above MLLW
    def above_mhhw_ft(level_m):
        """ Height above mean higher-high water, in feet. Generated by JXP and Claude """
        return (level_m - mhhw) / (12 * IN)
    stats['outlook'] = dict(
        mhhw_m=float(mhhw),
        peak_pred_above_mhhw_ft=above_mhhw_ft(float(win_mry['hhw'].max())),
        peak_plus_nino_above_mhhw_ft=above_mhhw_ft(float(win_mry['hhw'].max() + off_nino / 100.)),
        peak_plus_worst_above_mhhw_ft=above_mhhw_ft(float(win_mry['hhw'].max() + off_worst / 100.)),
        record_1983_above_mhhw_ft=above_mhhw_ft(2.401),
        season=[str(season[0])[:10], str(season[1])[:10]],
        oni_forecast_used=oni_forecast,
        offset_from_regression_cm=float(off_reg),
        offset_typical_nino_cm=float(off_nino),
        worst_analogue_winter=int(worst['winter']),
        offset_worst_p90_cm=float(off_worst),
        top_predicted_santa_cruz=[dict(date=str(r.date)[:10], hhw_m=float(r.hhw))
                                  for r in top.itertuples()],
        highest_predicted_sc_m=float(win_sc['hhw'].max()),
        highest_predicted_sc_date=str(win_sc.loc[win_sc['hhw'].idxmax(), 'date'])[:10],
        highest_predicted_mry_m=float(win_mry['hhw'].max()),
        minor_m=minor_m, moderate_m=moderate_m,
        minor_m_santa_cruz=minor_m * offs['heightOffsetHighTide'],
        # Everything below is at Monterey, where the flood levels are defined
        days_above_minor_pred=int((win_mry['hhw'] > minor_m).sum()),
        days_above_minor_plus_nino=int((win_mry['hhw'] + off_nino / 100. > minor_m).sum()),
        days_above_minor_plus_worst=int((win_mry['hhw'] + off_worst / 100. > minor_m).sum()),
        peak_plus_nino_m=float(win_mry['hhw'].max() + off_nino / 100.),
        peak_plus_worst_m=float(win_mry['hhw'].max() + off_worst / 100.),
        record_observed_m=stats['residual']['record_hhw_m'],
        record_observed_date=stats['residual']['record_hhw_date'],
        # `dat` is metric, so the record high water converts with the metric MLLW
        station_record_m=(float(dat['record_max']) - dat['MLLW']) if dat.get('record_max') else None,
        station_record_date=dat.get('record_max_date'))
    fig_outlook(pred_mry_future, os.path.join(FIG_DIR, 'fig_winter_outlook.png'),
                minor_m, moderate_m, scenarios,
                sc_ratio=offs['heightOffsetHighTide'])

    # --- the biggest observed high waters, for the report's table ------------------------------
    top_obs = res.nlargest(12, 'hhw_obs')
    stats['biggest_observed'] = [dict(date=str(r.date)[:10], hhw_m=float(r.hhw_obs),
                                      pred_m=float(r.hhw_pred), residual_cm=100 * float(r.residual))
                                 for r in top_obs.itertuples()]

    out = os.path.join(OUT_DIR, 'tide_stats.json')
    with open(out, 'w') as fh:
        json.dump(stats, fh, indent=2, default=str)
    print('wrote', out)
    print(json.dumps({k: v for k, v in stats.items() if k != 'astronomical'}, indent=2,
                     default=str)[:2500])


