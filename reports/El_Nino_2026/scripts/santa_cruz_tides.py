def datums(station, units='metric'):
    """ Tidal datums of a station, in metres above station datum (STND).

    Parameters
    ----------
    station : str
    units : str, 'metric' or 'english'

    Returns
    -------
    dict : datum name -> value, plus `epoch`, `HAT` and the record maximum

    Generated by JXP and Claude
    """
    r = requests.get(f'{MDAPI}{station}/datums.json', params=dict(units=units),
                     headers=HEADERS, timeout=TIMEOUT)
    r.raise_for_status()
    j = r.json()
    out = {d['name']: float(d['value']) for d in (j.get('datums') or [])}
    out.update(epoch=j.get('epoch'), HAT=j.get('HAT'),
               record_max=j.get('max'), record_max_date=j.get('maxdate'))
    return out


