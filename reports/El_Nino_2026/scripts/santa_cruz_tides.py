""" Tides at the Santa Cruz Wharf (and Monterey Bay): are they running high?

Background that shapes everything here: **NOAA station 9413745 "Santa Cruz,
Monterey Bay" is a subordinate station** (type `S`).  It publishes tide
*predictions* only, derived from the Monterey gauge (9413450) with published
offsets -- high waters x0.97 and 6 minutes earlier, low waters x0.99 and 11
minutes earlier.  There is no water-level record at the wharf itself (the
CeNCOOS shore station on the wharf measures water properties, not water level),
so every *observation* in this analysis comes from Monterey, 25 km across the
bay, and is translated to Santa Cruz with those offsets where useful.

What the script computes, for `tides_monterey_bay_sep2026.md`:

  1. Monthly mean sea level at Monterey (1973-), de-trended and referenced to a
     1991-2020 monthly climatology (`cugn.indices.sea_level_anomaly`), against
     NOAA's ONI -- the "is the ocean standing higher than normal?" question.
  2. The astronomical tide by itself: the annual highest predicted tide at Santa
     Cruz over several decades, which exposes the 18.6-year lunar nodal cycle and
     shows where 2026-27 sits in it.
  3. Observed daily higher-high water at Monterey against its own prediction.
     The difference (the non-tidal residual) is the part El Nino and storms can
     move, separated from the astronomy.
  4. High-tide-flooding days per year at Monterey from NOAA's derived-product
     API, with the station's minor/moderate/major thresholds.
  5. The winter outlook: the highest predicted tides at Santa Cruz for the coming
     season, and what a typical El Nino residual would add to them.

Outputs
-------
  * `reports/El_Nino_2026/tides/figs/fig_*.png` (named for what they show, not
    numbered, so the report can order them as it likes)
  * `reports/El_Nino_2026/tides/tide_stats.json` -- every number the report quotes

Usage (ocean14):
    python reports/El_Nino_2026/scripts/santa_cruz_tides.py [--no-download]

Generated by JXP and Claude
"""
