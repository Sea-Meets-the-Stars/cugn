def flood_days(station, years=OBS_YEARS):
    """ Annual counts of minor/moderate/major high-tide-flooding days.

    Parameters
    ----------
    station : str
    years : (int, int), inclusive range

    Returns
    -------
    pandas.DataFrame : `year`, `minor`, `moderate`, `major`, `completeness`

    Generated by JXP and Claude
    """
    n = years[1] - years[0] + 1
    r = requests.get(HTF_API, params=dict(station=station, year=years[0], range=n),
                     headers=HEADERS, timeout=TIMEOUT)
    r.raise_for_status()
    rows = r.json().get('AnnualFloodCount', [])
    return pd.DataFrame([dict(year=x['year'], minor=x['minCount'], moderate=x['modCount'],
                              major=x['majCount'], completeness=x['percent_completeness'])
                         for x in rows]).sort_values('year').reset_index(drop=True)


def fetch_hilo(station, years, kind='obs', download=True, verbose=True):
    """ Observed or predicted high/low waters for a span of years, cached as CSV.

    The API serves one calendar year per request for both products.

    Parameters
    ----------
    station : str
    years : (int, int), inclusive
    kind : str, 'obs' (product `high_low`) or 'pred' (product `predictions`)
    download : bool, fetch missing years (False = use the cache only)
    verbose : bool

    Returns
    -------
    pandas.DataFrame : `time`, `level` (m above MLLW), `type` ('H'/'L'/'HH'/'LL')

    Generated by JXP and Claude
    """
    os.makedirs(CACHE_DIR, exist_ok=True)
    frames = []
    for yr in range(years[0], years[1] + 1):
        # One file per year: a dropped connection then costs one year, not the lot
        path = os.path.join(CACHE_DIR, f'{station}_{kind}_hilo_{yr}.csv')
        if os.path.exists(path):
            frames.append(pd.read_csv(path, parse_dates=['time']))
            continue
        if not download:
            continue
        params = dict(station=station, datum='MLLW',
                      begin_date=f'{yr}0101', end_date=f'{yr}1231')
        if kind == 'obs':
            params.update(product='high_low')
        else:
            params.update(product='predictions', interval='hilo')
        df = _get(params)
        if not len(df):
            if verbose:
                print(f'   {yr}: no data', flush=True)
            continue
        if kind == 'obs':
            sub = pd.DataFrame({'time': pd.to_datetime(df['Date Time']),
                                'level': pd.to_numeric(df['Water Level'], errors='coerce'),
                                'type': df['TY'].astype(str).str.strip()})
        else:
            sub = pd.DataFrame({'time': pd.to_datetime(df['Date Time']),
                                'level': pd.to_numeric(df['Prediction'], errors='coerce'),
                                'type': df['Type'].astype(str).str.strip()})
        sub.to_csv(path, index=False)
        frames.append(sub)
        if verbose and yr % 5 == 0:
            print(f'   {kind} {station}: through {yr}', flush=True)
    if not frames:
        raise RuntimeError(f'no {kind} data for {station} in {years}')
    return pd.concat(frames, ignore_index=True).sort_values('time').reset_index(drop=True)


def hohonu_token(path='~/.hohonu_token'):
    """ API key for the Hohonu dashboard, from the environment or a dot-file.

    The City of Santa Cruz's wharf gauge is on the Hohonu network.  Its public
    dashboard reads `https://dashboard.hohonu.io/api/v1/stations/<id>/statistic/`,
    which answers 401 without a key, so bulk data needs one from the City or from
    Hohonu.  Put it in $HOHONU_API_KEY or in `~/.hohonu_token`.

    Parameters
    ----------
    path : str, dot-file checked when the environment variable is unset

    Returns
    -------
    str or None : the key, or None when there is none to be had

    Generated by JXP and Claude
    """
    tok = os.environ.get('HOHONU_API_KEY')
    if tok:
        return tok.strip()
    path = os.path.expanduser(path)
    if os.path.exists(path):
        with open(path) as fh:
            return fh.read().strip()
    return None


def hohonu_fetch(start, end, station=HOHONU_STATION, datum='NAVD', download=True, verbose=True):
    """ Water level from the City of Santa Cruz wharf gauge, cached as CSV.

    Returns None (rather than raising) when no API key is available, so the rest
    of the analysis still runs; the report then says the wharf record is pending.

    Parameters
    ----------
    start, end : date-like, inclusive range
    station : str, Hohonu station id
    datum : str, vertical datum requested from the API ('NAVD', 'MLLW', 'STND')
    download : bool, fetch when the cache is cold
    verbose : bool

    Returns
    -------
    pandas.DataFrame with `time` and `level` (m), or None

    Generated by JXP and Claude
    """
    os.makedirs(CACHE_DIR, exist_ok=True)
    t0, t1 = pd.Timestamp(start), pd.Timestamp(end)
    path = os.path.join(CACHE_DIR, f'{station}_{datum}_{t0:%Y%m%d}-{t1:%Y%m%d}.csv')
    if os.path.exists(path):
        return pd.read_csv(path, parse_dates=['time'])
    if not download:
        return None
    tok = hohonu_token()
    if tok is None:
        if verbose:
            print('[hohonu] no API key ($HOHONU_API_KEY or ~/.hohonu_token); '
                  'skipping the City of Santa Cruz wharf gauge', flush=True)
        return None
    url = f'{HOHONU_API}/stations/{station}/statistic/'
    r = requests.get(url, params=dict(**{'from': f'{t0:%Y-%m-%d}', 'to': f'{t1:%Y-%m-%d}'},
                                      datum=datum, cleaned='true'),
                     headers=dict(Authorization=tok, **HEADERS), timeout=TIMEOUT)
    if r.status_code != 200:
        print(f'[hohonu] HTTP {r.status_code}: {r.text[:200]}', flush=True)
        return None
    j = r.json()
    # The API returns {"data": [[timestamp, value], ...]} for this endpoint;
    # accept a list of records too, in case the shape differs for this station.
    rows = j['data'] if isinstance(j, dict) and 'data' in j else j
    if isinstance(rows[0], dict):
        df = pd.DataFrame(rows).rename(columns={'timestamp': 'time', 'value': 'level'})
    else:
        df = pd.DataFrame(rows, columns=['time', 'level'])
    df['time'] = pd.to_datetime(df['time'])
    df['level'] = pd.to_numeric(df['level'], errors='coerce')
    df = df[['time', 'level']].dropna().sort_values('time').reset_index(drop=True)
    df.to_csv(path, index=False)
    if verbose:
        print(f'[hohonu] {len(df)} rows, {df.time.min()} .. {df.time.max()}', flush=True)
    return df


def compare_wharf_to_monterey(wharf, mry_obs, mry_pred):
    """ Check NOAA's Santa Cruz offsets against the City's own wharf record.

    Fits the height ratio between the two gauges' daily higher-high waters (which
    NOAA gives as 0.97) and the lag of the wharf high water behind Monterey's
    (NOAA gives -6 minutes), and reports how the wharf residual compares.

    Parameters
    ----------
    wharf : pandas.DataFrame with `time`, `level` (m, any datum)
    mry_obs, mry_pred : pandas.DataFrame with `time`, `level`, `type` (Monterey)

    Returns
    -------
    dict : fitted ratio, mean lag in minutes, number of matched days and the
        mean wharf-minus-Monterey difference

    Generated by JXP and Claude
    """
    w = wharf.copy()
    w['date'] = pd.DatetimeIndex(w['time']).normalize()
    # Daily maximum of the wharf record, and when it happened
    idx = w.groupby('date')['level'].idxmax()
    wh = w.loc[idx].rename(columns={'level': 'hhw_w', 'time': 't_w'})[['date', 'hhw_w', 't_w']]
    m = daily_higher_high(mry_obs).merge(wh, on='date')
    if not len(m):
        return dict(n_days=0)
    lag_min = (pd.DatetimeIndex(m['t_w']) - pd.DatetimeIndex(m['time_of_hhw'])).total_seconds() / 60.
    ratio = float(np.polyfit(m['hhw'], m['hhw_w'], 1)[0])
    return dict(n_days=int(len(m)), height_ratio=ratio,
                mean_lag_min=float(np.mean(lag_min)), median_lag_min=float(np.median(lag_min)),
                mean_difference_m=float((m['hhw_w'] - m['hhw']).mean()),
                first_day=str(m['date'].min())[:10], last_day=str(m['date'].max())[:10])


def high_waters(df):
    """ Every high water, stamped in local standard time.

    Parameters
    ----------
    df : pandas.DataFrame with `time` (GMT), `level`, `type`

    Returns
    -------
    pandas.DataFrame : `time` (local standard), `level`, `date` (local day)

    Generated by JXP and Claude
    """
    highs = df[df['type'].str.startswith('H')].copy()
    highs['time'] = pd.DatetimeIndex(highs['time']) + LOCAL_OFFSET
    highs['date'] = pd.DatetimeIndex(highs['time']).normalize()
    return highs[['time', 'level', 'date']].sort_values('time').reset_index(drop=True)


def daily_higher_high(df):
    """ The highest high water of each local day.

    Parameters
    ----------
    df : pandas.DataFrame with `time`, `level`, `type`

    Returns
    -------
    pandas.DataFrame : `date`, `hhw` (m above MLLW), `time_of_hhw`

    Generated by JXP and Claude
    """
    highs = high_waters(df)
    idx = highs.groupby('date')['level'].idxmax()
    out = highs.loc[idx, ['date', 'level', 'time']].rename(
        columns={'level': 'hhw', 'time': 'time_of_hhw'})
    return out.reset_index(drop=True)


def residual_series(obs_raw, pred_raw, tolerance='3h'):
    """ Observed minus predicted high water, matched tide by tide.

    Each observed high water is paired with the *nearest predicted high water*
    rather than with the highest prediction of the same calendar day.  That
    matters: the higher-high often falls within a couple of hours of midnight,
    and calendar-day matching then differences two different tide cycles, which
    manufactured apparent residuals of up to 0.9 m in July and August.

    Parameters
    ----------
    obs_raw, pred_raw : pandas.DataFrame with `time`, `level`, `type`
        (the raw high/low tables, not daily maxima)
    tolerance : str, how far a prediction may be from its observation

    Returns
    -------
    pandas.DataFrame : `date` (local day), `hhw_obs`, `hhw_pred`, `residual` (m),
        one row per day, for the day's highest observed high water

    Generated by JXP and Claude
    """
    obs, pred = high_waters(obs_raw), high_waters(pred_raw)
    m = pd.merge_asof(obs, pred[['time', 'level']].rename(columns={'level': 'pred'}),
                      on='time', direction='nearest', tolerance=pd.Timedelta(tolerance))
    m = m.dropna(subset=['pred'])
    m['residual'] = m['level'] - m['pred']
    # Keep the day's highest observed high water
    idx = m.groupby('date')['level'].idxmax()
    out = m.loc[idx].rename(columns={'level': 'hhw_obs', 'pred': 'hhw_pred'})
    return out[['date', 'hhw_obs', 'hhw_pred', 'residual']].reset_index(drop=True)


def annual_max_prediction(pred):
    """ Highest predicted tide of each calendar year (the astronomical envelope).

    Parameters
    ----------
    pred : pandas.DataFrame with `time`, `level`, `type`

    Returns
    -------
    pandas.DataFrame : `year`, `max_pred` (m above MLLW), `when`

    Generated by JXP and Claude
    """
    highs = pred[pred['type'].str.startswith('H')].copy()
    highs['year'] = pd.DatetimeIndex(highs['time']).year
    idx = highs.groupby('year')['level'].idxmax()
    out = highs.loc[idx, ['year', 'level', 'time']].rename(
        columns={'level': 'max_pred', 'time': 'when'})
    return out.reset_index(drop=True)


def winter_of(dates):
    """ Label each date with the year of the January of its winter.

    Parameters
    ----------
    dates : array-like of datetimes

    Returns
    -------
    numpy.ndarray of int

    Generated by JXP and Claude
    """
    t = pd.DatetimeIndex(dates)
    return np.where(t.month >= 11, t.year + 1, t.year)


def winter_residual_stats(res, months=(11, 12, 1, 2), min_days=90):
    """ Non-tidal residual of the daily high tide, winter by winter.

    Parameters
    ----------
    res : pandas.DataFrame from `residual_series`
    months : tuple of int, months counted as winter
    min_days : int, drop winters with fewer days than this

    Returns
    -------
    pandas.DataFrame : `winter`, `mean`, `median`, `p90`, `n` (metres)

    Generated by JXP and Claude
    """
    r = res.copy()
    t = pd.DatetimeIndex(r['date'])
    r['winter'] = winter_of(r['date'])
    r = r[t.month.isin(months)]
    g = r.groupby('winter')['residual'].agg(
        mean='mean', median='median', p90=lambda x: x.quantile(0.9), n='size').reset_index()
    return g[g['n'] >= min_days].reset_index(drop=True)


def threshold_days(res, level, months=(11, 12, 1, 2, 3)):
    """ Days per winter on which the observed high water passed a level.

    Parameters
    ----------
    res : pandas.DataFrame from `residual_series`
    level : float, water level in m above MLLW
    months : tuple of int, months counted

    Returns
    -------
    pandas.DataFrame : `winter`, `days`

    Generated by JXP and Claude
    """
    r = res.copy()
    t = pd.DatetimeIndex(r['date'])
    r['winter'] = winter_of(r['date'])
    r = r[t.month.isin(months)]
    g = r.groupby('winter')['hhw_obs'].agg(days=lambda x: int((x > level).sum())).reset_index()
    return g


def datum_epoch_offset(anom, epoch_center=1992.0, when=None):
    """ How much of today's high water is simply sea-level rise since the datum epoch.

    Predictions are referenced to the 1983-2001 tidal datum epoch, so a rising
    sea shows up as a positive observed-minus-predicted residual even in a
    perfectly ordinary year.  This converts the fitted linear trend into that
    offset.

    Parameters
    ----------
    anom : pandas.DataFrame from `cugn.indices.sea_level_anomaly`
        (its `.attrs['trend_mm_per_yr']` carries the rate)
    epoch_center : float, decimal year at the centre of the datum epoch
    when : float or None, decimal year to evaluate at (default: now)

    Returns
    -------
    dict : `trend_mm_per_yr`, `years_since_epoch`, `offset_cm`

    Generated by JXP and Claude
    """
    now = when if when is not None else (pd.Timestamp.now().year
                                         + pd.Timestamp.now().dayofyear / 365.25)
    rate = anom.attrs['trend_mm_per_yr']
    return dict(trend_mm_per_yr=rate, years_since_epoch=now - epoch_center,
                offset_cm=rate * (now - epoch_center) / 10.)


def nodal_fit(amax, period=18.613):
    """ Least-squares sinusoid at the lunar nodal period through the annual maxima.

    The highest tide of a year is noisy -- it depends on whether a perigean
    spring tide happens to land near a solstice -- so the 18.6-year modulation is
    easier to see as a fitted curve than by eye.

    Parameters
    ----------
    amax : pandas.DataFrame from `annual_max_prediction`
    period : float, lunar nodal period in years

    Returns
    -------
    dict : `amplitude_cm`, `mean_m`, `peak_year` (the modelled maximum nearest
        the middle of the record) and `curve` (year -> fitted value)

    Generated by JXP and Claude
    """
    yr = amax['year'].to_numpy(dtype=float)
    y = amax['max_pred'].to_numpy(dtype=float)
    w = 2 * np.pi / period
    X = np.column_stack([np.ones_like(yr), np.cos(w * yr), np.sin(w * yr)])
    coef, *_ = np.linalg.lstsq(X, y, rcond=None)
    amp = float(np.hypot(coef[1], coef[2]))
    phase = float(np.arctan2(coef[2], coef[1]))         # peak where w*yr = phase
    # Nodal peak closest to the middle of the record
    k = np.round((yr.mean() * w - phase) / (2 * np.pi))
    peak_year = float((phase + 2 * np.pi * k) / w)
    return dict(amplitude_cm=100 * amp, mean_m=float(coef[0]), peak_year=peak_year,
                period_yr=period, curve=(X @ coef).tolist())


def lunar_context(times):
    """ Moon-Earth distance and Moon-Sun elongation at a set of times.

    Uses astropy's built-in ephemeris, which is far more accurate than this
    application needs.  Elongation near 0 or 180 degrees is syzygy (new or full
    moon); small distances are perigee.

    Parameters
    ----------
    times : array-like of datetimes (UTC)

    Returns
    -------
    pandas.DataFrame : `time`, `distance_km`, `elongation_deg`,
        `from_syzygy_deg` (0 at new or full moon)

    Generated by JXP and Claude
    """
    t = Time(pd.DatetimeIndex(times).to_pydatetime(), scale='utc')
    moon, sun = get_body('moon', t), get_body('sun', t)
    elong = moon.separation(sun).deg
    return pd.DataFrame(dict(time=pd.DatetimeIndex(times),
                             distance_km=moon.distance.to('km').value,
                             elongation_deg=elong,
                             from_syzygy_deg=np.minimum(elong, 180. - elong)))


def perigee_events(t0, t1, step_hours=3):
    """ Times of lunar perigee in a window, with how close each is to syzygy.

    Perigee is found as a local minimum of the Moon-Earth distance sampled every
    `step_hours`, then refined by a parabola through the three samples.

    Parameters
    ----------
    t0, t1 : date-like, window to search
    step_hours : int, sampling interval

    Returns
    -------
    pandas.DataFrame : `time`, `distance_km`, `from_syzygy_deg`,
        `hours_from_syzygy` (signed time to the nearest new or full moon)

    Generated by JXP and Claude
    """
    grid = pd.date_range(t0, t1, freq=f'{step_hours}h')
    lc = lunar_context(grid)
    d = lc['distance_km'].to_numpy()
    lo = np.where((d[1:-1] < d[:-2]) & (d[1:-1] < d[2:]))[0] + 1
    rows = []
    for i in lo:
        # Parabolic refinement of the minimum in time
        y0, y1, y2 = d[i - 1], d[i], d[i + 1]
        shift = 0.5 * (y0 - y2) / (y0 - 2 * y1 + y2)
        tmin = grid[i] + pd.Timedelta(hours=step_hours * shift)
        rows.append(dict(time=tmin, distance_km=float(y1 - 0.25 * (y0 - y2) * shift)))
    out = pd.DataFrame(rows)
    if not len(out):
        return out
    lc2 = lunar_context(out['time'])
    out['from_syzygy_deg'] = lc2['from_syzygy_deg'].to_numpy()
    # Elongation moves ~12.2 deg/day relative to the sun, so convert to hours
    out['hours_from_syzygy'] = out['from_syzygy_deg'] / 12.19 * 24.
    return out


def proxigean_by_year(t0, t1, syzygy_hours=24., step_hours=6):
    """ The closest perigee-at-syzygy of each year: the 8.85-year cycle made visible.

    Fitting the 8.85-year perigee-precession cycle to the annual highest tide
    barely registers, because every year contains several perigean spring tides.
    What the cycle actually controls is how *close* the best alignment gets, so
    that is what this measures: among the perigees falling within `syzygy_hours`
    of a new or full moon, the smallest Moon-Earth distance of the year.

    Parameters
    ----------
    t0, t1 : date-like, window to search
    syzygy_hours : float, how close to new/full moon a perigee must fall
    step_hours : int, sampling interval passed to `perigee_events`

    Returns
    -------
    pandas.DataFrame : `year`, `distance_km`, `time`, `hours_from_syzygy`

    Generated by JXP and Claude
    """
    ev = perigee_events(t0, t1, step_hours=step_hours)
    ev = ev[ev['hours_from_syzygy'] <= syzygy_hours].copy()
    ev['year'] = pd.DatetimeIndex(ev['time']).year
    idx = ev.groupby('year')['distance_km'].idxmin()
    out = ev.loc[idx, ['year', 'distance_km', 'time', 'hours_from_syzygy']]
    return out.sort_values('year').reset_index(drop=True)


def cycle_fit(amax, periods=(18.613, 8.847)):
    """ Fit the lunar nodal and perigee cycles to the annual highest tides.

    Parameters
    ----------
    amax : pandas.DataFrame from `annual_max_prediction`
    periods : tuple of float, cycle periods in years (nodal, perigee precession)

    Returns
    -------
    dict : per-period amplitude in cm and the year of its modelled maximum
        nearest the middle of the record, plus the fitted `curve`

    Generated by JXP and Claude
    """
    yr = amax['year'].to_numpy(dtype=float)
    y = amax['max_pred'].to_numpy(dtype=float)
    cols = [np.ones_like(yr)]
    for P in periods:
        w = 2 * np.pi / P
        cols += [np.cos(w * yr), np.sin(w * yr)]
    X = np.column_stack(cols)
    coef, *_ = np.linalg.lstsq(X, y, rcond=None)
    out = dict(mean_m=float(coef[0]), curve=(X @ coef).tolist(), periods=list(periods))
    for k, P in enumerate(periods):
        c, sn = coef[1 + 2 * k], coef[2 + 2 * k]
        w = 2 * np.pi / P
        phase = float(np.arctan2(sn, c))
        n = np.round((yr.mean() * w - phase) / (2 * np.pi))
        out[f'amplitude_{P:g}yr_cm'] = float(100 * np.hypot(c, sn))
        out[f'peak_year_{P:g}yr'] = float((phase + 2 * np.pi * n) / w)
    return out


def extra_water_stats(res, winters_nino=BIG_NINO_WINTERS, months=(11, 12, 1, 2)):
    """ How often the high tide carries a given amount of extra water.

    Answers the planning question directly: on what fraction of winter days does
    the observed high water stand 6 inches, or a foot, above the predicted tide?

    Parameters
    ----------
    res : pandas.DataFrame from `residual_series`
    winters_nino : list of int, winters (year of the January) counted as El Nino
    months : tuple of int, months counted as winter

    Returns
    -------
    dict : fractions and day counts for 15 cm (6 in) and 30 cm (1 ft), for all
        winters, El Nino winters, and the last 12 months

    Generated by JXP and Claude
    """
    r = res.copy()
    t = pd.DatetimeIndex(r['date'])
    r['winter'] = winter_of(r['date'])
    win = r[t.month.isin(months)]
    nino = win[win['winter'].isin(winters_nino)]
    recent = r[r['date'] >= r['date'].max() - pd.Timedelta(days=365)]
    out = {}
    for label, sub in [('all_winters', win), ('nino_winters', nino), ('last12_months', recent)]:
        out[label] = dict(n_days=int(len(sub)),
                          frac_above_6in=float((sub['residual'] > 6 * IN).mean()),
                          frac_above_1ft=float((sub['residual'] > 12 * IN).mean()),
                          days_above_1ft=int((sub['residual'] > 12 * IN).sum()),
                          mean_in=float(sub['residual'].mean() / IN),
                          p90_in=float(sub['residual'].quantile(0.9) / IN),
                          max_in=float(sub['residual'].max() / IN))
    return out


def enso_relation(anom, oni, season=(11, 12, 1, 2)):
    """ How much higher the sea stands per degree of ONI, in winter.

    Parameters
    ----------
    anom : pandas.DataFrame with `time`, `anom` (m) from sea_level_anomaly
    oni : pandas.DataFrame with `time`, `oni` (deg C)
    season : tuple of months treated as "winter"

    Returns
    -------
    dict : slope (cm per deg C), correlation, n, and the per-winter means

    Generated by JXP and Claude
    """
    a = anom.dropna(subset=['anom']).copy()
    a['ym'] = pd.DatetimeIndex(a['time']).to_period('M')
    o = oni.copy()
    o['ym'] = pd.DatetimeIndex(o['time']).to_period('M')
    m = a.merge(o[['ym', 'oni']], on='ym')
    mon = pd.DatetimeIndex(m['time']).month
    # Label each winter by the year of its January
    winter_year = np.where(mon >= 11, pd.DatetimeIndex(m['time']).year + 1,
                           pd.DatetimeIndex(m['time']).year)
    sel = np.isin(mon, season)
    w = pd.DataFrame(dict(winter=winter_year[sel], anom=m['anom'].to_numpy()[sel],
                          oni=m['oni'].to_numpy()[sel]))
    wm = w.groupby('winter').agg(anom=('anom', 'mean'), oni=('oni', 'mean'),
                                 n=('anom', 'size')).reset_index()
    wm = wm[wm['n'] >= 3]                                   # complete winters only
    slope, intercept = np.polyfit(wm['oni'], wm['anom'], 1)
    r = float(np.corrcoef(wm['oni'], wm['anom'])[0, 1])
    return dict(slope_cm_per_degC=float(slope * 100), intercept_cm=float(intercept * 100),
                r=r, n=int(len(wm)), winters=wm.to_dict(orient='records'))


