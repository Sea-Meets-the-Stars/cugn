def _get(params, tries=5, pause=10.):
    """ One CO-OPS datagetter call, retried, returned as a DataFrame.

    Parameters
    ----------
    params : dict, query parameters passed to `cugn.indices._coops_request`
    tries : int, attempts before giving up
    pause : float, seconds between attempts

    Returns
    -------
    pandas.DataFrame : parsed CSV (empty when the API reports no data)

    Generated by JXP and Claude
    """
    for i in range(tries):
        try:
            return indices._coops_csv_to_frame(indices._coops_request(params))
        except Exception as exc:
            if i == tries - 1:
                raise
            print(f'   retry after {exc.__class__.__name__}', flush=True)
            time.sleep(pause * (i + 1))        # back off; DNS/network drops clear slowly


