""" Daily sea-level anomaly at Monterey (and San Francisco) for the public newsletter.

The monthly anomalies in the report (``cugn.indices.sea_level_anomaly``) are too
coarse to show the coastal Kelvin wave arriving, which happens over days.  This
script takes the hourly CO-OPS record cached by ``cugn.indices`` (verified where
available, preliminary for the latest weeks), forms daily means, and removes the
same seasonal climatology and linear trend the monthly anomaly uses, so the two
agree when averaged over a month.  The 1991-2020 monthly climatology is
interpolated to the day of year.

Outputs (in ``reports/El_Nino_2026/newsletter/figs/``):
  * ``newsletter_fig3_sealevel_<Mon><YYYY>.png`` -- a public figure of the daily
    anomaly since June, pink above normal, blue below;
  * a JSON sidecar beside it with the numbers the caption and text quote.

Usage (ocean14):
    python reports/El_Nino_2026/scripts/make_newsletter_sealevel.py --date 2026-10-10

Generated by JXP and Claude
"""
import os
import json
import argparse

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.dates as mdates

from cugn import indices

REPORT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIG_DIR = os.path.join(REPORT_DIR, 'newsletter', 'figs')
STATIONS = {'9413450': 'Monterey', '9414290': 'San Francisco'}
CLIM_YEARS = (1991, 2020)


def daily_anomaly(station, clim_years=CLIM_YEARS):
    """ Daily-mean sea level at a CO-OPS station as an anomaly from normal.

    Parameters
    ----------
    station : str, CO-OPS station id (e.g. '9413450' Monterey)
    clim_years : (int, int), years of the seasonal climatology

    Returns
    -------
    pandas.DataFrame : `time` (noon of each day), `msl` (m), `anom_cm`
        (cm above the seasonal normal and trend), `preliminary` (True if any
        hour of that day came from the preliminary product); `.attrs` holds
        `trend_mm_per_yr` and `station_name`.

    Generated by JXP and Claude
    """
    monthly = indices.sea_level_anomaly(indices.load_sea_level(station), clim_years=clim_years)
    hourly = indices.load_hourly_sea_level(station)
    daily = indices.daily_mean(hourly)
    # Days with any preliminary hour are flagged, for the caption
    pday = hourly.groupby(pd.DatetimeIndex(hourly['time']).normalize())['preliminary'].max()
    daily['preliminary'] = pday.reindex(pd.DatetimeIndex(daily['time']).normalize()).fillna(0).to_numpy() > 0
    # Same trend as the monthly anomaly: slope referenced to the centre of clim_years
    t = pd.DatetimeIndex(daily['time'])
    tyr = np.asarray(t.year + (t.dayofyear - 0.5) / 365.25, dtype=float)
    tm = pd.DatetimeIndex(monthly['time'])
    in_clim = (tm.year >= clim_years[0]) & (tm.year <= clim_years[1])
    tref = np.asarray(tm.year + (tm.dayofyear - 0.5) / 365.25, dtype=float)[in_clim].mean()
    slope = monthly.attrs['trend_mm_per_yr'] / 1000.          # m per year
    trend = slope * (tyr - tref)
    # Monthly climatology (12 values at mid-month) interpolated around the year
    clim12 = (monthly.loc[in_clim].assign(month=tm[in_clim].month)
              .groupby('month')['clim'].first().reindex(np.arange(1, 13)).to_numpy())
    mid = np.array([15.5, 45., 74.5, 105., 135.5, 166., 196.5, 227.5, 258., 288.5, 319., 349.5])
    doy = np.asarray(t.dayofyear, dtype=float)
    clim_day = np.interp(doy, np.r_[mid[-1] - 365.25, mid, mid[0] + 365.25],
                         np.r_[clim12[-1], clim12, clim12[0]])
    daily['anom_cm'] = 100. * (daily['msl'].to_numpy() - clim_day - trend)
    daily.attrs['trend_mm_per_yr'] = monthly.attrs['trend_mm_per_yr']
    daily.attrs['station_name'] = STATIONS.get(station, station)
    return daily


def summarize(frames, date, ndays=7):
    """ Numbers for the caption and the text.

    Parameters
    ----------
    frames : dict, station name -> DataFrame from daily_anomaly()
    date : pandas.Timestamp, the report date (last day used)
    ndays : int, length of the trailing window averaged

    Returns
    -------
    dict : per station, `last_day`, `last_{ndays}d_mean_cm`, `max_cm`, `max_day`,
        `aug_mean_cm`, `sep_mean_cm`, `preliminary_days`; plus `end`, `ndays`.

    Generated by JXP and Claude
    """
    out = dict(end=str(date.date()), ndays=ndays, clim_years=list(CLIM_YEARS))
    for name, df in frames.items():
        d = df[(df.time <= date + pd.Timedelta(hours=23)) & np.isfinite(df.anom_cm)]
        tail = d.tail(ndays)
        imax = d['anom_cm'].idxmax()
        out[name] = {
            'last_day': str(d.time.iloc[-1].date()),
            f'last_{ndays}d_mean_cm': round(float(tail.anom_cm.mean()), 1),
            'max_cm': round(float(d.loc[imax, 'anom_cm']), 1),
            'max_day': str(d.loc[imax, 'time'].date()),
            'aug_mean_cm': round(float(d[d.time.dt.month == 8].anom_cm.mean()), 1),
            'sep_mean_cm': round(float(d[d.time.dt.month == 9].anom_cm.mean()), 1),
            'preliminary_days': int(d['preliminary'].sum()),
            'trend_mm_per_yr': round(float(df.attrs['trend_mm_per_yr']), 2),
        }
    return out


def fig_sealevel_public(frames, path, date, start='2026-06-01'):
    """ Public figure: daily sea level above normal since June, in cm and inches.

    Parameters
    ----------
    frames : dict, station name -> DataFrame from daily_anomaly()
    path : str, output PNG
    date : pandas.Timestamp, last day drawn
    start : str, first day drawn

    Returns
    -------
    str : `path`

    Generated by JXP and Claude
    """
    plt.rcParams.update({'font.size': 14})
    fig, ax = plt.subplots(figsize=(11, 5.6))
    ylim = (-15, 45)
    ax.axhspan(0., ylim[1], color='#FBDCE4', zorder=0)       # higher than normal
    ax.axhspan(ylim[0], 0., color='#D8E6F5', zorder=0)       # lower than normal
    styles = {'Monterey': dict(color='red', lw=3.4, zorder=4),
              'San Francisco': dict(color='0.35', lw=1.8, zorder=3)}
    for name, df in frames.items():
        d = df[(df.time >= pd.Timestamp(start)) & (df.time <= date + pd.Timedelta(hours=23))]
        ax.plot(d.time, d.anom_cm, label=name, solid_capstyle='round', **styles.get(name, {}))
    ax.axhline(0, color='k', lw=2.5, ls='--', zorder=2)
    ax.axhline(30.48, color='0.3', lw=0.8, ls=':', zorder=2)
    ax.text(pd.Timestamp(start) + pd.Timedelta(days=2), 31.5, 'one foot above normal', fontsize=11, color='0.3')
    ax.set_ylim(*ylim); ax.set_xlim(pd.Timestamp(start), date + pd.Timedelta(days=1))
    ax.set_ylabel('Sea level above normal (cm)', fontsize=15)
    axr = ax.twinx(); axr.set_ylim(ylim[0] / 2.54, ylim[1] / 2.54); axr.set_ylabel('(inches)', fontsize=15)
    ax.xaxis.set_major_formatter(mdates.DateFormatter('%-d %b'))
    ax.set_title('The El Niño sea-level pulse has reached Monterey Bay', fontsize=16, fontweight='bold', pad=22)
    fig.text(0.5, 0.905, 'Daily-mean sea level at the NOAA tide gauges, relative to the 1991–2020 seasonal normal; '
             'recent weeks are preliminary data', ha='center', fontsize=11.5, color='0.3')
    ax.legend(loc='upper left', fontsize=12.5, frameon=False)
    ax.grid(axis='y', lw=0.3, alpha=0.6)
    fig.tight_layout()
    fig.savefig(path, dpi=160); plt.close(fig)
    return path


def main():
    """ Draw the figure and write its JSON sidecar. Generated by JXP and Claude """
    ap = argparse.ArgumentParser()
    ap.add_argument('--date', default='2026-10-10', help='report date (YYYY-MM-DD): last day used')
    args = ap.parse_args()
    date = pd.Timestamp(args.date)
    os.makedirs(FIG_DIR, exist_ok=True)
    frames = {name: daily_anomaly(st) for st, name in STATIONS.items()}
    png = os.path.join(FIG_DIR, f'newsletter_fig3_sealevel_{date:%b%Y}.png')
    fig_sealevel_public(frames, png, date)
    stats = summarize(frames, date)
    with open(os.path.splitext(png)[0] + '.json', 'w') as fh:
        json.dump(stats, fh, indent=2)
    print('wrote', png)
    print(json.dumps(stats, indent=2))


if __name__ == '__main__':
    main()
