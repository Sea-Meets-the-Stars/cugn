""" Is Monterey Bay's sea surface now the most anomalously warm in the satellite record?

Verifies the surface-temperature numbers of the November 2026 newsletter before
they are quoted (the report's stats.json puts the Monterey Bay box at about
+5.9 degC for the week ending 16 Nov 2026 and the marine heatwave at "Severe").

Three checks:

  * rank: the Monterey Bay box-mean OISST anomaly (same box, 1991-2020 Hobday
    climatology and heatwave detection as report Fig. 9) is ranked against every
    day, and every `ndays`-day running mean, since 1991; the highest value of
    each earlier year is listed, and the days in each heatwave category are
    counted before and after the start of the current event;
  * data vintage: how many of the last days are NCEI *preliminary* OISST;
  * an independent thermometer: NDBC buoy 46042 (Monterey, 36.785 N 122.396 W,
    inside the box) water temperature for the last ~45 days, daily means beside
    the OISST box mean for the same days.  The buoy is not used anywhere else
    in the newsletter, so agreement means the satellite product is not the
    source of the anomaly.  A buoy that does not answer is reported, not fatal.

Usage (ocean14):
    python reports/El_Nino_2026/scripts/check_sst_record.py [--end 2026-11-16]

Writes `reports/El_Nino_2026/figs/sst_record_check_<YYYY-MM>.json`.

Generated by JXP and Claude
"""
import os
import io
import json
import argparse

import numpy as np
import pandas as pd
import requests

from cugn import oisst

# Same box as report Fig. 9 / newsletter text
MONTEREY_BOX = dict(lat=(36.3, 37.0), lon=(-122.6, -121.8))
NDBC_URL = 'https://www.ndbc.noaa.gov/data/realtime2/{station}.txt'
BUOY = '46042'
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'figs')


def box_series():
    """ Daily OISST in the Monterey Bay box with the Hobday climatology and categories.

    Returns
    -------
    pandas.DataFrame : indexed by day; columns sst, clim, thresh, anom, is_mhw,
        category, category_label, event (from cugn.oisst.hobday_mhw)

    Generated by JXP and Claude
    """
    ds = oisst.load(start_year=1991)
    series = oisst.box_mean(ds, MONTEREY_BOX['lat'], MONTEREY_BOX['lon'])
    return oisst.hobday_mhw(series)['daily']


def rank_record(daily, end, ndays=7):
    """ Rank the latest daily and `ndays`-day mean anomalies against the whole record.

    Parameters
    ----------
    daily : pandas.DataFrame from box_series()
    end : pandas.Timestamp, last day considered
    ndays : int, length of the running mean

    Returns
    -------
    dict : latest values, their ranks, the record before the current event, the
        yearly maxima of the top years, and category day counts

    Generated by JXP and Claude
    """
    d = daily.loc[:end]
    anom = d['anom'].dropna()
    run = anom.rolling(ndays, min_periods=ndays).mean().dropna()
    # the current heatwave event starts where the last unbroken MHW run begins
    ev = d['event'].iloc[-1]
    ev_start = d.index[d['event'] == ev][0] if ev >= 0 else d.index[-1]
    before = anom.loc[:ev_start - pd.Timedelta('1D')]
    run_before = run.loc[:ev_start - pd.Timedelta('1D')]
    # highest daily anomaly of each year, top six years
    ymax = anom.groupby(anom.index.year).agg(['max', 'idxmax']).sort_values('max', ascending=False).head(6)
    cats_before = d.loc[:ev_start - pd.Timedelta('1D'), 'category'].value_counts().to_dict()
    cats_event = d.loc[ev_start:, 'category'].value_counts().to_dict()
    return {
        'first_day': str(anom.index[0].date()), 'last_day': str(anom.index[-1].date()), 'n_days': int(anom.size),
        'event_start': str(ev_start.date()),
        'last_daily_anom': round(float(anom.iloc[-1]), 2),
        'last_daily_sst': round(float(d['sst'].iloc[-1]), 2),
        'last_daily_clim': round(float(d['clim'].iloc[-1]), 2),
        'event_max_daily_anom': round(float(anom.loc[ev_start:].max()), 2),
        'event_max_day': str(anom.loc[ev_start:].idxmax().date()),
        'event_max_sst': round(float(d.loc[anom.loc[ev_start:].idxmax(), 'sst']), 2),
        'rank_of_event_max_daily': int((anom > anom.loc[ev_start:].max()).sum() + 1),
        'record_daily_before_event': round(float(before.max()), 2),
        'record_daily_before_event_day': str(before.idxmax().date()),
        f'last_{ndays}d_mean_anom': round(float(run.iloc[-1]), 2),
        f'rank_of_last_{ndays}d_mean': int((run > run.iloc[-1]).sum() + 1),
        f'record_{ndays}d_before_event': round(float(run_before.max()), 2),
        f'record_{ndays}d_before_event_end': str(run_before.idxmax().date()),
        'days_above_previous_daily_record': int((anom.loc[ev_start:] > before.max()).sum()),
        'top_years_daily_max': [[int(y), round(float(r['max']), 2), str(pd.Timestamp(r['idxmax']).date())]
                                for y, r in ymax.iterrows()],
        'category_days_before_event': {int(k): int(v) for k, v in sorted(cats_before.items())},
        'category_days_this_event': {int(k): int(v) for k, v in sorted(cats_event.items())},
        'absolute_sst_record_before_event': round(float(d.loc[:ev_start - pd.Timedelta('1D'), 'sst'].max()), 2),
        'absolute_sst_record_before_event_day': str(d.loc[:ev_start - pd.Timedelta('1D'), 'sst'].idxmax().date()),
    }


def preliminary_days(end):
    """ Count the days of the current year's OISST file flagged preliminary, up to `end`.

    Parameters
    ----------
    end : pandas.Timestamp

    Returns
    -------
    int or None : number of preliminary days (None if the file carries no flag)

    Generated by JXP and Claude
    """
    ds = oisst.load(start_year=end.year)
    for name in ('preliminary', 'is_preliminary'):
        if name in ds:
            return int(ds[name].sel(time=slice(None, end)).values.astype(bool).sum())
    return None


def buoy_daily(station=BUOY):
    """ Daily-mean water temperature from an NDBC buoy's real-time file (~45 days).

    Parameters
    ----------
    station : str, NDBC station id

    Returns
    -------
    pandas.Series : daily-mean WTMP (deg C) indexed by day (UTC); days with fewer
        than 12 reports are dropped

    Generated by JXP and Claude
    """
    r = requests.get(NDBC_URL.format(station=station), timeout=60,
                     headers={'User-Agent': 'cugn-newsletter-check'})
    r.raise_for_status()
    # two header lines (names, units), both starting with '#'; 'MM' marks missing
    lines = r.text.splitlines()
    names = lines[0].lstrip('#').split()
    df = pd.read_csv(io.StringIO('\n'.join(lines[2:])), sep=r'\s+', names=names, na_values=['MM'])
    t = pd.to_datetime(dict(year=df['YY'], month=df['MM'], day=df['DD'], hour=df['hh'], minute=df['mm']))
    w = pd.Series(df['WTMP'].to_numpy(dtype=float), index=t).dropna()
    g = w.groupby(w.index.normalize())
    return g.mean()[g.count() >= 12].sort_index()


def main():
    """ Run the checks, print them and write the JSON. Generated by JXP and Claude """
    ap = argparse.ArgumentParser()
    ap.add_argument('--end', default=None, help='last day (YYYY-MM-DD); default: last day in the archive')
    ap.add_argument('--ndays', type=int, default=7)
    args = ap.parse_args()

    daily = box_series()
    end = pd.Timestamp(args.end) if args.end else daily['sst'].dropna().index[-1]
    out = dict(box=MONTEREY_BOX, ndays=args.ndays, oisst=rank_record(daily, end, args.ndays))
    out['oisst']['preliminary_days_this_year'] = preliminary_days(end)

    # Independent check: the buoy against the box mean on the same days
    try:
        b = buoy_daily()
        both = pd.DataFrame({'buoy': b, 'oisst': daily['sst'], 'clim': daily['clim']}).dropna().loc[:end]
        both['buoy_anom'] = both['buoy'] - both['clim']     # buoy minus the OISST climatology of the box
        last = both.tail(args.ndays)
        out['buoy'] = {
            'station': BUOY, 'n_days': int(len(both)),
            'first_day': str(both.index[0].date()), 'last_day': str(both.index[-1].date()),
            'mean_buoy_minus_oisst': round(float((both['buoy'] - both['oisst']).mean()), 2),
            'rms_buoy_minus_oisst': round(float(np.sqrt(((both['buoy'] - both['oisst']) ** 2).mean())), 2),
            f'last_{args.ndays}d_buoy_sst': round(float(last['buoy'].mean()), 2),
            f'last_{args.ndays}d_oisst_sst': round(float(last['oisst'].mean()), 2),
            f'last_{args.ndays}d_buoy_anom_vs_oisst_clim': round(float(last['buoy_anom'].mean()), 2),
            'max_buoy_daily_sst': round(float(both['buoy'].max()), 2),
            'max_buoy_day': str(both['buoy'].idxmax().date()),
        }
        print(both.round(2).tail(21).to_string())
    except Exception as exc:   # the buoy is a cross-check, not an input
        out['buoy'] = {'station': BUOY, 'error': f'{exc.__class__.__name__}: {exc}'}

    path = os.path.join(OUT_DIR, f'sst_record_check_{end:%Y-%m}.json')
    with open(path, 'w') as fh:
        json.dump(out, fh, indent=2)
    print(json.dumps(out, indent=2))
    print('wrote', os.path.normpath(path))


if __name__ == '__main__':
    main()
