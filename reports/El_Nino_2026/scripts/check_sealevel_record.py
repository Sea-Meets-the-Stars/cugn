""" Is October 2026 the highest monthly sea level on record at Monterey (and San Francisco)?

Verifies the claim made in the November 2026 data update (Q&A 3 of
`prompts/elnino_nov2026_prompts.md`) before it goes into the newsletter.

For each station the monthly mean sea level (CO-OPS `monthly_mean`, MSL
datum) is turned into an anomaly exactly as the newsletter does
(`cugn.indices.sea_level_anomaly`: 1991-2020 monthly climatology, linear trend
fit over the full record), then October 2026 is ranked against every month.
Robustness checks:

  * no detrending (MSL minus the monthly climatology only).  This answers
    "highest water ever measured" rather than "largest departure from the
    trend", and favours recent months by the ~2 mm/yr sea-level rise;
  * a different climatology (1983-2012);
  * San Francisco over its full record (1897-) rather than the 1991- copy on
    disk.  The long record is cached separately
    (`$OS_CCS/SeaLevel/record_check/`) so the newsletter's SF file, and its
    trend fit, are left untouched;
  * the top months of the big El Nino winters (1982-83, 1997-98, 2015-16).

Also reports whether the October 2026 value is verified (the CO-OPS
`monthly_mean` product only uses verified data; the hourly file's preliminary
flags tell when verified data end).

Usage (ocean14):
    python reports/El_Nino_2026/scripts/check_sealevel_record.py [--month 2026-10]

Writes `reports/El_Nino_2026/figs/sealevel_record_check_<YYYY-MM>.json`.

Generated by JXP and Claude
"""
import os
import json
import argparse

import numpy as np
import pandas as pd

from cugn import indices

# Stations: CO-OPS id -> (name, first year of the full record to check)
STATIONS = {'9413450': ('Monterey', 1973),
            '9414290': ('San Francisco', 1897)}
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'figs')
CACHE_DIR = os.path.join(indices.SEALEVEL_DIR, 'record_check')
EL_NINO_WINTERS = {'1982-83': ('1982-07', '1983-06'),
                   '1997-98': ('1997-07', '1998-06'),
                   '2015-16': ('2015-07', '2016-06')}


def fetch_full_monthly(station, first_year):
    """ Full-record monthly MSL for a station, cached outside the main files.

    Parameters
    ----------
    station : str
        CO-OPS station id.
    first_year : int
        First year to request.

    Returns
    -------
    pandas.DataFrame with `time` (15th of month), `msl` (m), `inferred` (0/1).

    Generated by JXP and Claude
    """
    os.makedirs(CACHE_DIR, exist_ok=True)
    path = os.path.join(CACHE_DIR, f'{station}_monthly_mean_full.csv')
    if not os.path.exists(path):
        frames = []
        # <=10-year chunks, as in cugn.indices.download_tide_gauge
        t0 = pd.Timestamp(f'{first_year}-01-01')
        end = pd.Timestamp.now('UTC').tz_localize(None)
        while t0 <= end:
            t1 = min(t0 + pd.DateOffset(years=10) - pd.Timedelta(days=1), end)
            text = indices._coops_request(dict(product='monthly_mean', station=station,
                                               begin_date=t0.strftime('%Y%m%d'),
                                               end_date=t1.strftime('%Y%m%d')))
            frames.append(indices._coops_csv_to_frame(text))
            t0 = t1 + pd.Timedelta(days=1)
        df = pd.concat([f for f in frames if len(f)], ignore_index=True)
        df['time'] = pd.to_datetime(dict(year=df['Year'], month=df['Month'], day=15))
        df.drop_duplicates('time').sort_values('time').to_csv(path, index=False)
    df = pd.read_csv(path, parse_dates=['time'])
    return pd.DataFrame({'time': df['time'],
                         'msl': pd.to_numeric(df['MSL'], errors='coerce'),
                         'inferred': df.get('Inferred', 0)}).dropna(subset=['msl'])


def rank_month(anom, month):
    """ Rank of one month's anomaly among all months, with the top 5.

    Parameters
    ----------
    anom : pandas.DataFrame with `time` and `anom` (m)
    month : str, 'YYYY-MM'

    Returns
    -------
    dict with `value_cm`, `rank`, `n_months`, `margin_cm` (over the next
    highest month, negative if not first) and `top5` [(YYYY-MM, cm), ...].

    Generated by JXP and Claude
    """
    a = anom.dropna(subset=['anom']).copy()
    a['ym'] = a['time'].dt.strftime('%Y-%m')
    a = a.sort_values('anom', ascending=False).reset_index(drop=True)
    row = a[a.ym == month]
    if row.empty:
        return dict(value_cm=None, rank=None, n_months=len(a))
    val = float(row['anom'].iloc[0])
    others = a[a.ym != month]['anom']
    return dict(value_cm=round(100 * val, 1),
                rank=int(row.index[0]) + 1,
                n_months=int(len(a)),
                margin_cm=round(100 * (val - float(others.max())), 1),
                top5=[(r.ym, round(100 * r.anom, 1)) for r in a.head(5).itertuples()])


def winter_peaks(anom):
    """ Highest monthly anomaly of each big El Nino winter.

    Parameters
    ----------
    anom : pandas.DataFrame with `time` and `anom` (m)

    Returns
    -------
    dict : winter -> (YYYY-MM, cm) or None if no data.

    Generated by JXP and Claude
    """
    out = {}
    for name, (t0, t1) in EL_NINO_WINTERS.items():
        sub = anom[(anom.time >= t0) & (anom.time <= t1 + '-28')].dropna(subset=['anom'])
        out[name] = (None if sub.empty else
                     (sub.loc[sub.anom.idxmax(), 'time'].strftime('%Y-%m'),
                      round(100 * float(sub.anom.max()), 1)))
    return out


def main():
    """ Run the checks and write the JSON summary. Generated by JXP and Claude """
    ap = argparse.ArgumentParser()
    ap.add_argument('--month', default='2026-10', help='month to test, YYYY-MM')
    args = ap.parse_args()
    result = dict(month=args.month)

    for sid, (name, first_year) in STATIONS.items():
        res = {}
        # 1. The record exactly as the newsletter sees it (file on disk).
        disk = indices.load_sea_level(sid)
        res['newsletter_record'] = dict(first=disk.time.min().strftime('%Y-%m'),
                                        **rank_month(indices.sea_level_anomaly(disk), args.month))
        # 2. Full record from CO-OPS, cached separately.
        full = fetch_full_monthly(sid, first_year)
        res['full_record_first'] = full.time.min().strftime('%Y-%m')
        res['full_record_months'] = int(len(full))
        # Verified?  CO-OPS flags months filled by inference.
        row = full[full.time.dt.strftime('%Y-%m') == args.month]
        res['month_inferred'] = None if row.empty else int(row['inferred'].iloc[0])
        a_def = indices.sea_level_anomaly(full[['time', 'msl']])
        res['full_detrended_1991_2020'] = rank_month(a_def, args.month)
        res['full_trend_mm_per_yr'] = round(a_def.attrs['trend_mm_per_yr'], 2)
        res['full_not_detrended_1991_2020'] = rank_month(
            indices.sea_level_anomaly(full[['time', 'msl']], detrend=False), args.month)
        res['full_detrended_1983_2012'] = rank_month(
            indices.sea_level_anomaly(full[['time', 'msl']], clim_years=(1983, 2012)), args.month)
        res['el_nino_winter_peaks_cm'] = winter_peaks(a_def)
        # Is there a big gap that could hide an old record?
        yrs = full.time.dt.year.value_counts()
        res['years_with_lt_9_months'] = sorted(int(y) for y in yrs[yrs < 9].index
                                               if y < pd.Timestamp(args.month).year)
        result[name] = res

    # Verified-data check from the hourly file (preliminary flag).
    for sid, (name, _) in STATIONS.items():
        hr = pd.read_csv(os.path.join(indices.SEALEVEL_DIR, f'{sid}_hourly_MSL_2026.csv'),
                         parse_dates=['time'])
        prelim = hr[hr.preliminary == 1]
        result[name]['hourly_first_preliminary'] = (None if prelim.empty else
                                                    str(prelim.time.min()))

    path = os.path.join(OUT_DIR, f'sealevel_record_check_{args.month}.json')
    with open(path, 'w') as fh:
        json.dump(result, fh, indent=2)
    print(json.dumps(result, indent=2))
    print('wrote', os.path.abspath(path))


if __name__ == '__main__':
    main()
