""" Figures for the mean-flow-removal analysis (Direction 1).

Compares the baseline structure functions against those computed after removing
a fitted survey-scale mean flow (affine and quadratic), for each experiment.

Generated by JXP and Claude.
"""

import os
import sys

import numpy as np
from matplotlib import pyplot as plt
import matplotlib.gridspec as gridspec

sys.path.append(os.path.abspath("."))

import mean_flow
import struct_defs

# Output location for the new-analysis figures
FIG_DIR = os.path.abspath("../Figures_new")

datasets = ['Calypso2019', 'Calypso2022', 'ARCTERX-2023']
focus_dataset = 'Calypso2022'


def _panel(ax, r, goodN, series, ylabel, title=None):
    """Plot a set of (label, y, yerr, style) series versus separation.

    Args:
        ax: Matplotlib axis.
        r (np.ndarray): Bin-mean separations [km].
        goodN (np.ndarray): Boolean mask of well-sampled bins.
        series (list): Tuples (label, y, yerr_or_None, color, marker).
        ylabel (str): Y-axis label.
        title (str): Optional axis title.

    Generated by JXP and Claude.
    """
    for label, y, yerr, color, marker in series:
        if yerr is not None:
            ax.errorbar(r[goodN], y[goodN], yerr=yerr[goodN], color=color,
                        fmt=marker, capsize=4, markersize=6, label=label,
                        alpha=0.9)
        else:
            ax.plot(r[goodN], y[goodN], marker, color=color, markersize=6,
                    label=label, alpha=0.9)
    ax.axhline(0., color='0.4', linestyle='--', linewidth=1)
    ax.set_xlabel('Separation r [km]')
    ax.set_ylabel(ylabel)
    if title:
        ax.set_title(title)
    ax.grid(which='major', linewidth=0.7, alpha=0.5)
    ax.legend(fontsize=10, loc='best')


def fig_one_dataset(res, outfile:str):
    """Two-panel S1(r) and S3(r) comparison for one experiment.

    Args:
        res (dict): Output of mean_flow.run_mean_flow().
        outfile (str): Path to save the PNG.

    Generated by JXP and Claude.
    """
    r = res['r']
    goodN = res['goodN']
    base = res['baseline']

    fig = plt.figure(figsize=(13, 5.5))
    gs = gridspec.GridSpec(1, 2)

    # --- S1(r) ---
    ax1 = plt.subplot(gs[0])
    s1 = [('baseline $S_1$', base['S1'], base['err_S1'], 'k', 'o')]
    colors = {1: 'tab:blue', 2: 'tab:green'}
    for order in res['removed']:
        rm = res['removed'][order]
        oname = {1: 'affine', 2: 'quadratic'}[order]
        s1.append((f'{oname}-removed $S_1$', rm['S1'], rm['err_S1'],
                   colors[order], 's'))
    _panel(ax1, r, goodN, s1, r'$S_1 = \langle\delta u_L\rangle$  [m/s]',
           title=f"{res['dataset']}: first-order (mean) increment")

    # --- S3(r) ---
    ax3 = plt.subplot(gs[1])
    s3 = [
        ('baseline raw $S_3$', base['S3raw'], base['err_S3'], 'k', 'x'),
        ('centered $S_{3,c}$ (paper)', base['S3corr'], base['err_S3'],
         'tab:red', 'o'),
    ]
    for order in res['removed']:
        rm = res['removed'][order]
        oname = {1: 'affine', 2: 'quadratic'}[order]
        s3.append((f'{oname}-removed raw $S_3$', rm['S3raw'], rm['err_S3'],
                   colors[order], 's'))
    _panel(ax3, r, goodN, s3, r'$S_3$  [m$^3$/s$^3$]',
           title=f"{res['dataset']}: third-order structure function")

    plt.tight_layout()
    plt.savefig(outfile, dpi=200)
    plt.close(fig)
    print(f"Saved: {outfile}")


def print_diagnostics(res):
    """Print the fitted-flow diagnostics and S3 comparison for one experiment.

    Args:
        res (dict): Output of mean_flow.run_mean_flow().

    Generated by JXP and Claude.
    """
    print(f"\n===== {res['dataset']} (iz={res['iz']}) =====")
    goodN = res['goodN']
    base = res['baseline']
    print(f"  good bins (N>minN): {goodN.sum()}")
    print(f"  baseline S1 max |.| over good bins: "
          f"{np.nanmax(np.abs(base['S1'][goodN])):.4e} m/s")
    for order in res['removed']:
        rm = res['removed'][order]
        fit = rm['fit']
        print(f"  --- order {order} flow fit ---")
        print(f"    R^2(u)={fit['R2_u']:.3f}  R^2(v)={fit['R2_v']:.3f}  "
              f"ngood={fit['ngood']}")
        if fit['gradient'] is not None:
            g = fit['gradient']
            print(f"    divergence={g['divergence']:+.3e} /s  "
                  f"vorticity={g['vorticity']:+.3e} /s  "
                  f"strain={g['strain']:.3e} /s")
        print(f"    S1 max |.| after removal: "
              f"{np.nanmax(np.abs(rm['S1'][goodN])):.4e} m/s")
        # How well does removal agree with the algebraic centering?
        diff = rm['S3raw'][goodN] - base['S3corr'][goodN]
        print(f"    median |removed S3raw - centered S3|: "
              f"{np.nanmedian(np.abs(diff)):.3e}  "
              f"(typical centered |S3|: "
              f"{np.nanmedian(np.abs(base['S3corr'][goodN])):.3e})")


def main(orders=(1, 2), iz:int=5, nboot:int=1000):
    """Run the mean-flow analysis for all experiments and make figures.

    Args:
        orders (tuple): Flow-field polynomial orders to remove.
        iz (int): Depth index.
        nboot (int): Bootstrap realizations.

    Generated by JXP and Claude.
    """
    os.makedirs(FIG_DIR, exist_ok=True)
    all_res = {}
    for dataset in datasets:
        res = mean_flow.run_mean_flow(dataset, iz=iz, orders=orders,
                                      btype='lin', max_time=struct_defs.max_time,
                                      minN=struct_defs.minN, nboot=nboot)
        all_res[dataset] = res
        print_diagnostics(res)
        outfile = os.path.join(
            FIG_DIR, f'fig_meanflow_{dataset}_z{(iz+1)*10}.png')
        fig_one_dataset(res, outfile)
    return all_res


if __name__ == '__main__':
    main()
