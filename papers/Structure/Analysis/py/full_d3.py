""" Full and transverse structure functions (Direction 2).

The paper reports only the longitudinal third moment
S3 = <duL^3> (= D_LLL).  The 2D energy/enstrophy-cascade literature
(Lindborg 1999; Xie & Buhler 2019; Balwada 2022; Gutierrez 2025) works with the
*full* third-order structure function
    D3(r) = <duL (duL^2 + duT^2)> = D_LLL + D_LTT ,
whose sign and slope carry the spectral kinetic-energy flux, and the enstrophy
branch (D3 ~ r^3) that the longitudinal-only moment cannot show.

This module computes, from the same glider pairs used in the paper:
  - second order:  D_LL = <duL^2>, D_TT = <duT^2>,
  - third order:   D_LLL = <duL^3>, D_LTT = <duL duT^2>,
                   D_TTT = <duT^3>, and the full D3 = D_LLL + D_LTT,
and tests the 2D isotropy / incompressibility relation linking D_TT to D_LL.

Generated by JXP and Claude.
"""

import os
import sys

import numpy as np

sys.path.append(os.path.abspath("."))

import sf_utils


def _binned_centered_thirds(gp, duL, duT, rbins, nboot):
    """Per-bin *centered* third moments, formed from fluctuations.

    In each separation bin the mean increments <duL>, <duT> are subtracted
    (u' = duL - <duL>, w' = duT - <duT>) before forming the third moments, which
    removes the homogeneity (S1) bias exactly.  Returns the centered
    longitudinal, cross, transverse, and full third-order structure functions
    with bootstrap errors.

    Args:
        gp (ProfilerPairs): Pair object providing gp.r [km].
        duL (np.ndarray): Per-pair longitudinal increment.
        duT (np.ndarray): Per-pair transverse increment.
        rbins (np.ndarray): Bin edges [km].
        nboot (int): Bootstrap realizations.

    Returns:
        dict: For each of 'D_LLL_c', 'D_LTT_c', 'D_TTT_c', 'D3_c', a mean array
            ('..._m') and bootstrap error ('..._e').

    Generated by JXP and Claude.
    """
    r = gp.r
    keys = ['D_LLL_c', 'D_LTT_c', 'D_TTT_c', 'D3_c']
    means = {k: [] for k in keys}
    errs = {k: [] for k in keys}
    for ss in range(rbins.size - 1):
        in_r = np.where((r > rbins[ss]) & (r <= rbins[ss + 1]))[0]
        if in_r.size == 0:
            for k in keys:
                means[k].append(np.nan); errs[k].append(np.nan)
            continue
        L = duL[in_r]; T = duT[in_r]

        def _thirds(Lp, Tp):
            # Center within the (sub)sample, then form third moments
            up = Lp - np.nanmean(Lp)
            wp = Tp - np.nanmean(Tp)
            d_lll = np.nanmean(up ** 3)
            d_ltt = np.nanmean(up * wp ** 2)
            d_ttt = np.nanmean(wp ** 3)
            return d_lll, d_ltt, d_ttt, d_lll + d_ltt

        vals = _thirds(L, T)
        for k, val in zip(keys, vals):
            means[k].append(val)
        # Bootstrap
        idx = np.random.choice(in_r.size, size=(nboot, in_r.size), replace=True)
        boot = np.array([_thirds(L[i], T[i]) for i in idx])
        for j, k in enumerate(keys):
            errs[k].append(np.nanstd(boot[:, j]))
    out = {}
    for k in keys:
        out[k + '_m'] = np.array(means[k])
        out[k + '_e'] = np.array(errs[k])
    return out


def compute_components(dataset:str, iz:int=5, btype:str='lin',
                       max_time:float=10., minN:int=100, nboot:int=1000):
    """Compute all 2nd/3rd-order longitudinal & transverse SF components.

    Builds the glider pairs once, forms duL and duT via calc_delta, then bins
    every moment of interest on the same pairs.

    Args:
        dataset (str): Experiment name.
        iz (int): Depth index (default 5 -> 60 m).
        btype (str): Binning type ('lin' or 'log').
        max_time (float): Max pair time separation [hr].
        minN (int): Minimum pairs per bin for the good mask.
        nboot (int): Bootstrap realizations.

    Returns:
        dict: 'dataset', 'r', 'goodN', and each component with '_m'/'_e' mean
            and error: D_LL, D_TT, D_LLL, D_LTT, D_TTT, D3 (full), plus the
            centered D_LLL and the mean increments S1L, S1T.

    Generated by JXP and Claude.
    """
    # calc_delta (inside build_pairs) computes both duL and duT at depth iz
    gp, rbins = sf_utils.build_pairs(dataset, iz=iz, variables='duLduLduL',
                                     max_time=max_time, btype=btype)
    duL = gp.duL
    duT = gp.duT

    # Per-pair moment quantities
    quantities = {
        'S1L': duL,                     # <duL>
        'S1T': duT,                     # <duT>
        'D_LL': duL ** 2,               # <duL^2>
        'D_TT': duT ** 2,               # <duT^2>
        'D_LLL': duL ** 3,              # <duL^3>  (longitudinal 3rd, = paper S3)
        'D_LTT': duL * duT ** 2,        # <duL duT^2>
        'D_TTT': duT ** 3,              # <duT^3>
        'D3': duL * (duL ** 2 + duT ** 2),  # full 3rd = D_LLL + D_LTT
    }

    out = dict(dataset=dataset, iz=iz)
    for key, vals in quantities.items():
        b = sf_utils.binned_bootstrap(vals, gp.r, rbins, nboot=nboot)
        out[key + '_m'] = b['mean']
        out[key + '_e'] = b['err']
    out['r'] = b['r']
    out['N'] = b['N']
    out['goodN'] = b['N'] > minN

    # Centered longitudinal 3rd moment (paper's algebraic correction)
    S1 = out['S1L_m']
    S2 = out['D_LL_m']
    out['D_LLL_corr_m'] = out['D_LLL_m'] - 3. * S1 * S2 + 2. * S1 ** 3

    # Properly centered full/transverse third moments (subtract per-bin means
    # of both duL and duT before cubing).  D_LLL_c here should match the
    # algebraic D_LLL_corr above -- a useful internal cross-check.
    cen = _binned_centered_thirds(gp, duL, duT, rbins, nboot)
    out.update(cen)
    return out


def isotropy_prediction(r, D_LL, goodN=None, deg:int=4):
    """Predict D_TT from D_LL under 2D isotropy + incompressibility.

    For a homogeneous, isotropic, incompressible field the transverse and
    longitudinal 2nd-order structure functions are linked through the
    correlation-function relation g = f + r f'/(d-1).  In terms of the
    structure functions (d = 2) this gives
        D_TT(r) = d/dr [ r D_LL(r) ] = D_LL(r) + r dD_LL/dr .

    The derivative is evaluated from a smooth polynomial fit to D_LL(r) so the
    prediction is not dominated by bin-to-bin scatter.

    Args:
        r (np.ndarray): Bin-mean separations [km].
        D_LL (np.ndarray): Longitudinal 2nd-order SF at those separations.
        goodN (np.ndarray): Optional boolean mask of well-sampled bins used for
            the fit (defaults to all finite points).
        deg (int): Polynomial degree for the smoothing fit.

    Returns:
        np.ndarray: Predicted transverse 2nd-order SF (same units as D_LL).

    Generated by JXP and Claude.
    """
    ok = np.isfinite(r) & np.isfinite(D_LL)
    if goodN is not None:
        ok &= goodN
    # Smooth polynomial fit to D_LL(r), then differentiate analytically
    coef = np.polyfit(r[ok], D_LL[ok], deg)
    p = np.poly1d(coef)
    dp = p.deriv()
    pred = np.full_like(r, np.nan, dtype=float)
    pred[ok] = p(r[ok]) + r[ok] * dp(r[ok])
    return pred


def run_all(datasets=('Calypso2019', 'Calypso2022', 'ARCTERX-2023'),
            iz:int=5, nboot:int=1000):
    """Compute SF components for all experiments.

    Args:
        datasets (tuple): Experiment names.
        iz (int): Depth index.
        nboot (int): Bootstrap realizations.

    Returns:
        dict: Keyed by dataset -> compute_components() output.

    Generated by JXP and Claude.
    """
    return {ds: compute_components(ds, iz=iz, nboot=nboot) for ds in datasets}
