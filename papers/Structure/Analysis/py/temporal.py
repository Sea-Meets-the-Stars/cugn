""" Temporal evolution of the structure functions within a survey (Direction 6).

The survey-mean flow (and hence the S1 bias) may drift over a multi-week
campaign.  We split each experiment into consecutive time windows, recompute the
structure functions in each, and ask: does S1 vary through the campaign, and
does any shorter, cleaner sub-window recover the velocity cascade (or a stronger
scalar cascade) better than the full survey?

Generated by JXP and Claude.
"""

import os
import sys

import numpy as np

sys.path.append(os.path.abspath("."))

from profiler import profilerpairs

import glider_io
import data_utils


def _window_subset(profilers, t0, t1):
    """Return copies of profilers restricted to profiles in [t0, t1).

    Args:
        profilers (list): ProfilerData objects.
        t0 (float): Window start time [s].
        t1 (float): Window end time [s].

    Returns:
        list: Subsetted profilers with >=2 profiles in the window.

    Generated by JXP and Claude.
    """
    out = []
    for p in profilers:
        in_win = np.where((p.time >= t0) & (p.time < t1))[0]
        if in_win.size >= 2:
            # profile_subset is non-destructive (returns a new object), so
            # subsetting one window no longer corrupts the shared profilers.
            out.append(p.profile_subset(in_win, init=False))
    return out


def evolve(dataset, iz=5, nwin=4, max_time=10., btype='lin', minN=50,
           nboot=500):
    """Recompute S1, centered S3, and the scalar mixed-moment per time window.

    Args:
        dataset (str): Experiment name.
        iz (int): Depth index.
        nwin (int): Number of equal-duration time windows.
        max_time (float): Max pair time separation [hr].
        btype (str): Binning type.
        minN (int): Minimum pairs per bin for the good mask (relaxed since
            windows have fewer pairs).
        nboot (int): Bootstrap realizations.

    Returns:
        dict: per-window arrays of center-time [days from start], npairs,
            S1_max, n_S3_2sig, chi_T_slope, ngood.

    Generated by JXP and Claude.
    """
    profilers = glider_io.load_dataset(dataset)
    rbins = data_utils.rbinning(btype, dataset)
    allt = np.concatenate([p.time for p in profilers])
    allt = allt[np.isfinite(allt)]
    tmin = np.nanmin(allt)
    # Split on time *quantiles* so each window holds ~equal profiles (the
    # profile times are front-loaded, so uniform absolute-time bins would put
    # nearly all data in the first window).
    edges = np.quantile(allt, np.linspace(0., 1., nwin + 1))
    edges[-1] += 1.0  # make the last edge inclusive of the final profile

    rows = dict(tcen=[], npairs=[], S1_max=[], n_S3_2sig=[], chi_T=[], ngood=[])
    for iw in range(nwin):
        sub = _window_subset(profilers, edges[iw], edges[iw + 1])
        # Need at least two distinct gliders in the window
        if len({int(p.missid) for p in sub}) < 2:
            continue
        gp = profilerpairs.ProfilerPairs(
            sub, max_time=max_time, avoid_same_glider=True,
            remove_nans=True, debug=False, randomize=False)
        if gp.npairs < minN:
            continue
        gp.calc_delta(iz, 'duLdTdT', skip_velocity=False)
        gp.calc_Sn('duLduLduL')
        Sn = gp.calc_Sn_vs_r(rbins, nboot=nboot)
        gp.calc_corr_Sn(Sn)
        N = np.array(Sn['config']['N'])
        g = N > minN
        if g.sum() == 0:
            continue
        S1 = np.array(Sn['S1_duL'])
        z = np.array(Sn['S3corr_duLduLduL']) / np.array(Sn['err_S3_duLduLduL'])

        # Scalar mixed-moment slope in this window
        r = gp.r
        rr, mix, mixe = [], [], []
        for ss in range(rbins.size - 1):
            in_r = np.where((r > rbins[ss]) & (r <= rbins[ss + 1]))[0]
            if in_r.size < 3:
                rr.append(np.nan); mix.append(np.nan); mixe.append(np.nan); continue
            uL = gp.duL[in_r]; dT = gp.dT[in_r]
            up = uL - np.nanmean(uL); tp = dT - np.nanmean(dT)
            rr.append(np.nanmean(r[in_r]))
            mix.append(np.nanmean(up * tp ** 2))
            bs = np.random.choice(in_r.size, size=(200, in_r.size), replace=True)
            ub = uL[bs] - np.nanmean(uL[bs], axis=1, keepdims=True)
            tb = dT[bs] - np.nanmean(dT[bs], axis=1, keepdims=True)
            mixe.append(np.nanstd(np.nanmean(ub * tb ** 2, axis=1)))
        rr = np.array(rr); mix = np.array(mix); mixe = np.array(mixe)
        gm = np.isfinite(mix) & np.isfinite(mixe) & (mixe > 0) & (N > minN)
        if gm.sum() >= 2:
            rm = rr[gm] * 1e3; w = 1.0 / mixe[gm] ** 2
            slope = np.sum(w * rm * mix[gm]) / np.sum(w * rm ** 2)
        else:
            slope = np.nan

        rows['tcen'].append((0.5 * (edges[iw] + edges[iw + 1]) - tmin) / 86400.)
        rows['npairs'].append(gp.npairs)
        rows['S1_max'].append(np.nanmax(np.abs(S1[g])))
        rows['n_S3_2sig'].append(int(np.sum(np.abs(z[g]) > 2)))
        rows['chi_T'].append(slope)
        rows['ngood'].append(int(g.sum()))

    for k in rows:
        rows[k] = np.array(rows[k])
    rows['dataset'] = dataset
    rows['nwin'] = nwin
    return rows


def run_all(datasets=('Calypso2019', 'Calypso2022', 'ARCTERX-2023'),
            nwin=4, nboot=500):
    """Temporal-evolution analysis for all experiments.

    Args:
        datasets (tuple): Experiment names.
        nwin (int): Number of time windows.
        nboot (int): Bootstrap realizations.

    Returns:
        dict: dataset -> evolve() output.

    Generated by JXP and Claude.
    """
    return {ds: evolve(ds, nwin=nwin, nboot=nboot) for ds in datasets}
