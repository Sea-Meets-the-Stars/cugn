""" Intermittency and higher-order statistics of duL (Direction 3).

Even where the signed third moment is null (no detectable energy flux), a
turbulent velocity field leaves a clear statistical fingerprint: the
probability density of the velocity increment develops fat, non-Gaussian tails
at small separations, so the flatness (kurtosis) exceeds the Gaussian value of 3
and grows toward small r.  Higher-order longitudinal structure functions
S_p(r) = <|delta u_L|^p> then scale with anomalous (intermittency) exponents.

This module measures, from the glider pairs:
  - the (centered) skewness and flatness of delta u_L versus separation,
  - the PDFs of the normalized increment at several separations,
  - the absolute structure functions S_p(r) for p = 1..6 and the
    extended-self-similarity (ESS) exponents zeta_p / zeta_3.

Generated by JXP and Claude.
"""

import os
import sys

import numpy as np

sys.path.append(os.path.abspath("."))

import sf_utils


def moments_vs_r(dataset, iz=5, max_time=10., btype='lin', minN=100,
                 pmax=6, nboot=1000):
    """Centered higher-order moments, skewness, flatness, and |duL|^p vs r.

    For each separation bin, subtract the bin-mean increment (fluctuation
    u' = duL - <duL>) and compute the centered moments, the skewness
    <u'^3>/<u'^2>^{3/2}, the flatness <u'^4>/<u'^2>^2, and the absolute moments
    S_p = <|u'|^p> for p = 1..pmax (used for ESS).  Bootstrap errors on skewness
    and flatness.

    Args:
        dataset (str): Experiment name.
        iz (int): Depth index.
        max_time (float): Max pair time separation [hr].
        btype (str): Binning type.
        minN (int): Minimum pairs per bin for the good mask.
        pmax (int): Highest absolute-moment order.
        nboot (int): Bootstrap realizations.

    Returns:
        dict: r, goodN, N, skew, skew_err, flat, flat_err, Sp (dict p->array),
            and the raw duL and separation for PDF plotting.

    Generated by JXP and Claude.
    """
    gp, rbins = sf_utils.build_pairs(dataset, iz=iz, variables='duLduLduL',
                                     max_time=max_time, btype=btype)
    duL = gp.duL
    r = gp.r

    nb = rbins.size - 1
    skew = np.full(nb, np.nan); skew_err = np.full(nb, np.nan)
    flat = np.full(nb, np.nan); flat_err = np.full(nb, np.nan)
    rr = np.full(nb, np.nan); N = np.zeros(nb, dtype=int)
    Sp = {p: np.full(nb, np.nan) for p in range(1, pmax + 1)}

    for ss in range(nb):
        in_r = np.where((r > rbins[ss]) & (r <= rbins[ss + 1]))[0]
        N[ss] = in_r.size
        if in_r.size < 3:
            continue
        rr[ss] = np.nanmean(r[in_r])
        x = duL[in_r]
        xp = x - np.nanmean(x)            # centered fluctuation
        m2 = np.nanmean(xp ** 2)
        skew[ss] = np.nanmean(xp ** 3) / m2 ** 1.5
        flat[ss] = np.nanmean(xp ** 4) / m2 ** 2
        for p in range(1, pmax + 1):
            Sp[p][ss] = np.nanmean(np.abs(xp) ** p)
        # Bootstrap skew/flatness
        idx = np.random.choice(in_r.size, size=(nboot, in_r.size), replace=True)
        xb = xp[idx]
        m2b = np.nanmean(xb ** 2, axis=1)
        sk = np.nanmean(xb ** 3, axis=1) / m2b ** 1.5
        fl = np.nanmean(xb ** 4, axis=1) / m2b ** 2
        skew_err[ss] = np.nanstd(sk)
        flat_err[ss] = np.nanstd(fl)

    return dict(dataset=dataset, r=rr, goodN=N > minN, N=N, skew=skew,
                skew_err=skew_err, flat=flat, flat_err=flat_err, Sp=Sp,
                duL=duL, rsep=r, rbins=rbins, pmax=pmax)


def ess_exponents(res):
    """Extended-self-similarity exponents zeta_p / zeta_3 from S_p vs S_3.

    ESS (Benzi et al. 1993) posits S_p(r) ~ S_3(r)^{zeta_p/zeta_3} over a wider
    range than the direct S_p(r) ~ r^{zeta_p} scaling.  We fit
    log S_p vs log S_3 over the good bins.

    Args:
        res (dict): Output of moments_vs_r().

    Returns:
        dict: p -> (zeta_p/zeta_3) slope, plus the K41 (non-intermittent)
            reference p/3.

    Generated by JXP and Claude.
    """
    g = res['goodN']
    S3 = res['Sp'][3][g]
    out = {}
    for p in range(1, res['pmax'] + 1):
        Sp = res['Sp'][p][g]
        ok = np.isfinite(Sp) & np.isfinite(S3) & (Sp > 0) & (S3 > 0)
        if ok.sum() >= 2:
            slope = np.polyfit(np.log(S3[ok]), np.log(Sp[ok]), 1)[0]
        else:
            slope = np.nan
        out[p] = slope
    out['K41'] = {p: p / 3. for p in range(1, res['pmax'] + 1)}
    return out


def run_all(datasets=('Calypso2019', 'Calypso2022', 'ARCTERX-2023'),
            iz=5, nboot=1000):
    """Compute intermittency diagnostics for all experiments.

    Args:
        datasets (tuple): Experiment names.
        iz (int): Depth index.
        nboot (int): Bootstrap realizations.

    Returns:
        dict: dataset -> moments_vs_r() output (with 'ess' added).

    Generated by JXP and Claude.
    """
    out = {}
    for ds in datasets:
        res = moments_vs_r(ds, iz=iz, nboot=nboot)
        res['ess'] = ess_exponents(res)
        out[ds] = res
    return out
