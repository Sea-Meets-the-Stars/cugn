""" Figures for the BGC (chlorophyll fluorescence) structure-function analysis.

Mirrors figs_scalar.py, restricted to the two experiments with an 'fl' field
(Calypso2019, ARCTERX-2023) -- Calypso2022, the paper's focus survey, has no
BGC sensor in its CTD file.

Generated by JXP and Claude.
"""

import os
import sys

import numpy as np
from matplotlib import pyplot as plt
import matplotlib.gridspec as gridspec

sys.path.append(os.path.abspath("."))

import bgc_sf

FIG_DIR = os.path.abspath("../Figures_new")
datasets = ['Calypso2019', 'ARCTERX-2023']


def fig_second_order(all_res, outfile:str):
    """Second-order chlorophyll SF D_FlFl vs r (log-log) per experiment.

    Args:
        all_res (dict): bgc_sf.run_all() output.
        outfile (str): Path to save the PNG.

    Generated by JXP and Claude.
    """
    fig = plt.figure(figsize=(6.5, 4.5))
    ax = plt.subplot(111)
    colors = {'Calypso2019': 'tab:blue', 'ARCTERX-2023': 'tab:green'}
    for ds in datasets:
        res = all_res[ds]
        g = res['goodN']
        ax.errorbar(res['r'][g], res['D_FlFl'][g], yerr=res['D_FlFl_e'][g],
                    fmt='o-', color=colors[ds], capsize=2, markersize=4,
                    label=ds)
    ax.set_xscale('log'); ax.set_yscale('log')
    ax.set_xlabel('Separation r [km]')
    ax.set_ylabel(r'$D_{FlFl}=\langle(\delta fl)^2\rangle$')
    ax.set_title('2nd-order chlorophyll-fluorescence SF')
    ax.grid(alpha=0.4, which='both'); ax.legend(fontsize=9)
    plt.tight_layout()
    plt.savefig(outfile, dpi=200)
    plt.close(fig)
    print(f"Saved: {outfile}")


def fig_mixed(all_res, outfile:str):
    """Mixed (Yaglom) third moment <duL dfl^2>: raw vs centered, per experiment.

    Args:
        all_res (dict): bgc_sf.run_all() output.
        outfile (str): Path to save the PNG.

    Generated by JXP and Claude.
    """
    fig = plt.figure(figsize=(11, 4.5))
    gs = gridspec.GridSpec(1, 2)
    for k, ds in enumerate(datasets):
        res = all_res[ds]
        g = res['goodN']
        r = res['r']
        ax = plt.subplot(gs[k])
        ax.plot(r[g], res['mixed_Fl_raw'][g], 'x', color='0.6',
                label='raw (biased)')
        ax.errorbar(r[g], res['mixed_Fl_cen'][g], yerr=res['mixed_Fl_cen_e'][g],
                    fmt='o', color='k', capsize=3, label='centered')
        ax.axhline(0., color='0.4', ls='--', lw=1)
        ax.set_xlabel('Separation r [km]')
        ax.set_ylabel(r'$\langle\delta u_L\,(\delta fl)^2\rangle$')
        ax.set_title(f'{ds}: mixed 3rd moment (chlorophyll fl)')
        ax.grid(alpha=0.4); ax.legend(fontsize=9)
    plt.tight_layout()
    plt.savefig(outfile, dpi=200)
    plt.close(fig)
    print(f"Saved: {outfile}")


def print_diagnostics(all_res):
    """Print significance of the centered mixed (Yaglom) moments.

    Args:
        all_res (dict): bgc_sf.run_all() output.

    Generated by JXP and Claude.
    """
    for ds in datasets:
        res = all_res[ds]
        g = res['goodN']
        z = res['mixed_Fl_cen'][g] / res['mixed_Fl_cen_e'][g]
        n2 = np.sum(np.abs(z) > 2)
        print(f"\n===== {ds} =====")
        print(f"  chlorophyll fl: centered mixed moment {n2}/{g.sum()} bins "
              f"> 2 sigma, max |z|={np.nanmax(np.abs(z)):.2f}")


def main(iz=5, nboot=1000):
    """Run the BGC (chlorophyll) direction for the two available experiments.

    Generated by JXP and Claude.
    """
    os.makedirs(FIG_DIR, exist_ok=True)
    all_res = bgc_sf.run_all(datasets=tuple(datasets), iz=iz, nboot=nboot)
    print_diagnostics(all_res)
    fig_second_order(all_res, os.path.join(FIG_DIR, 'fig_bgc_D2_z60.png'))
    fig_mixed(all_res, os.path.join(FIG_DIR, 'fig_bgc_mixedFl_z60.png'))
    return all_res


if __name__ == '__main__':
    main()
