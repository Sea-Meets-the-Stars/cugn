""" Figures for the scalar (T/S) structure-function analysis (Direction 5).

Generated by JXP and Claude.
"""

import os
import sys

import numpy as np
from matplotlib import pyplot as plt
import matplotlib.gridspec as gridspec

sys.path.append(os.path.abspath("."))

import scalar_sf

FIG_DIR = os.path.abspath("../Figures_new")
datasets = ['Calypso2019', 'Calypso2022', 'ARCTERX-2023']
scalar_units = {'S': 'salinity', 'T': 'temperature [°C]'}


def fig_second_order(all_res, outfile:str):
    """Second-order scalar SFs D_SS and D_TT vs r (log-log) per experiment.

    Args:
        all_res (dict): scalar_sf.run_all() output.
        outfile (str): Path to save the PNG.

    Generated by JXP and Claude.
    """
    fig = plt.figure(figsize=(11, 4.5))
    gs = gridspec.GridSpec(1, 2)
    colors = {'Calypso2019': 'tab:blue', 'Calypso2022': 'tab:red',
              'ARCTERX-2023': 'tab:green'}
    for col, q in enumerate(['T', 'S']):
        ax = plt.subplot(gs[col])
        for ds in datasets:
            res = all_res[ds]
            g = res['goodN']
            ax.errorbar(res['r'][g], res[f'D_{q}{q}'][g],
                        yerr=res[f'D_{q}{q}_e'][g], fmt='o-', color=colors[ds],
                        capsize=2, markersize=4, label=ds)
        ax.set_xscale('log'); ax.set_yscale('log')
        ax.set_xlabel('Separation r [km]')
        ax.set_ylabel(rf'$D_{{{q}{q}}}=\langle(\delta {q})^2\rangle$')
        ax.set_title(f'2nd-order {scalar_units[q]} SF')
        ax.grid(alpha=0.4, which='both'); ax.legend(fontsize=9)
    plt.tight_layout()
    plt.savefig(outfile, dpi=200)
    plt.close(fig)
    print(f"Saved: {outfile}")


def fig_mixed(all_res, outfile:str, q:str='T'):
    """Mixed (Yaglom) third moment <duL dq^2>: raw vs centered, per experiment.

    Args:
        all_res (dict): scalar_sf.run_all() output.
        outfile (str): Path to save the PNG.
        q (str): Scalar key, 'T' or 'S'.

    Generated by JXP and Claude.
    """
    fig = plt.figure(figsize=(15, 4.5))
    gs = gridspec.GridSpec(1, 3)
    for k, ds in enumerate(datasets):
        res = all_res[ds]
        g = res['goodN']
        r = res['r']
        ax = plt.subplot(gs[k])
        ax.plot(r[g], res[f'mixed_{q}_raw'][g], 'x', color='0.6',
                label='raw (biased)')
        ax.errorbar(r[g], res[f'mixed_{q}_cen'][g],
                    yerr=res[f'mixed_{q}_cen_e'][g], fmt='o', color='k',
                    capsize=3, label='centered')
        ax.axhline(0., color='0.4', ls='--', lw=1)
        ax.set_xlabel('Separation r [km]')
        ax.set_ylabel(rf'$\langle\delta u_L\,(\delta {q})^2\rangle$')
        ax.set_title(f'{ds}: mixed 3rd moment ({scalar_units[q]})')
        ax.grid(alpha=0.4); ax.legend(fontsize=9)
    plt.tight_layout()
    plt.savefig(outfile, dpi=200)
    plt.close(fig)
    print(f"Saved: {outfile}")


def print_diagnostics(all_res):
    """Print significance of the centered mixed (Yaglom) moments.

    Args:
        all_res (dict): scalar_sf.run_all() output.

    Generated by JXP and Claude.
    """
    for ds in datasets:
        res = all_res[ds]
        g = res['goodN']
        print(f"\n===== {ds} =====")
        for q in ['T', 'S']:
            z = res[f'mixed_{q}_cen'][g] / res[f'mixed_{q}_cen_e'][g]
            n2 = np.sum(np.abs(z) > 2)
            print(f"  {scalar_units[q]}: centered mixed moment "
                  f"{n2}/{g.sum()} bins > 2 sigma, max |z|={np.nanmax(np.abs(z)):.2f}")


def main(iz=5, nboot=1000):
    """Run Direction 5 for all experiments and make figures.

    Generated by JXP and Claude.
    """
    os.makedirs(FIG_DIR, exist_ok=True)
    all_res = scalar_sf.run_all(datasets=tuple(datasets), iz=iz, nboot=nboot)
    print_diagnostics(all_res)
    fig_second_order(all_res, os.path.join(FIG_DIR, 'fig_scalar_D2_z60.png'))
    fig_mixed(all_res, os.path.join(FIG_DIR, 'fig_scalar_mixedT_z60.png'), 'T')
    fig_mixed(all_res, os.path.join(FIG_DIR, 'fig_scalar_mixedS_z60.png'), 'S')
    return all_res


if __name__ == '__main__':
    main()
