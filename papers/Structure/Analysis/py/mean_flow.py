""" Mean-flow (survey-scale shear) removal as a competing estimator for the
third-order structure function.

Motivation
----------
Homogeneous, isotropic turbulence requires the first-order structure function
S1 = <duL> = 0.  A finite glider survey instead sees a survey-scale mean flow,
so S1 != 0, and this biases the raw third moment S3 through the 3*S1*S2 term.
The paper removes this algebraically via the *centered* moment
    S3corr = S3 - 3*S1*S2 + 2*S1**3 .

Here we test an alternative, physically explicit estimator: fit a smooth,
large-scale velocity field u(x) to the survey (constant + linear shear, and
optionally quadratic), *subtract it from the profile velocities*, and then
recompute the structure functions from the residual velocities.

A key identity motivates this: for a velocity difference duL = u1 - u0, any
spatially *constant* mean flow cancels exactly, so only the spatially varying
part (the shear) can change duL.  A pure affine field u(x) = A + G.x yields
du = G.(x1-x0) = G.r, i.e. an increment that grows linearly with separation --
exactly the kind of scale-dependent S1 seen in the surveys.  Removing that
affine part therefore attacks the S1 bias at its root, and we can ask whether
the resulting S3 agrees with the algebraic centering.

Generated by JXP and Claude.
"""

