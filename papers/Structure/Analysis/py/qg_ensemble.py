def fig_jets(zm: dict, ctx: dict, outfile: str):
    """Zonal-mean u(y) with the 5-yr region eps ratios at their y-centers.

    Args:
        zm (dict): zonal_mean_u() output.
        ctx (dict): fig8_context() output.
        outfile (str): Output PNG path.

    Generated by JXP and Claude.
    """
    fig = plt.figure(figsize=(10, 3.8))
    gs = gridspec.GridSpec(1, 2)
    ax = plt.subplot(gs[0])
    ax.plot(zm['y'], zm['U'] * 1e2, 'k-', lw=1.5, label=r'$\overline{u}(y)$')
    ax.fill_between(zm['y'], (zm['U'] - zm['Urms']) * 1e2,
                    (zm['U'] + zm['Urms']) * 1e2, color='gray', alpha=0.3,
                    label='temporal rms')
    ax.axvspan(300, 600, color='tab:orange', alpha=0.15,
               label='regions (y)')
    ax.axhline(0., color='gray', ls='--', lw=0.6)
    ax.set_xlabel('y [km]')
    ax.set_ylabel(r'zonal-mean $u$ [cm s$^{-1}$], 5-yr mean')
    ax.legend(fontsize=8)
    ax2 = ax.twinx()
    tab = ctx['table']
    ax2.scatter(tab.y0 + 50, tab.eps_ratio, c=tab.x0, cmap='viridis',
                marker='s', s=30, zorder=5)
    ax2.set_ylabel(r'region $\epsilon_c/\epsilon_{\rm full}$ (5 yr; squares)')

    ax = plt.subplot(gs[1])
    im = ax.imshow(zm['U_xt'] * 1e2, origin='lower', extent=[0, 1000, 0, 1000],
                   cmap='RdBu_r', vmin=-np.abs(zm['U_xt']).max() * 1e2,
                   vmax=np.abs(zm['U_xt']).max() * 1e2)
    for x0, y0 in itertools.product(REGION_X0, REGION_Y0):
        clr = 'k' if (x0, y0) != FIG8_REGION else 'magenta'
        ax.add_patch(plt.Rectangle((x0, y0), 100, 100, fill=False,
                                   edgecolor=clr, lw=1.2))
    plt.colorbar(im, ax=ax, label=r'5-yr mean $u$ [cm s$^{-1}$]')
    ax.set_xlabel('x [km]')
    ax.set_ylabel('y [km]')
    plt.tight_layout()
    plt.savefig(outfile, dpi=300)
    plt.close(fig)
    print(f'Saved: {outfile}')


def fig_ensemble(df, curves, ref, outfile: str, ndays: int = 100):
    """Spaghetti + percentile envelopes of raw and centered S3 (r < 80 km).

    Args:
        df (pandas.DataFrame): build_ensemble() table.
        curves (dict): build_ensemble() curves.
        ref (dict): 5-yr full-domain reference.
        outfile (str): Output PNG path.
        ndays (int): Window length (for the title).

    Generated by JXP and Claude.
    """
    r = curves['r']
    fig = plt.figure(figsize=(10, 3.8))
    gs = gridspec.GridSpec(1, 2)
    for ii, (key, clr, lbl) in enumerate(
            [('S3', 'tab:blue', r'raw $S_3$'),
             ('S3c', 'tab:red', r'centered $S_3^{c}$')]):
        ax = plt.subplot(gs[ii])
        # Individual realizations
        for cc in curves[key]:
            ax.plot(r, cc * 1e3, '-', color=clr, lw=0.5, alpha=0.25)
        # 16-84 and median
        p16, p50, p84 = np.percentile(curves[key], [16, 50, 84], axis=0)
        ax.fill_between(r, p16 * 1e3, p84 * 1e3, color=clr, alpha=0.25,
                        label='16-84%')
        ax.plot(r, p50 * 1e3, '-', color=clr, lw=2, label='median')
        # Full-domain truth
        ax.plot(r, ref['S3c'] * 1e3, 'k-', lw=2, label='full domain (5 yr)')
        ax.axhline(0., color='gray', ls='--', lw=0.8)
        ax.set_xlim(r.min(), r.max())
        ax.set_xlabel(r'$r$ [km]')
        ax.set_ylabel(lbl + r'  $[10^{-3}\,{\rm m^3\,s^{-3}}]$')
        ax.set_title(f'{len(df)} realizations: 9 regions x {ndays}-d windows',
                     fontsize=9)
        ax.legend(fontsize=8, loc='upper left')
    plt.tight_layout()
    plt.savefig(outfile, dpi=300)
    plt.close(fig)
    print(f'Saved: {outfile}')


def fig_negfrac(curves, scan: pandas.DataFrame, outfile: str):
    """Negative-fraction diagnostics.

    Left: fraction of 100-d realizations with S3<0 and S3c<0 per r-bin.
    Right: P(eps_c<0) and P(eps_c < -2 sigma) vs averaging window length.

    Args:
        curves (dict): build_ensemble() curves (100-d windows).
        scan (pandas.DataFrame): scan_windows() output.
        outfile (str): Output PNG path.

    Generated by JXP and Claude.
    """
    nf = negfrac_vs_r(curves)
    fig = plt.figure(figsize=(10, 3.8))
    gs = gridspec.GridSpec(1, 2)
    ax = plt.subplot(gs[0])
    ax.plot(nf['r'], nf['f_raw'], 'o-', color='tab:blue', label=r'raw $S_3$')
    ax.plot(nf['r'], nf['f_c'], 's-', color='tab:red',
            label=r'centered $S_3^c$')
    ax.axhline(0.5, color='gray', ls=':', lw=0.8)
    ax.set_ylim(0, 1)
    ax.set_xlabel(r'$r$ [km]')
    ax.set_ylabel('fraction negative (100-d windows)')
    ax.legend(fontsize=8)

    ax = plt.subplot(gs[1])
    ax.semilogx(scan.ndays, scan.f_eps_raw_neg, 'o-', color='tab:blue',
                label=r'$\epsilon_{\rm raw}<0$')
    ax.semilogx(scan.ndays, scan.f_eps_c_neg, 's-', color='tab:red',
                label=r'$\epsilon_{c}<0$')
    ax.semilogx(scan.ndays, scan.f_eps_c_sig_neg, 's--', color='darkred',
                label=r'$\epsilon_{c}<-2\sigma$')
    ax.semilogx(scan.ndays, scan.f_full_win_neg, 'k^-',
                label='full domain, same window')
    ax.set_ylim(-0.02, 0.6)
    ax.set_xlabel('averaging window [days]')
    ax.set_ylabel('fraction of realizations')
    ax.legend(fontsize=8)
    plt.tight_layout()
    plt.savefig(outfile, dpi=300)
    plt.close(fig)
    print(f'Saved: {outfile}')


def fig_eps_scatter(df, ref, outfile: str):
    """Region eps_c vs the time-matched full-domain eps, plus a histogram.

    Args:
        df (pandas.DataFrame): build_ensemble() table (100-d windows).
        ref (dict): 5-yr full-domain reference.
        outfile (str): Output PNG path.

    Generated by JXP and Claude.
    """
    fig = plt.figure(figsize=(10, 3.8))
    gs = gridspec.GridSpec(1, 2)
    ax = plt.subplot(gs[0])
    is8 = (df.x0 == FIG8_REGION[0]) & (df.y0 == FIG8_REGION[1])
    ax.errorbar(df.eps_full_win[~is8] * 1e10, df.eps_c[~is8] * 1e10,
                yerr=df.eps_c_err[~is8] * 1e10, fmt='o', ms=3, color='gray',
                alpha=0.6, lw=0.6, label='other regions')
    ax.errorbar(df.eps_full_win[is8] * 1e10, df.eps_c[is8] * 1e10,
                yerr=df.eps_c_err[is8] * 1e10, fmt='o', ms=4,
                color='tab:red', lw=0.8, label='Fig. 8 region (x300,y400)')
    lim = np.nanmax(np.abs(df.eps_c)) * 1e10 * 1.1
    ax.plot([-lim, lim], [-lim, lim], 'k:', lw=0.8)
    ax.axhline(0., color='gray', lw=0.6)
    ax.axvline(0., color='gray', lw=0.6)
    ax.set_xlim(0, np.nanmax(df.eps_full_win) * 1e10 * 1.3)
    ax.set_xlabel(r'full domain $\epsilon$, same window $[10^{-10}$ m$^2$s$^{-3}]$')
    ax.set_ylabel(r'100-km region $\epsilon_c$ $[10^{-10}$ m$^2$s$^{-3}]$')
    ax.legend(fontsize=8)

    ax = plt.subplot(gs[1])
    ax.hist(df.eps_c * 1e10, bins=30, color='tab:red', alpha=0.6,
            label=r'$\epsilon_c$ (centered)')
    ax.hist(df.eps_raw * 1e10, bins=30, histtype='step', color='tab:blue',
            label=r'$\epsilon_{\rm raw}$')
    ax.axvline(ref['eps'] * 1e10, color='k', lw=2, label='full domain (5 yr)')
    ax.axvline(0., color='gray', ls='--')
    ax.set_xlabel(r'$\epsilon$ $[10^{-10}$ m$^2$s$^{-3}]$')
    ax.set_ylabel('N')
    ax.legend(fontsize=8)
    plt.tight_layout()
    plt.savefig(outfile, dpi=300)
    plt.close(fig)
    print(f'Saved: {outfile}')


def fig_fig8_context(ctx: dict, df100, curves100, outfile: str):
    """Figure 8 in context.

    Left: 5-yr centered S3 of all nine regions vs the full domain (Figure 8
    region highlighted). Right: the 18 100-d windows of the Figure 8 region.

    Args:
        ctx (dict): fig8_context() output.
        df100 (pandas.DataFrame): 100-d ensemble table.
        curves100 (dict): 100-d ensemble curves.
        outfile (str): Output PNG path.

    Generated by JXP and Claude.
    """
    r = ctx['curves']['r']
    ref = ctx['ref']
    tab = ctx['table']
    fig = plt.figure(figsize=(10, 3.8))
    gs = gridspec.GridSpec(1, 2)
    ax = plt.subplot(gs[0])
    for ii, row in tab.iterrows():
        if row.is_fig8:
            ax.plot(r, ctx['curves']['S3c'][ii] * 1e3, 'o-', color='tab:red',
                    ms=3, lw=1.5, label='Fig. 8 region (x300,y400)', zorder=5)
        else:
            ax.plot(r, ctx['curves']['S3c'][ii] * 1e3, '-', color='tab:blue',
                    lw=0.8, alpha=0.6,
                    label='other regions' if ii == 0 else None)
    ax.plot(r, ref['S3c'] * 1e3, 'k-', lw=2, label='full domain')
    ax.axhline(0., color='gray', ls='--', lw=0.8)
    ax.set_xlabel(r'$r$ [km]')
    ax.set_ylabel(r'$S_3^c$ (5-yr) $[10^{-3}\,{\rm m^3\,s^{-3}}]$')
    ax.legend(fontsize=8, loc='upper left')

    ax = plt.subplot(gs[1])
    is8 = ((df100.x0 == FIG8_REGION[0]) & (df100.y0 == FIG8_REGION[1])).values
    for cc in curves100['S3c'][is8]:
        ax.plot(r, cc * 1e3, '-', color='tab:red', lw=0.7, alpha=0.6)
    ax.plot(r, ctx['curves']['S3c'][tab.index[tab.is_fig8][0]] * 1e3, 'o-',
            color='darkred', ms=3, lw=1.5, label='5-yr mean')
    ax.plot(r, ref['S3c'] * 1e3, 'k-', lw=2, label='full domain')
    ax.axhline(0., color='gray', ls='--', lw=0.8)
    ax.set_xlabel(r'$r$ [km]')
    ax.set_ylabel(r'$S_3^c$ (100-d) $[10^{-3}\,{\rm m^3\,s^{-3}}]$')
    ax.set_title('Fig. 8 region: 18 independent 100-d windows', fontsize=9)
    ax.legend(fontsize=8, loc='upper left')
    plt.tight_layout()
    plt.savefig(outfile, dpi=300)
    plt.close(fig)
    print(f'Saved: {outfile}')


