def main():
    """Run the full ensemble analysis, write tables and figures, print a summary.

    Generated by JXP and Claude.
    """
    os.makedirs(OUTPUTS_DIR, exist_ok=True)
    os.makedirs(FIG_DIR, exist_ok=True)

    # Load everything once
    regions = [load_region(x0, y0)
               for x0, y0 in itertools.product(REGION_X0, REGION_Y0)]
    full = load_full()

    # --- 1. The 100-d ensemble (the fig_qg_all_duL3 configuration)
    df100, curves100, ref = build_ensemble(100, regions=regions, full=full)
    df100.to_csv(os.path.join(OUTPUTS_DIR, 'qg_ensemble_100d.csv'),
                 index=False)
    s100 = summarize(df100, ref)
    print('\n=== 100-d windows, 9 regions, r in (5, 80) km ===')
    for k, v in s100.items():
        print(f'  {k:28s} {v:.4g}')
    nf = negfrac_vs_r(curves100)
    print('\n  r [km]   f(S3<0)  f(S3c<0)')
    for rr, a, b in zip(nf['r'], nf['f_raw'], nf['f_c']):
        print(f'  {rr:6.1f}   {a:6.3f}   {b:6.3f}')

    # --- 2. Variance decomposition (region vs epoch)
    vd = variance_decomposition(df100)
    print('\n=== Variance decomposition of eps_c (100 d) ===')
    for k, v in vd.items():
        print(f'  {k:28s} {v:.4g}')

    # --- 3. Window-length scan
    scan = scan_windows(regions=regions, full=full)
    scan.to_csv(os.path.join(OUTPUTS_DIR, 'qg_ensemble_window_scan.csv'),
                index=False)
    print('\n=== Window scan ===')
    cols = ['ndays', 'N', 'std_eps_c', 'median_eps_c_err', 'snr_ensemble', 'f_eps_raw_neg', 'f_eps_c_neg', 'f_eps_c_sig_neg',
            'f_eps_c_sig_pos', 'f_all_bins_neg', 'f_within_50pct_of_full',
            'f_full_win_neg']
    print(scan[cols].to_string(index=False, float_format='%.3f'))

    # --- 4. Figure 8 context
    ctx = fig8_context(regions=regions, full=full)
    ctx['table'].to_csv(os.path.join(OUTPUTS_DIR, 'qg_ensemble_5yr.csv'),
                        index=False)
    print('\n=== 5-yr, per region (Fig. 8 = x300,y400) ===')
    print(ctx['table'][['x0', 'y0', 'eps_raw_ratio', 'eps_ratio',
                        'eps_c_err', 'nrms_5yr', 'rank_nrms',
                        'frac_neg_c']].to_string(index=False,
                                                 float_format='%.3f'))
    is8 = (df100.x0 == FIG8_REGION[0]) & (df100.y0 == FIG8_REGION[1])
    d8 = df100[is8]
    print('\n=== Fig. 8 region, 100-d windows ===')
    print(d8[['iwin', 't0', 't1', 'eps_c', 'eps_c_err', 'eps_full_win',
              'frac_neg_c', 'nrms_win']].to_string(index=False,
                                                  float_format='%.3g'))
    print(f'  Fig-8 region: f(eps_c<0) = {np.mean(d8.eps_c < 0):.3f}; '
          f'f(eps_c<-2sig) = {np.mean(d8.eps_c/d8.eps_c_err < -2):.3f}')

    # Fig. 9 (time_evolution) uses the FIRST N days of the region record
    for nd in (30, 90, 180, 365):
        mom = window_moments(regions[[(g['x0'], g['y0']) for g in regions]
                                     .index(FIG8_REGION)], np.arange(nd))
        print(f'  Fig-9 x300,y400 first {nd:4d} d: '
              f'eps_c/eps_full = {fit_eflux(ref["r"], mom["S3c"])/ref["eps"]:.2f}'
              f', frac_neg = {np.mean(mom["S3c"] < 0):.2f}')

    # --- 5. Figures
    fig_ensemble(df100, curves100, ref,
                 os.path.join(FIG_DIR, 'fig_qg_ensemble_S3_100d.png'))
    fig_negfrac(curves100, scan,
                os.path.join(FIG_DIR, 'fig_qg_ensemble_negfrac.png'))
    fig_eps_scatter(df100, ref,
                    os.path.join(FIG_DIR, 'fig_qg_ensemble_eps.png'))
    fig_fig8_context(ctx, df100, curves100,
                     os.path.join(FIG_DIR, 'fig_qg_ensemble_fig8.png'))

    # --- 6. Persistent meridional structure (zonal jets?)
    zm = zonal_mean_u()
    print('\n=== Zonal-mean u (5 yr), cm/s ===')
    print(f'  domain: min {zm["U"].min()*1e2:.2f}, max {zm["U"].max()*1e2:.2f}'
          f', rms {np.sqrt(np.mean(zm["U"]**2))*1e2:.2f}')
    print(f'  time-mean |u| rms over (x,y): '
          f'{np.sqrt(np.mean(zm["U_xt"]**2))*1e2:.2f}')
    for y0 in REGION_Y0:
        sel = (zm['y'] >= y0) & (zm['y'] < y0 + 100)
        print(f'  y in [{y0},{y0+100}): <u> = {zm["U"][sel].mean()*1e2:6.2f}'
              f'  eps_ratio(5yr) mean over x = '
              f'{ctx["table"][ctx["table"].y0 == y0].eps_ratio.mean():.2f}')
    fig_jets(zm, ctx, os.path.join(FIG_DIR, 'fig_qg_ensemble_jets.png'))


# Command line execution
if __name__ == '__main__':
    main()
