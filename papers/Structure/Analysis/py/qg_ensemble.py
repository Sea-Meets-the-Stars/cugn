""" Ensemble analysis of the QG 100x100 km subregion third-order structure functions.

Treats the nine 100x100 km QG subregions (x0, y0 in {300, 400, 500} km) and
non-overlapping averaging windows (default 100 days; 18 per region over the
5-year record) as an ensemble of "survey-sized" realizations, and asks:

  1. How often is the centered (cumulant-corrected) longitudinal third moment
     S3c = S3 - 3 S1 S2 + 2 S1^3 negative for r < 80 km?
  2. Is that negativity statistically significant within a window, or noise?
  3. Is it set by the region (spatial sampling) or by the epoch (the whole
     domain's cascade fluctuating in time)?
  4. How typical is the paper's Figure 8 example (x0=300, y0=400, 5-yr mean)?

Inputs are the per-day, orientation-averaged region SF files
  Analysis/Output/SF_region_x{x0}_y{y0}_5years.nc
and the full-domain per-day SF file
  $OS_DATA/QG/SFQG_aver_pos_orien_5yearb_duL.nc
Both store ulls = <du_L>, du2 = <du_L^2>, du3 = <du_L^3> per day and r-bin.

Run:  python qg_ensemble.py   (from Analysis/py/)

Generated by JXP and Claude.
"""

# imports
import os
import itertools

import numpy as np
import pandas
import xarray

from matplotlib import pyplot as plt
import matplotlib.gridspec as gridspec

# Paths (resolved relative to this file so the module runs from anywhere)
PY_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT_DIR = os.path.join(PY_DIR, '..', 'Output')
OUTPUTS_DIR = os.path.join(PY_DIR, '..', 'Outputs')
FIG_DIR = os.path.join(PY_DIR, '..', 'Figures_new')

# The nine 100 km regions used in fig_qg_all_duL3()
REGION_X0 = (300, 400, 500)
REGION_Y0 = (300, 400, 500)

# The paper's Figure 8 example (figs_paper_structure.py, flg 9)
FIG8_REGION = (300, 400)

# Separation limits [km]; r < 80 km per JXP, r > 5 km drops the sub-grid bin
RMIN, RMAX = 5., 80.
# Fit range for the inverse-energy relation S3 = +(3/2) eps r (paper: 15-70 km)
RFIT = (15., 70.)


# #####################################################################
# I/O
# #####################################################################
def _series_from_ds(ds: xarray.Dataset, rmin: float = RMIN,
                    rmax: float = RMAX) -> dict:
    """Extract per-day S1, S2, S3 arrays from an orientation-averaged SF Dataset.

    Args:
        ds (xarray.Dataset): SF Dataset with dims (time, mid_rbins) and
            variables ulls, du2, du3 (time in seconds, mid_rbins in m).
        rmin (float): Minimum bin-center separation to keep [km] (exclusive).
        rmax (float): Maximum bin-center separation to keep [km] (exclusive).

    Returns:
        dict: 't' (days, int array, nt), 'r' (km, nr), and 'S1','S2','S3'
            arrays of shape (nt, nr) with units m/s, (m/s)^2, (m/s)^3.

    Generated by JXP and Claude.
    """
    # Bin centers in km and the r cut
    r_km = ds.mid_rbins.values * 1e-3
    keep = (r_km > rmin) & (r_km < rmax)
    # Time in integer days (files are daily)
    t_days = np.round(ds.time.values / 86400.).astype(int)
    # Pull the three raw moments (transpose to time-first just in case)
    out = dict(t=t_days, r=r_km[keep])
    for key, var in zip(['S1', 'S2', 'S3'], ['ulls', 'du2', 'du3']):
        out[key] = ds[var].transpose('time', 'mid_rbins').values[:, keep]
    return out


def load_region(x0: int, y0: int, rmin: float = RMIN,
                rmax: float = RMAX) -> dict:
    """Load the per-day SF series of one 100x100 km QG subregion.

    Args:
        x0 (int): Lower-left x of the region [km].
        y0 (int): Lower-left y of the region [km].
        rmin (float): Minimum separation kept [km].
        rmax (float): Maximum separation kept [km].

    Returns:
        dict: See _series_from_ds(); also 'x0', 'y0'.

    Generated by JXP and Claude.
    """
    region_file = os.path.join(OUTPUT_DIR,
                               f'SF_region_x{int(x0)}_y{int(y0)}_5years.nc')
    ds = xarray.load_dataset(region_file)
    out = _series_from_ds(ds, rmin=rmin, rmax=rmax)
    out['x0'], out['y0'] = x0, y0
    return out


def load_full(rmin: float = RMIN, rmax: float = RMAX) -> dict:
    """Load the per-day full-domain (1000 km) duL structure-function series.

    Args:
        rmin (float): Minimum separation kept [km].
        rmax (float): Maximum separation kept [km].

    Returns:
        dict: See _series_from_ds().

    Generated by JXP and Claude.
    """
    full_file = os.path.join(os.getenv('OS_DATA'), 'QG',
                             'SFQG_aver_pos_orien_5yearb_duL.nc')
    ds = xarray.load_dataset(full_file)
    return _series_from_ds(ds, rmin=rmin, rmax=rmax)


# #####################################################################
# Core statistics
# #####################################################################
def centered_s3(S1, S2, S3):
    """Centered (third-cumulant) longitudinal moment.

    Args:
        S1, S2, S3 (np.ndarray): Raw moments <du>, <du^2>, <du^3>.

    Returns:
        np.ndarray: S3 - 3 S1 S2 + 2 S1^3.

    Generated by JXP and Claude.
    """
    return S3 - 3. * S1 * S2 + 2. * S1**3


def window_moments(series: dict, idx: np.ndarray) -> dict:
    """Average the raw moments over a set of days and form the centered S3.

    The centering is applied to the window-mean moments (as in
    qg_uL_SF.parse_SF), i.e. it is the cumulant of the pooled sample.

    Args:
        series (dict): Output of load_region()/load_full().
        idx (np.ndarray): Integer day indices into the series.

    Returns:
        dict: 'S1','S2','S3','S3c' arrays over r.

    Generated by JXP and Claude.
    """
    S1 = series['S1'][idx].mean(axis=0)
    S2 = series['S2'][idx].mean(axis=0)
    S3 = series['S3'][idx].mean(axis=0)
    return dict(S1=S1, S2=S2, S3=S3, S3c=centered_s3(S1, S2, S3))


def fit_eflux(r_km: np.ndarray, S3: np.ndarray, rfit: tuple = RFIT) -> float:
    """Least-squares fit of S3 = +(3/2) eps r through the origin.

    Args:
        r_km (np.ndarray): Separations [km].
        S3 (np.ndarray): Third moment [(m/s)^3]; may be 2D (..., nr).
        rfit (tuple): (rmin, rmax) of the fit range [km].

    Returns:
        float or np.ndarray: eps [m^2 s^-3]; positive = inverse (upscale)
            energy cascade.

    Generated by JXP and Claude.
    """
    sel = (r_km >= rfit[0]) & (r_km <= rfit[1])
    x = 1.5 * r_km[sel] * 1e3            # (3/2) r in meters
    y = np.asarray(S3)[..., sel]
    # Through-origin LS slope: sum(x y) / sum(x^2)
    return (y * x).sum(axis=-1) / (x**2).sum()


def make_windows(nt: int, ndays: int) -> list:
    """Non-overlapping windows of ndays counted back from the end of the record.

    Mirrors fig_qg_all_duL3() (i1 = -(istep+1)*dt). Any remainder at the
    start of the record is dropped.

    Args:
        nt (int): Number of days in the series.
        ndays (int): Window length [days].

    Returns:
        list of np.ndarray: Day indices of each window, latest window first.

    Generated by JXP and Claude.
    """
    nwin = nt // ndays
    return [np.arange(nt - (k + 1) * ndays, nt - k * ndays)
            for k in range(nwin)]


def block_bootstrap_eps(series: dict, idx: np.ndarray, nboot: int = 300,
                        block: int = 10, rng=None) -> float:
    """Block-bootstrap standard error of the fitted eps from centered S3.

    Days within the window are resampled in contiguous blocks (to respect
    the ~1-2 week eddy decorrelation time); the moments are re-averaged and
    re-centered for each resample.

    Args:
        series (dict): Output of load_region().
        idx (np.ndarray): Day indices of the window.
        nboot (int): Number of bootstrap resamples.
        block (int): Block length [days].
        rng (np.random.Generator): Random generator (optional).

    Returns:
        float: Standard deviation of eps over the resamples [m^2 s^-3].

    Generated by JXP and Claude.
    """
    if rng is None:
        rng = np.random.default_rng(1234)
    n = len(idx)
    nblk = int(np.ceil(n / block))
    # Block start positions (allow any start so blocks overlap the window)
    starts = rng.integers(0, n - block + 1, size=(nboot, nblk))
    # Build the resampled day indices for every bootstrap at once
    offs = np.arange(block)
    samp = (starts[:, :, None] + offs[None, None, :]).reshape(nboot, -1)[:, :n]
    days = idx[samp]                                   # (nboot, n)
    S1 = series['S1'][days].mean(axis=1)               # (nboot, nr)
    S2 = series['S2'][days].mean(axis=1)
    S3 = series['S3'][days].mean(axis=1)
    eps = fit_eflux(series['r'], centered_s3(S1, S2, S3))
    return float(np.std(eps))


# #####################################################################
# Ensemble construction
# #####################################################################
def build_ensemble(ndays: int = 100, regions=None, full: dict = None,
                   do_boot: bool = True) -> tuple:
    """Build the region x window ensemble of subregion structure functions.

    Args:
        ndays (int): Window length [days].
        regions (list): Region series from load_region(); loaded if None.
        full (dict): Full-domain series from load_full(); loaded if None.
        do_boot (bool): If True, compute the block-bootstrap error on eps.

    Returns:
        tuple: (df, curves, ref)
            df (pandas.DataFrame): One row per (region, window) with
                x0, y0, iwin, t0, t1, eps_raw, eps_c, eps_c_err, eps_full_win,
                full_cov, frac_neg_c, frac_neg_raw, mean_S3c, all_neg_c,
                nrms_5yr, nrms_win.
            curves (dict): 'r', and arrays 'S3', 'S3c', 'S3c_full_win'
                of shape (nrow, nr) aligned with df.
            ref (dict): 5-yr full-domain reference 'r','S3','S3c','eps'.

    Generated by JXP and Claude.
    """
    if regions is None:
        regions = [load_region(x0, y0)
                   for x0, y0 in itertools.product(REGION_X0, REGION_Y0)]
    if full is None:
        full = load_full()
    r = regions[0]['r']
    assert np.allclose(full['r'], r)

    # 5-yr full-domain truth (all days of the full file)
    ref = window_moments(full, np.arange(len(full['t'])))
    ref['r'] = r
    ref['eps'] = fit_eflux(r, ref['S3c'])
    norm_5yr = np.sqrt(np.mean(ref['S3c']**2))

    # Map from model day -> full-file index (the full file is offset by
    # +36 days relative to the region files)
    full_pos = {t: i for i, t in enumerate(full['t'])}

    rng = np.random.default_rng(2026)
    rows, S3_list, S3c_list, S3cf_list = [], [], [], []
    for reg in regions:
        for iwin, idx in enumerate(make_windows(len(reg['t']), ndays)):
            mom = window_moments(reg, idx)
            # Time-matched full-domain window (only the overlapping days)
            fidx = np.array([full_pos[t] for t in reg['t'][idx]
                             if t in full_pos], dtype=int)
            cov = len(fidx) / len(idx)
            if cov > 0:
                fmom = window_moments(full, fidx)
                eps_full_win = fit_eflux(r, fmom['S3c'])
                S3cf = fmom['S3c']
                nrms_win = (np.sqrt(np.mean((mom['S3c'] - S3cf)**2))
                            / np.sqrt(np.mean(S3cf**2)))
            else:
                eps_full_win, nrms_win = np.nan, np.nan
                S3cf = np.full_like(r, np.nan)
            # Bootstrap error on eps
            eps_err = (block_bootstrap_eps(reg, idx, rng=rng)
                       if do_boot else np.nan)
            rows.append(dict(
                x0=reg['x0'], y0=reg['y0'], iwin=iwin,
                t0=int(reg['t'][idx[0]]), t1=int(reg['t'][idx[-1]]),
                eps_raw=fit_eflux(r, mom['S3']),
                eps_c=fit_eflux(r, mom['S3c']),
                eps_c_err=eps_err,
                eps_full_win=eps_full_win, full_cov=cov,
                frac_neg_c=np.mean(mom['S3c'] < 0),
                frac_neg_raw=np.mean(mom['S3'] < 0),
                mean_S3c=np.mean(mom['S3c']),
                all_neg_c=bool(np.all(mom['S3c'] < 0)),
                nrms_5yr=np.sqrt(np.mean((mom['S3c'] - ref['S3c'])**2))
                / norm_5yr,
                nrms_win=nrms_win,
            ))
            S3_list.append(mom['S3'])
            S3c_list.append(mom['S3c'])
            S3cf_list.append(S3cf)

    df = pandas.DataFrame(rows)
    curves = dict(r=r, S3=np.array(S3_list), S3c=np.array(S3c_list),
                  S3c_full_win=np.array(S3cf_list))
    return df, curves, ref


def summarize(df: pandas.DataFrame, ref: dict) -> dict:
    """Headline statistics of an ensemble table.

    Args:
        df (pandas.DataFrame): Output of build_ensemble().
        ref (dict): 5-yr full-domain reference from build_ensemble().

    Returns:
        dict: Counts and fractions (negative eps, significantly negative,
            all-bins-negative, majority-negative, raw vs centered, etc.).

    Generated by JXP and Claude.
    """
    n = len(df)
    sig = df.eps_c / df.eps_c_err
    out = dict(
        N=n,
        eps_full_5yr=ref['eps'],
        median_eps_c=float(df.eps_c.median()),
        # Realization-to-realization scatter vs the in-window bootstrap error
        std_eps_c=float(df.eps_c.std()),
        median_eps_c_err=float(df.eps_c_err.median()),
        snr_ensemble=float(ref['eps'] / df.eps_c.std()),
        # Negative at > 1 sigma of the *ensemble* scatter below zero
        f_eps_c_lt_m1sig_ens=float(np.mean(df.eps_c < -df.eps_c.std())),
        f_eps_raw_neg=float(np.mean(df.eps_raw < 0)),
        f_eps_c_neg=float(np.mean(df.eps_c < 0)),
        f_eps_c_sig_neg=float(np.mean(sig < -2)),
        f_eps_c_sig_pos=float(np.mean(sig > 2)),
        f_mean_S3c_neg=float(np.mean(df.mean_S3c < 0)),
        f_majority_bins_neg=float(np.mean(df.frac_neg_c > 0.5)),
        f_all_bins_neg=float(np.mean(df.all_neg_c)),
        f_any_bin_neg=float(np.mean(df.frac_neg_c > 0)),
        f_within_50pct_of_full=float(np.mean(
            np.abs(df.eps_c / ref['eps'] - 1) < 0.5)),
        f_nrms_lt_0p5=float(np.mean(df.nrms_5yr < 0.5)),
        f_full_win_neg=float(np.mean(df.eps_full_win < 0)),
    )
    return out


def negfrac_vs_r(curves: dict) -> dict:
    """Fraction of realizations with negative raw and centered S3 per r-bin.

    Args:
        curves (dict): Output curves of build_ensemble().

    Returns:
        dict: 'r', 'f_raw', 'f_c' arrays over r.

    Generated by JXP and Claude.
    """
    return dict(r=curves['r'],
                f_raw=np.mean(curves['S3'] < 0, axis=0),
                f_c=np.mean(curves['S3c'] < 0, axis=0))


def scan_windows(windows=(30, 60, 100, 182, 365, 912, 1825),
                 regions=None, full=None) -> pandas.DataFrame:
    """Repeat the ensemble statistics as a function of window length.

    Args:
        windows (tuple): Window lengths [days].
        regions (list): Region series (loaded if None).
        full (dict): Full-domain series (loaded if None).

    Returns:
        pandas.DataFrame: One row per window length with the summarize()
            keys plus 'ndays'.

    Generated by JXP and Claude.
    """
    if regions is None:
        regions = [load_region(x0, y0)
                   for x0, y0 in itertools.product(REGION_X0, REGION_Y0)]
    if full is None:
        full = load_full()
    rows = []
    for nd in windows:
        # Bootstrap only where it is affordable/meaningful (>= 30 d windows)
        df, _, ref = build_ensemble(nd, regions=regions, full=full,
                                    do_boot=True)
        s = summarize(df, ref)
        s['ndays'] = nd
        rows.append(s)
    return pandas.DataFrame(rows)


def variance_decomposition(df: pandas.DataFrame) -> dict:
    """Split the scatter of eps_c into epoch (time) and region parts.

    Uses a two-way (region x window) layout: the epoch component is the
    variance of the per-window mean across regions, the region component the
    variance of the per-region mean across windows. Also reports the mean
    pairwise correlation of eps_c between regions across windows, and the
    correlation of the region-mean eps_c with the time-matched full-domain eps.

    Args:
        df (pandas.DataFrame): Output of build_ensemble().

    Returns:
        dict: var_total, var_epoch, var_region, var_resid, mean_corr_regions,
            corr_regionmean_vs_full.

    Generated by JXP and Claude.
    """
    tab = df.pivot_table(index='iwin', columns=['x0', 'y0'], values='eps_c')
    a = tab.values                                     # (nwin, nreg)
    grand = a.mean()
    epoch = a.mean(axis=1) - grand                     # per-window effect
    region = a.mean(axis=0) - grand                    # per-region effect
    resid = a - grand - epoch[:, None] - region[None, :]
    # Pairwise correlations between regions across windows
    cc = np.corrcoef(a.T)
    iu = np.triu_indices_from(cc, k=1)
    # Region-mean vs time-matched full domain
    fwin = df.groupby('iwin').eps_full_win.mean().loc[tab.index].values
    ok = np.isfinite(fwin)
    return dict(var_total=float(a.var()), var_epoch=float(epoch.var()),
                var_region=float(region.var()),
                var_resid=float(resid.var()),
                mean_corr_regions=float(np.mean(cc[iu])),
                corr_regionmean_vs_full=float(
                    np.corrcoef(a.mean(axis=1)[ok], fwin[ok])[0, 1]))


def fig8_context(regions=None, full=None) -> dict:
    """Place the paper's Figure 8 example in the context of the ensemble.

    Computes, for each of the nine regions, the 5-yr (all 1825 days) centered
    S3 and its eps and normalized rms deviation from the full domain, and
    ranks the Figure 8 region among them.

    Args:
        regions (list): Region series (loaded if None).
        full (dict): Full-domain series (loaded if None).

    Returns:
        dict: 'table' (DataFrame of the 9 regions, 5-yr), 'curves'
            (S3, S3c arrays), 'ref' (full-domain reference).

    Generated by JXP and Claude.
    """
    df, curves, ref = build_ensemble(1825, regions=regions, full=full,
                                     do_boot=True)
    df['eps_ratio'] = df.eps_c / ref['eps']
    df['eps_raw_ratio'] = df.eps_raw / ref['eps']
    df['rank_nrms'] = df.nrms_5yr.rank().astype(int)
    df['is_fig8'] = (df.x0 == FIG8_REGION[0]) & (df.y0 == FIG8_REGION[1])
    return dict(table=df, curves=curves, ref=ref)


def zonal_mean_u(ndays: int = 1825, stride: int = 5) -> dict:
    """Time- and zonal-mean upper-layer u(y) over the analysis period.

    Diagnoses persistent meridional structure (e.g. beta-plane zonal jets)
    that would make fixed 100-km boxes statistically inequivalent even after
    long averaging. Uses the same day range as qg_utils.load_last_time().

    Args:
        ndays (int): Number of days (ending 2 days before the record end).
        stride (int): Use every stride-th day (to limit I/O).

    Returns:
        dict: 'y' [km], 'U' (time+zonal mean u, m/s), 'Urms' (rms over time
            of the zonal-mean u, m/s), 'U_xt' (time-mean u(y, x), m/s).

    Generated by JXP and Claude.
    """
    qg_file = os.path.join(os.getenv('OS_DATA'), 'QG',
                           'QGModelOutput20years.nc')
    qg = xarray.open_dataset(qg_file)
    # Same indexing as qg_utils.load_last_time (i1 = -2 - ndays)
    nt = qg.time.size
    tidx = np.arange(nt - 2 - ndays, nt - 2, stride)
    u = qg.u.isel(lev=0, time=tidx).load()          # (time, y, x)
    uz = u.mean('x')                                # zonal mean per time
    return dict(y=qg.y.values * 1e-3, U=uz.mean('time').values,
                Urms=uz.std('time').values,
                U_xt=u.mean('time').values)


