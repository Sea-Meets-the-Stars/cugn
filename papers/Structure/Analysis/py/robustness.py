""" Robustness / uncertainty checks (Q&A items 4 and 5).

Three checks that bear on the paper's central claim that the centered third
moment is "consistent with zero" (no bin beyond ~2 sigma):

  1. Bootstrap vs effective-DOF errors.  The paper's bootstrap resamples the
     *pairs* within a bin, which assumes pairs are independent.  They are not:
     each profile appears in many pairs, and neighbouring pairs share profiles
     and overlap in space/time.  We estimate an effective number of independent
     samples per bin from the count of *distinct profiles* contributing, and
     inflate the bootstrap error accordingly, then re-test significance.

  2. Delta-t sensitivity scan.  How does the survey-mean S1 (and hence the bias,
     and the centered S3) change as the max pair time separation is varied?

  3. Last-bin broadening.  Merge the sparsely-sampled large-r bins and re-test
     the lone ~2 sigma excursion near r ~ 63 km in Calypso 2022.

Generated by JXP and Claude.
"""

import os
import sys

import numpy as np

sys.path.append(os.path.abspath("."))

